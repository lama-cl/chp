def param_declared_type(entry: dict[str, Any], index: int) -> str:
    params = entry.get("paramDeclaredTypes")
    if isinstance(params, list) and 0 <= index < len(params):
        v = params[index]
        if isinstance(v, str):
            return v
    return ""


def type_atom_text_from_ir_atom(atom: Any) -> str:
    atom = normalize_ir(atom)
    if not isinstance(atom, dict) or ir_kind(atom) != "asType":
        return ""
    return render_type_atom(atom.get("type"))


def as_type_ir_from_text(text: str) -> Any:
    if not text:
        return None
    return {"kind": "asType", "type": {"text": text, "canonical": text}}


def seq_from_items(items: list[Any]) -> Any:
    out: Any = None
    for item in items:
        out = compose_ir(out, item)
    return normalize_ir(out)


def split_actual_path_for_wrapper(path_ir: Any, formal_type: str) -> tuple[Any, Any]:
    """Split caller-side path into prefix and callee formal-entry atom.

    For a call like ``int *`` actual to ``void *`` formal, the transfer edge
    usually carries ``int * => void *``.  The provenance view should render this
    as ``int * => f⌜void * => ...⌝f``: the caller prefix stays outside the
    wrapper, while the formal-entry type starts the wrapper body.
    """
    path_ir = normalize_ir(strip_callwrap_ir(path_ir))
    items = flatten_seq(path_ir)
    if items is None:
        formal_atom = as_type_ir_from_text(formal_type)
        return path_ir, formal_atom
    if not items:
        return None, as_type_ir_from_text(formal_type)

    last_text = type_atom_text_from_ir_atom(items[-1])
    if formal_type and last_text == formal_type:
        return seq_from_items(items[:-1]), items[-1]
    return seq_from_items(items), as_type_ir_from_text(formal_type)


def node_function_name(node: str) -> str:
    if "::" in node:
        return node.split("::", 1)[0]
    return node


def solved_param_records_by_key(entries: list[dict[str, Any]]) -> dict[str, dict[int, dict[str, Any]]]:
    out: dict[str, dict[int, dict[str, Any]]] = {}
    for entry in entries:
        key = str(entry.get("publicLookupKey") or public_lookup_key(entry))
        solved = entry.get("solvedParamSummaries")
        if not isinstance(solved, list):
            continue
        for rec in solved:
            if not isinstance(rec, dict):
                continue
            try:
                idx = int(rec.get("index"))
            except Exception:
                continue
            out.setdefault(key, {})[idx] = rec
    return out


def entry_by_public_key(entries: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    return {str(entry.get("publicLookupKey") or public_lookup_key(entry)): entry
            for entry in entries}


def render_call_site_wrapper(edge: dict[str, Any], callee_rec: dict[str, Any],
                             callee_entry: dict[str, Any] | None) -> dict[str, Any] | None:
    callee_node = str(edge.get("calleeNode") or "")
    caller_node = str(edge.get("callerNode") or "")
    if not callee_node or not caller_node:
        return None
    try:
        caller_idx = int(edge.get("callerParamIndex"))
        callee_idx = int(edge.get("calleeParamIndex"))
    except Exception:
        return None

    path_obj = edge.get("actualPathFromCallerParam") if isinstance(edge.get("actualPathFromCallerParam"), dict) else {}
    path_ir = path_obj.get("ir") if isinstance(path_obj, dict) else None
    callee_core_ir = normalize_ir(callee_rec.get("semanticCoreIr"))
    if callee_core_ir is None:
        callee_core_ir = strip_callwrap_ir(callee_rec.get("ir"))
    if callee_core_ir is None:
        return None

    formal_type = param_declared_type(callee_entry or {}, callee_idx)
    caller_prefix_ir, formal_entry_ir = split_actual_path_for_wrapper(path_ir, formal_type)
    wrapper_inner_ir = compose_ir(formal_entry_ir, callee_core_ir)
    wrapper_inner = render_ir(wrapper_inner_ir)
    callee_name = node_function_name(callee_node) or "call"
    wrapper = f"{callee_name}⌜{wrapper_inner}⌝{callee_name}"
    caller_prefix = render_ir(caller_prefix_ir)
    rendered = f"{caller_prefix} => {wrapper}" if caller_prefix else wrapper

    loc = edge.get("location") if isinstance(edge.get("location"), dict) else {}
    out: dict[str, Any] = {
        "kind": "call-site-specialized-param-provenance",
        "callerNode": caller_node,
        "calleeNode": callee_node,
        "callerParamIndex": caller_idx,
        "calleeParamIndex": callee_idx,
        "callerParam": param_node_label(caller_node, caller_idx),
        "calleeParam": param_node_label(callee_node, callee_idx),
        "calleeName": callee_name,
        "rendered": rendered,
        "callerPrefix": caller_prefix,
        "formalEntry": render_ir(formal_entry_ir),
        "calleeCore": render_ir(callee_core_ir),
        "wrapperInner": wrapper_inner,
        "wrapperRendered": wrapper,
        "actualPath": render_ir(strip_callwrap_ir(path_ir)),
        "source": "display-only-call-provenance",
        "note": "Display-only provenance view; not fed back into the SCC solver or solvedParamSummaries[*].ir.",
    }
    if loc:
        out["location"] = loc
    for field in ("edgeKey", "edgeKind", "summaryFile", "sourceFile", "tuSourceFile"):
        if edge.get(field):
            out[field] = edge.get(field)
    guard = edge.get("guard") if isinstance(edge.get("guard"), dict) else None
    if guard:
        out["guard"] = guard.get("text") or guard
    return out


def build_solved_param_call_provenance(entries: list[dict[str, Any]],
                                       transfer_edges: list[dict[str, Any]]) -> dict[str, Any]:
    """Build call-site-specialized wrapper renderings from solved param facts.

    This is a report-domain layer.  It intentionally does not change the
    wrapper-free solver/core IR stored under solvedParamSummaries[*].ir.
    """
    entries_by_key = entry_by_public_key(entries)
    solved_by_key = solved_param_records_by_key(entries)
    records: list[dict[str, Any]] = []
    seen: set[str] = set()

    for edge in transfer_edges:
        callee_key = str(edge.get("calleeNode") or "")
        if not callee_key:
            continue
        try:
            callee_idx = int(edge.get("calleeParamIndex"))
        except Exception:
            continue
        callee_rec = solved_by_key.get(callee_key, {}).get(callee_idx)
        if not callee_rec:
            continue
        rendered = render_call_site_wrapper(edge, callee_rec, entries_by_key.get(callee_key))
        if not rendered:
            continue
        dedup_key = json.dumps({
            "caller": rendered.get("callerParam"),
            "callee": rendered.get("calleeParam"),
            "rendered": rendered.get("rendered"),
            "edgeKey": rendered.get("edgeKey"),
        }, sort_keys=True, separators=(",", ":"))
        if dedup_key in seen:
            continue
        seen.add(dedup_key)
        records.append(rendered)

    records.sort(key=lambda r: (str(r.get("callerNode") or ""),
                                int(r.get("callerParamIndex") or 0),
                                str(r.get("calleeNode") or ""),
                                int(r.get("calleeParamIndex") or 0),
                                str(r.get("rendered") or "")))
    by_caller: dict[str, list[dict[str, Any]]] = defaultdict(list)
    by_callee: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for rec in records:
        by_caller[str(rec.get("callerNode") or "")].append(rec)
        by_callee[str(rec.get("calleeNode") or "")].append(rec)

    return {
        "purpose": "Display-only call-site-specialized wrapper renderings for solved parameter summaries.",
        "solverInvariant": "Wrappers are not reintroduced into solvedParamSummaries[*].ir and are not fed back into fixpoint solving.",
        "intendedUse": "Experiments such as type-preserving polymorphism checks over void* functions can compare the caller prefix with the callee wrapper body.",
        "records": records,
        "counts": {
            "records": len(records),
            "callerNodes": len([k for k, v in by_caller.items() if v]),
            "calleeNodes": len([k for k, v in by_callee.items() if v]),
        },
    }

def set_entry_status(entries: list[dict[str, Any]], idx: int, status: str) -> None:
    old = entries[idx].get("status", "unambiguous")
    if STATUS_RANK.get(status, 0) >= STATUS_RANK.get(old, 0):
        entries[idx]["status"] = status
        entries[idx]["resolution"] = RESOLUTION_FOR_STATUS.get(status, "unknown")


def all_external_like(entries: list[dict[str, Any]], idxs: list[int]) -> bool:
    return all(entries[i].get("linkage", "unknown") in EXTERNAL_LIKE_LINKAGES for i in idxs)


def all_internal(entries: list[dict[str, Any]], idxs: list[int]) -> bool:
    return all(entries[i].get("linkage", "unknown") in INTERNAL_LINKAGES for i in idxs)


def group_summary(entries: list[dict[str, Any]], idxs: list[int]) -> dict[str, Any]:
    return {
        "count": len(idxs),
        "summaryFiles": sorted({entries[i].get("summaryFile", "") for i in idxs}),
        "sourceFiles": sorted({entries[i].get("sourceFile", "") for i in idxs}),
        "locations": sorted({entries[i].get("locationKey", "") for i in idxs}),
        "linkages": sorted({entries[i].get("linkage", "unknown") for i in idxs}),
        "entries": idxs,
    }


def classify(entries: list[dict[str, Any]], *, project_kind: str) -> dict[str, Any]:
    by_lookup: dict[str, list[int]] = defaultdict(list)
    by_public: dict[str, list[int]] = defaultdict(list)
    by_name: dict[str, list[int]] = defaultdict(list)
    for i, e in enumerate(entries):
        by_lookup[e["lookupKey"]].append(i)
        by_public[e["publicLookupKey"]].append(i)
        by_name[e["qualifiedName"] or e["function"]].append(i)

    duplicate_groups: list[dict[str, Any]] = []
    ambiguity_groups: list[dict[str, Any]] = []
    problem_groups: list[dict[str, Any]] = []
    scoped_name_groups: list[dict[str, Any]] = []

    for key, idxs in sorted(by_lookup.items()):
        if len(idxs) <= 1:
            continue
        source_loc_pairs = {(entries[i].get("sourceFile", ""), entries[i].get("locationKey", "")) for i in idxs}
        source_files = {entries[i].get("sourceFile", "") for i in idxs}
        g = group_summary(entries, idxs)
        g["lookupKey"] = key

        if project_kind == "example-suite" and all_external_like(entries, idxs) and len(source_files) > 1:
            kind = "standalone-example-duplicate"
            g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                      "note": "same external name/signature occurs in multiple independent examples; not a linked-project duplicate"})
            duplicate_groups.append(g)
            ambiguity_groups.append(g)
            for i in idxs:
                set_entry_status(entries, i, kind)
            continue

        if len(source_loc_pairs) == 1:
            kind = "repeated-same-definition-summary"
            g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                      "note": "same definition appears in multiple summaries; C3 may deduplicate or prefer current TU"})
            duplicate_groups.append(g)
            for i in idxs:
                set_entry_status(entries, i, kind)
            continue

        if all_external_like(entries, idxs):
            kind = "duplicate-external-definition"
            g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                      "note": "same external name/signature has multiple distinct definitions; unsafe for C3 import"})
            duplicate_groups.append(g)
            problem_groups.append(g)
            for i in idxs:
                set_entry_status(entries, i, kind)
            continue

        kind = "duplicate-internal-definition"
        g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                  "note": "same internal lookup key has multiple distinct definitions; source identity may be insufficient"})
        duplicate_groups.append(g)
        problem_groups.append(g)
        for i in idxs:
            set_entry_status(entries, i, kind)

    for key, idxs in sorted(by_public.items()):
        if len(idxs) <= 1:
            continue
        exact_keys = sorted({entries[i]["lookupKey"] for i in idxs})
        if len(exact_keys) <= 1:
            continue
        g = group_summary(entries, idxs)
        g["publicLookupKey"] = key

        if all_internal(entries, idxs):
            kind = "internal-same-name-signature"
            g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                      "note": "multiple internal/static functions share name/signature; safe only with source/TU context"})
            scoped_name_groups.append(g)
            ambiguity_groups.append(g)
            for i in idxs:
                set_entry_status(entries, i, kind)
            continue

        linkages = {entries[i].get("linkage", "unknown") for i in idxs}
        if "unknown" in linkages:
            kind = "ambiguous-unknown-linkage"
            g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                      "note": "same name/signature appears with unknown linkage; unsafe until linkage identity is improved"})
            problem_groups.append(g)
            ambiguity_groups.append(g)
            for i in idxs:
                set_entry_status(entries, i, kind)
            continue

        kind = "mixed-linkage-name-signature"
        g.update({"kind": kind, "resolution": RESOLUTION_FOR_STATUS[kind],
                  "note": "internal/static and external functions share name/signature; C3 needs source/TU context"})
        scoped_name_groups.append(g)
        ambiguity_groups.append(g)
        for i in idxs:
            set_entry_status(entries, i, kind)

    return {
        "byLookupKey": dict(sorted(by_lookup.items())),
        "byPublicLookupKey": dict(sorted(by_public.items())),
        "byQualifiedName": dict(sorted(by_name.items())),
        "duplicateGroups": duplicate_groups,
        "ambiguityGroups": ambiguity_groups,
        "problemGroups": problem_groups,
        "scopedNameGroups": scoped_name_groups,
    }


def build_index(summary_files: list[Path], output: Path, *, project_kind: str,
                input_summary_fingerprint: str = "", build_reason: str = "") -> tuple[dict[str, Any], list[Issue]]:
    build_started = time.perf_counter()
    input_bytes = summary_input_bytes(summary_files)
    stage_started = build_started
    issues: list[Issue] = []
    root = output.parent
    entries: list[dict[str, Any]] = []
    tus: list[dict[str, Any]] = []
    summary_dependency_edges: list[dict[str, Any]] = []
    summary_param_transfer_edges: list[dict[str, Any]] = []
    return_alias_pointer_use_continuations: list[dict[str, Any]] = []
    details_by_public_key: dict[str, dict[str, Any]] = {}
    details_by_lookup_key: dict[str, dict[str, Any]] = {}
    for sf in summary_files:
        data, err = load_json(sf)
        if err:
            issues.append(Issue("error", str(sf), err))
            continue
        assert data is not None
        schema_error = validate_tu_summary_schema(data, sf)
        if schema_error:
            issues.append(Issue("error", str(sf), schema_error))
            continue
        tu = data.get("tu") if isinstance(data.get("tu"), dict) else {}
        tu_source = tu.get("sourceFile") if isinstance(tu.get("sourceFile"), str) else ""
        tu_config = tu.get("configurationId") if isinstance(tu.get("configurationId"), str) else ""
        tu_hash = tu.get("compileCommandHash") if isinstance(tu.get("compileCommandHash"), str) else ""
        details = extract_function_details(data)
        deps = extract_summary_dependency_edges(data, sf, root, tu_source,
                                                 tu_config, tu_hash, issues)
        transfers = extract_summary_param_transfer_edges(data, sf, root, tu_source,
                                                         tu_config, tu_hash, issues)
        return_alias_facts = extract_return_alias_pointer_use_continuations(
            data, sf, root, tu_source, tu_config, tu_hash, issues)
        summary_dependency_edges.extend(deps)
        summary_param_transfer_edges.extend(transfers)
        return_alias_pointer_use_continuations.extend(return_alias_facts)
        tus.append({"summaryFile": stable_relpath(sf, root), "sourceFile": tu_source,
                    "configurationId": tu_config, "compileCommandHash": tu_hash,
                    "numFunctionSummaries": len(details),
                    "numSummaryDependencyEdges": len(deps),
                    "numSummaryParamTransferEdges": len(transfers),
                    "numReturnAliasPointerUseContinuations": len(return_alias_facts)})
        if not details:
            issues.append(Issue("warning", str(sf), "no function summaries found"))
        for d in details:
            e = extract_entry(d, sf, root, tu_source, tu_config, tu_hash, issues)
            if e is not None:
                details_by_public_key[e["publicLookupKey"]] = d
                details_by_lookup_key[e["lookupKey"]] = d
                entries.append(e)

    parse_and_extract_ms = int((time.perf_counter() - stage_started) * 1000)
    stage_started = time.perf_counter()

    entries.sort(key=lambda e: (e.get("qualifiedName", ""), e.get("signatureKey", ""),
                                e.get("linkage", ""), e.get("sourceFile", ""),
                                e.get("locationKey", ""), e.get("summaryFile", "")))
    summary_dependency_edges.sort(key=lambda e: (e.get("callerNode", ""),
                                                 e.get("calleeNode", ""),
                                                 e.get("kind", ""),
                                                 e.get("summaryFile", ""),
                                                 e.get("edgeKey", "")))
    summary_param_transfer_edges.sort(key=lambda e: (e.get("callerNode", ""),
                                                     e.get("calleeNode", ""),
                                                     e.get("callerParamIndex", -1),
                                                     e.get("calleeParamIndex", -1),
                                                     e.get("summaryFile", ""),
                                                     e.get("edgeKey", "")))
    branch_family_transfer_metadata = branch_family_transfer_metadata_summary(
        summary_param_transfer_edges)
    return_alias_pointer_use_continuations.sort(
        key=lambda e: (e.get("sourceEntity", ""),
                       ((e.get("operation") or {}) if isinstance(e.get("operation"), dict) else {}).get("kind", ""),
                       e.get("summaryFile", ""),
                       e.get("factKey", "")))
    groups = classify(entries, project_kind=project_kind)
    dep_graph = dependency_graph_summary(summary_dependency_edges)
    dep_sccs = dependency_scc_summary(summary_dependency_edges)
    graph_and_scc_ms = int((time.perf_counter() - stage_started) * 1000)
    stage_started = time.perf_counter()
    solved_param_summary_stats = materialize_project_solved_param_summaries(
        entries, details_by_public_key, dep_sccs, summary_param_transfer_edges)
    num_materialized_solved_param_summaries = int(solved_param_summary_stats.get("numFunctions", 0))
    solved_param_ms = int((time.perf_counter() - stage_started) * 1000)
    stage_started = time.perf_counter()
    solved_param_summary_debug = build_solved_param_summary_debug(entries, solved_param_summary_stats)
    provenance_transfer_edges, provenance_transfer_edge_filter_stats = filter_param_transfer_edges_for_public_solver(
        entries, summary_param_transfer_edges)
    solved_param_call_provenance = build_solved_param_call_provenance(entries, provenance_transfer_edges)
    solved_return_summary_stats = materialize_project_solved_return_summaries(
        entries, details_by_public_key)
    num_materialized_solved_return_summaries = int(solved_return_summary_stats.get("numFunctions", 0))
    solved_pointer_use_stats = materialize_project_solved_pointer_use_summaries(
        entries, details_by_lookup_key, dep_sccs, summary_param_transfer_edges)
    num_materialized_solved_pointer_use_summaries = int(solved_pointer_use_stats.get("numFunctions", 0))
    return_alias_pointer_use_stats = return_alias_pointer_use_continuation_summary(
        return_alias_pointer_use_continuations)
    solved_other_ms = int((time.perf_counter() - stage_started) * 1000)
    build_metadata = {
        "builderVersion": "C6g5w1d-tagged-recursive-closure-key-materialization",
        "buildReason": build_reason or "unspecified",
        "inputSummaryFingerprint": input_summary_fingerprint,
        "inputSummaryBytes": input_bytes,
        "timingsMilliseconds": {
            "parseAndExtract": parse_and_extract_ms,
            "graphAndScc": graph_and_scc_ms,
            "solvedParam": solved_param_ms,
            "solvedOther": solved_other_ms,
            "totalBeforeWrite": int((time.perf_counter() - build_started) * 1000),
        },
    }
    return {
        "schemaName": SCHEMA_NAME,
        "schemaVersion": SCHEMA_VERSION,
        "projectKind": project_kind,
        "summaryRoot": str(root),
        "buildMetadata": build_metadata,
        "numSummaryFiles": len(summary_files),
        "numFunctions": len(entries),
        "numSummaryDependencyEdges": len(summary_dependency_edges),
        "numSummaryParamTransferEdges": len(summary_param_transfer_edges),
        "numBranchFamilyTransferEdges": int(
            branch_family_transfer_metadata.get("counts", {}).get("arms", 0)),
        "numBranchFamilies": int(
            branch_family_transfer_metadata.get("counts", {}).get("families", 0)),
        "numReturnAliasPointerUseContinuations": len(return_alias_pointer_use_continuations),
        "numMaterializedSolvedParamSummaryFunctions": num_materialized_solved_param_summaries,
        "numMaterializedSolvedReturnSummaryFunctions": num_materialized_solved_return_summaries,
        "numMaterializedSolvedPointerUseSummaryFunctions": num_materialized_solved_pointer_use_summaries,
        "solvedParamSummaryFixpoint": solved_param_summary_stats,
        "solvedReturnSummaryFixpoint": solved_return_summary_stats,
        "solvedPointerUseSummaryFixpoint": solved_pointer_use_stats,
        "solvedParamSummaryDebug": solved_param_summary_debug,
        "solvedParamCallProvenance": solved_param_call_provenance,
        "returnAliasPointerUseContinuationSummary": return_alias_pointer_use_stats,
        "projectSummaryAlgebra": solved_param_summary_stats.get("summaryAlgebra", {}),
        "translationUnits": tus,
        "functions": entries,
        "summaryDependencyEdges": summary_dependency_edges,
        "summaryParamTransferEdges": summary_param_transfer_edges,
        "branchFamilyTransferMetadata": branch_family_transfer_metadata,
        "summaryParamTransferEdgeFilter": provenance_transfer_edge_filter_stats,
        "returnAliasPointerUseContinuations": return_alias_pointer_use_continuations,
        "summaryDependencyGraph": dep_graph,
        "summaryDependencySCCs": dep_sccs,
        "lookups": {"byLookupKey": groups["byLookupKey"],
                    "byPublicLookupKey": groups["byPublicLookupKey"],
                    "byQualifiedName": groups["byQualifiedName"]},
        "statusCounts": status_counts(entries, "status"),
        "resolutionCounts": status_counts(entries, "resolution"),
        "duplicateGroups": groups["duplicateGroups"],
        "ambiguityGroups": groups["ambiguityGroups"],
        "problemGroups": groups["problemGroups"],
        "scopedNameGroups": groups["scopedNameGroups"],
        "groupCounts": {"duplicates": len(groups["duplicateGroups"]),
                        "ambiguities": len(groups["ambiguityGroups"]),
                        "problems": len(groups["problemGroups"]),
                        "scopedNameGroups": len(groups["scopedNameGroups"])},
        "issues": [asdict(i) for i in issues],
    }, issues


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Build cast-history project summary index")
    ap.add_argument("paths", nargs="*", type=Path, default=[Path("json-summaries")], help="Summary JSON files or directories")
    ap.add_argument("-o", "--output", type=Path, default=None, help="Output path; default <summary-dir>/project-summary-index.json")
    ap.add_argument("--strict", action="store_true", help="Return nonzero if warnings occur")
    ap.add_argument("--fail-on-problems", action="store_true", help="Return nonzero if hard C3 resolution problems are found")
    ap.add_argument("--project-kind", choices=["real", "example-suite"], default="real",
                    help="Use 'real' for linked projects; use 'example-suite' for independent standalone examples.")
    ap.add_argument("--build-reason", default="",
                    help="Optional C1/C2/import phase label recorded in buildMetadata.")
    ap.add_argument("--reuse-output-if-input-unchanged", type=Path, default=None,
                    help="Reuse this existing index when its inputSummaryFingerprint exactly matches the current summaries.")
    args = ap.parse_args(argv)
    paths = args.paths or [Path("json-summaries")]
    files = find_summary_files(paths)
    if not files:
        print("error: no *.cast-summary.json files found", file=sys.stderr)
        return 1
    out = args.output or default_output_path(paths)
    out.parent.mkdir(parents=True, exist_ok=True)
    fingerprint_started = time.perf_counter()
    input_fingerprint = summary_input_fingerprint(files)
    fingerprint_ms = int((time.perf_counter() - fingerprint_started) * 1000)

    if (args.reuse_output_if_input_unchanged is not None and
            reusable_index_matches(args.reuse_output_if_input_unchanged,
                                   input_fingerprint)):
        reuse_path = args.reuse_output_if_input_unchanged
        if reuse_path.resolve() != out.resolve():
            shutil.copyfile(reuse_path, out)
        print(f"reused project summary index: {out}")
        print(f"  reuse status: exact-input-fingerprint-match")
        print(f"  input fingerprint: {input_fingerprint}")
        print(f"  fingerprint-ms: {fingerprint_ms}")
        return 0

    index, issues = build_index(
        files, out, project_kind=args.project_kind,
        input_summary_fingerprint=input_fingerprint,
        build_reason=args.build_reason)
    index.setdefault("buildMetadata", {}).setdefault("timingsMilliseconds", {})[
        "inputFingerprint"] = fingerprint_ms
    write_started = time.perf_counter()
    out.write_text(json.dumps(index, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    write_ms = int((time.perf_counter() - write_started) * 1000)
    errors = [i for i in issues if i.severity == "error"]
    warnings = [i for i in issues if i.severity == "warning"]
    print(f"wrote project summary index: {out}")
    print(f"  project kind:  {args.project_kind}")
    print(f"  summary files: {len(files)}")
    print(f"  functions:     {index['numFunctions']}")
    print(f"  dep edges:     {index.get('numSummaryDependencyEdges', 0)}")
    print(f"  param xfers:   {index.get('numSummaryParamTransferEdges', 0)}")
    print(f"  branch families: {index.get('numBranchFamilies', 0)} "
          f"(arms: {index.get('numBranchFamilyTransferEdges', 0)})")
    print(f"  solved params: {index.get('numMaterializedSolvedParamSummaryFunctions', 0)} functions")
    print(f"  solved returns: {index.get('numMaterializedSolvedReturnSummaryFunctions', 0)} functions")
    print(f"  solved pointer uses: {index.get('numMaterializedSolvedPointerUseSummaryFunctions', 0)} functions")
    print(f"  duplicates:    {index['groupCounts']['duplicates']}")
    print(f"  ambiguities:   {index['groupCounts']['ambiguities']}")
    print(f"  problems:      {index['groupCounts']['problems']}")
    print(f"  scoped groups: {index['groupCounts']['scopedNameGroups']}")
    print(f"  warnings:      {len(warnings)}")
    print(f"  errors:        {len(errors)}")
    print(f"  index write-ms: {write_ms}")
    meta = index.get("buildMetadata", {})
    if isinstance(meta, dict):
        timings = meta.get("timingsMilliseconds", {})
        print(f"  input fingerprint: {meta.get('inputSummaryFingerprint', '')}")
        print(f"  build reason: {meta.get('buildReason', 'unspecified')}")
        if isinstance(timings, dict):
            print("  index build timings (ms):")
            for key in ("inputFingerprint", "parseAndExtract", "graphAndScc",
                        "solvedParam", "solvedOther", "totalBeforeWrite", "write"):
                if key in timings:
                    print(f"    {key}: {timings[key]}")
    print("  status counts:")
    for status, count in index.get("statusCounts", {}).items():
        print(f"    {status}: {count}")
    print("  resolution counts:")
    for status, count in index.get("resolutionCounts", {}).items():
        print(f"    {status}: {count}")
    dep_graph = index.get("summaryDependencyGraph", {})
    if isinstance(dep_graph, dict) and dep_graph.get("kindCounts"):
        print("  dependency graph:")
        print(f"    unique edges:  {dep_graph.get('numUniqueEdges', 0)}")
        print(f"    concrete raw:  {dep_graph.get('numConcreteEdges', 0)}")
        print(f"    symbolic raw:  {dep_graph.get('numSymbolicEdges', 0)}")
        print("  dependency edge counts:")
        for kind, count in dep_graph.get("kindCounts", {}).items():
            print(f"    {kind}: {count}")
    dep_sccs = index.get("summaryDependencySCCs", {})
    if isinstance(dep_sccs, dict):
        concrete = dep_sccs.get("concreteFunctionGraph", {})
        full = dep_sccs.get("fullGraph", {})
        if isinstance(concrete, dict) or isinstance(full, dict):
            print("  dependency SCCs:")
            if isinstance(concrete, dict):
                print(f"    concrete graph: {concrete.get('numNontrivialSCCs', 0)} nontrivial / {concrete.get('numSCCs', 0)} total")
            if isinstance(full, dict):
                print(f"    full graph:     {full.get('numNontrivialSCCs', 0)} nontrivial / {full.get('numSCCs', 0)} total")
    solved_stats = index.get("solvedParamSummaryFixpoint", {})
    if isinstance(solved_stats, dict):
        print("  solved-param fixpoint:")
        print(f"    iterations: {solved_stats.get('iterations', 0)} / {solved_stats.get('maxIterations', 0)}")
        print(f"    converged:  {solved_stats.get('converged', True)}")
        print(f"    considered: {solved_stats.get('consideredTransferEdges', 0)} transfer edges")
        print(f"    changed:    {solved_stats.get('changedTransferEdges', 0)} transfer edges")
        if "intraSCCTransferEdgesConsidered" in solved_stats:
            print(f"    intra-SCC:  {solved_stats.get('intraSCCTransferEdgesChanged', 0)} changed / {solved_stats.get('intraSCCTransferEdgesConsidered', 0)} considered")
        if "crossSCCTransferEdgesConsidered" in solved_stats:
            print(f"    cross-SCC:  {solved_stats.get('crossSCCTransferEdgesChanged', 0)} changed / {solved_stats.get('crossSCCTransferEdgesConsidered', 0)} considered")
