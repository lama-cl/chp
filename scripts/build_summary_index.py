def branch_family_transfer_metadata_summary(
    transfer_edges: list[dict[str, Any]],
) -> dict[str, Any]:
    """Summarize branch-family transport and C6g5w1d C2 consumption.

    The records originate on normal ``summaryParamTransferEdges`` emitted by
    the C++ visitor.  C6g5w1d consumes only proved recursive closure keys for
    two narrow family kinds; all other records remain diagnostic transport.
    """
    families: dict[str, dict[str, Any]] = {}
    malformed: list[dict[str, Any]] = []
    for edge in transfer_edges:
        family = edge.get("branchFamily")
        single_arm = edge.get("branchArm")
        many_arms = edge.get("branchArms")
        if family is None and single_arm is None and many_arms is None:
            continue
        if not isinstance(family, dict):
            malformed.append({
                "edgeKey": edge.get("edgeKey", ""),
                "reason": "branchFamily must be an object when branch arm metadata is present",
            })
            continue
        arms: list[dict[str, Any]] = []
        if isinstance(single_arm, dict):
            arms.append(single_arm)
        elif single_arm is not None:
            malformed.append({
                "edgeKey": edge.get("edgeKey", ""),
                "reason": "branchArm must be an object",
            })
            continue
        if isinstance(many_arms, list):
            for arm in many_arms:
                if isinstance(arm, dict):
                    arms.append(arm)
                else:
                    malformed.append({
                        "edgeKey": edge.get("edgeKey", ""),
                        "reason": "branchArms must contain only objects",
                    })
        elif many_arms is not None:
            malformed.append({
                "edgeKey": edge.get("edgeKey", ""),
                "reason": "branchArms must be an array",
            })
            continue
        if not arms:
            malformed.append({
                "edgeKey": edge.get("edgeKey", ""),
                "reason": "branchFamily requires branchArm or branchArms",
            })
            continue
        family_id = str(family.get("id") or "")
        if not family_id:
            malformed.append({
                "edgeKey": edge.get("edgeKey", ""),
                "reason": "branch-family metadata lacks family id",
            })
            continue
        rec = families.setdefault(family_id, {
            "id": family_id,
            "kind": str(family.get("kind") or "unknown"),
            "ownerNode": str(family.get("ownerNode") or edge.get("callerNode") or ""),
            "ownerParamIndex": family.get("ownerParamIndex", edge.get("callerParamIndex")),
            "origin": str(family.get("origin") or ""),
            "recursiveClosureKey": str(
                family.get("recursiveClosureKey") or family_id
            ),
            "diagnosticOnly": True,
            "consumedByTaggedRecursiveSolver": bool(
                family.get("consumedByTaggedRecursiveSolver", False)),
            "transport": "tu-summary summaryParamTransferEdges -> project-summary-index",
            "arms": [],
        })
        closure_key = str(family.get("recursiveClosureKey") or family_id)
        rec["consumedByTaggedRecursiveSolver"] = bool(
            rec.get("consumedByTaggedRecursiveSolver", False) or
            family.get("consumedByTaggedRecursiveSolver", False))
        if rec.get("recursiveClosureKey") != closure_key:
            malformed.append({
                "edgeKey": edge.get("edgeKey", ""),
                "reason": "one branch family has inconsistent recursiveClosureKey values",
            })
            continue
        for arm in arms:
            arm_id = str(arm.get("id") or "")
            if not arm_id:
                malformed.append({
                    "edgeKey": edge.get("edgeKey", ""),
                    "reason": "branch-family metadata lacks arm id",
                })
                continue
            rec["arms"].append({
                "id": arm_id,
                "kind": str(arm.get("kind") or "unknown"),
                "actualPath": str(arm.get("actualPath") or ""),
                "guardText": str(arm.get("guardText") or ""),
                "originSourceEntity": str(arm.get("originSourceEntity") or ""),
                "callSite": arm.get("callSite", edge.get("location", {})),
                "callerNode": str(edge.get("callerNode") or ""),
                "calleeNode": str(edge.get("calleeNode") or ""),
                "callerParamIndex": edge.get("callerParamIndex"),
                "calleeParamIndex": edge.get("calleeParamIndex"),
                "transferGuard": edge.get("guard"),
                "edgeKey": str(edge.get("edgeKey") or ""),
                "summaryFile": str(edge.get("summaryFile") or ""),
                "tuSourceFile": str(edge.get("tuSourceFile") or ""),
            })

    out_families: list[dict[str, Any]] = []
    for family_id in sorted(families):
        rec = families[family_id]
        seen: set[str] = set()
        arms: list[dict[str, Any]] = []
        for arm in sorted(rec["arms"], key=lambda a: (
            str(a.get("id") or ""), str(a.get("edgeKey") or ""),
            str(a.get("actualPath") or ""),
        )):
            key = json.dumps(arm, sort_keys=True, separators=(",", ":"))
            if key not in seen:
                seen.add(key)
                arms.append(arm)
        rec["arms"] = arms
        rec["memberCount"] = len(arms)
        out_families.append(rec)

    return {
        "purpose": (
            "C6g5w1d transport and consumption report. Source-defined branch-family "
            "and arm metadata survives ordinary parameter-transfer export and C2 index "
            "construction; recursiveClosureKey is consumed only by the tagged C2 "
            "recursive summary materializer for supported family kinds."
        ),
        "transportInvariant": (
            "Metadata is carried on summaryParamTransferEdges. C6g5w1d consumes "
            "recursiveClosureKey only for parallel-call-actuals and guarded-local-ptrarith "
            "inside a recursive SCC; untagged solvedParamSummaries and pointer-use facts "
            "remain on their established solver paths."
        ),
        "rehydrationContract": (
            "SummaryIndex reads ordinary summaryParamTransferEdges first and "
            "deduplicates this companion metadata as an import-side fallback. The "
            "companion is not a second solver input."
        ),
        "families": out_families,
        "counts": {
            "families": len(out_families),
            "arms": sum(len(x.get("arms", [])) for x in out_families),
            "malformedEdges": len(malformed),
        },
        "malformedEdges": malformed,
    }


def normalize_return_alias_pointer_use_continuation(fact: dict[str, Any],
                                                    summary_file: Path,
                                                    summary_root: Path,
                                                    tu_source: str,
                                                    tu_config: str,
                                                    tu_hash: str) -> dict[str, Any]:
    """Normalize a C4Q1 return-alias pointer-use continuation fact.

    These facts are reporting/indexing records.  They explain pointer-use
    payloads that were propagated through a returned alias in the final visitor
    pass; they are not yet a project-level pointer-use solver input.
    """
    out = dict(fact)
    out["summaryFile"] = stable_relpath(summary_file, summary_root)
    out["tuSourceFile"] = tu_source
    out["tuConfigurationId"] = tu_config
    out["tuCompileCommandHash"] = tu_hash

    op = out.get("operation") if isinstance(out.get("operation"), dict) else {}
    loc = op.get("location") if isinstance(op.get("location"), dict) else {}
    source_entity = str(out.get("sourceEntity") or "")
    semantic = out.get("semanticAttachPath") if isinstance(out.get("semanticAttachPath"), dict) else {}
    provenance = out.get("provenanceAttachPath") if isinstance(out.get("provenanceAttachPath"), dict) else {}
    semantic_rendered = canonical_history_key(semantic)
    provenance_rendered = canonical_history_key(provenance)
    kind = str(op.get("kind") or "")
    ptr_ty = str(op.get("pointerType") or "")
    access_ty = str(op.get("accessType") or "")
    loc_key = location_key(loc)
    out["factKey"] = "::".join([
        "return-alias-pointer-use", source_entity, semantic_rendered,
        provenance_rendered, kind, ptr_ty, access_ty, loc_key,
    ])
    return out


def extract_return_alias_pointer_use_continuations(summary: dict[str, Any],
                                                   summary_file: Path,
                                                   summary_root: Path,
                                                   tu_source: str,
                                                   tu_config: str,
                                                   tu_hash: str,
                                                   issues: list[Issue]) -> list[dict[str, Any]]:
    raw = summary.get("returnAliasPointerUseContinuations")
    if raw is None:
        return []
    if not isinstance(raw, list):
        issues.append(Issue("warning", str(summary_file),
                            "returnAliasPointerUseContinuations is not an array"))
        return []
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    for i, fact in enumerate(raw):
        if not isinstance(fact, dict):
            issues.append(Issue("warning", str(summary_file),
                                f"returnAliasPointerUseContinuations[{i}] is not an object"))
            continue
        norm = normalize_return_alias_pointer_use_continuation(
            fact, summary_file, summary_root, tu_source, tu_config, tu_hash)
        key = str(norm.get("factKey") or "")
        if key and key in seen:
            continue
        if key:
            seen.add(key)
        out.append(norm)
    return out


def return_alias_pointer_use_continuation_summary(
        facts: list[dict[str, Any]]) -> dict[str, Any]:
    by_kind: dict[str, int] = {}
    by_source: dict[str, int] = {}
    by_tu: dict[str, int] = {}
    for fact in facts:
        op = fact.get("operation") if isinstance(fact.get("operation"), dict) else {}
        kind = str(op.get("kind") or "unknown")
        source = str(fact.get("sourceEntity") or "<unknown>")
        tu = str(fact.get("tuSourceFile") or "<unknown>")
        by_kind[kind] = by_kind.get(kind, 0) + 1
        by_source[source] = by_source.get(source, 0) + 1
        by_tu[tu] = by_tu.get(tu, 0) + 1
    return {
        "numFacts": len(facts),
        "byOperationKind": dict(sorted(by_kind.items())),
        "bySourceEntity": dict(sorted(by_source.items())),
        "byTranslationUnit": dict(sorted(by_tu.items())),
        "note": "C4Q1 reporting-only facts. These explain pointer-use payloads propagated through returned aliases; they are not yet SCC-solved project-level pointer-use summaries.",
    }


