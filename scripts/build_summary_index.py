    if isinstance(ptr_stats, dict):
        print("  solved-pointer-use fixpoint:")
        print(f"    iterations: {ptr_stats.get('iterations', 0)} / {ptr_stats.get('maxIterations', 0)}")
        print(f"    converged:  {ptr_stats.get('converged', True)}")
        print(f"    considered: {ptr_stats.get('consideredTransferUses', 0)} transfer uses")
        print(f"    changed:    {ptr_stats.get('changedTransferUses', 0)} transfer uses")

    call_prov = index.get("solvedParamCallProvenance", {})
    if isinstance(call_prov, dict):
        counts = call_prov.get("counts", {}) if isinstance(call_prov.get("counts"), dict) else {}
        print(f"  solved param call provenance: {counts.get('records', 0)} records")

    solved_debug = index.get("solvedParamSummaryDebug", {})
    if isinstance(solved_debug, dict):
        counts = solved_debug.get("counts", {}) if isinstance(solved_debug.get("counts"), dict) else {}
        print("  solved-param debug:")
        print(f"    functions with solved params: {counts.get('functionsWithSolvedParams', 0)}")
        print(f"    solved param records:         {counts.get('solvedParamRecords', 0)}")
        print(f"    explained param records:      {counts.get('explainedParamRecords', 0)}")
        print(f"    recursive SCC functions:      {counts.get('recursiveSCCFunctions', 0)}")
        print(f"    downstream functions:         {counts.get('downstreamFunctions', 0)}")
        print(f"    simple SCC paths:             {counts.get('simpleSCCPathsEnumerated', 0)}")
        interp = solved_debug.get("interpretation", {})
        if isinstance(interp, dict) and interp.get("terminalVoidPointer"):
            print("    terminal void*: documented in solvedParamSummaryDebug.interpretation.terminalVoidPointer")
    if warnings:
        print("\nWarnings:")
        for issue in warnings[:50]:
            print(f"  {issue.file}: {issue.message}")
        if len(warnings) > 50:
            print(f"  ... {len(warnings) - 50} more warnings")
    if errors:
        print("\nErrors:")
        for issue in errors:
            print(f"  {issue.file}: {issue.message}")
