def obs_ir_is_nonempty(ir: Any) -> bool:
    return isinstance(ir, dict) and ir.get("kind") not in (None, "", "none")


# C6a1: report-only display order metadata.  These fields are allowed to
# influence human-readable/export ordering, but they must never affect semantic
# equality, deduplication, or fixpoint convergence.
DISPLAY_ORDER_FIELDS = {"_displayOrderKey", "_displayOrderSeq", "_displayOrderSource"}
# C6g5t: fork/arm tags and display ordering are report-only metadata.  They
# describe the local origin of parallel alternatives but are deliberately
# excluded from semantic equality, index convergence, and solver membership.
FORK_ARM_FIELDS = {"_forkId", "_armId", "_forkOrigin"}
REPORT_ONLY_IR_FIELDS = DISPLAY_ORDER_FIELDS | FORK_ARM_FIELDS


def strip_display_order_metadata(ir: Any) -> Any:
    if isinstance(ir, dict):
        return {k: strip_display_order_metadata(v)
                for k, v in ir.items()
                if k not in REPORT_ONLY_IR_FIELDS}
    if isinstance(ir, list):
        return [strip_display_order_metadata(v) for v in ir]
    return ir


def obs_ir_key(ir: Any) -> str:
    return json.dumps(strip_display_order_metadata(ir), sort_keys=True, separators=(",", ":"))


def display_order_key(ir: Any) -> tuple[int, str, int, int, int, str]:
    """Best-effort source-natural display order for report-domain arms.

    The key is intentionally ignored by obs_ir_key().  It is used only when
    printing/exporting Parallel and Join arms.  Missing order sorts after arms
    that have a source order, with textual IR as a deterministic fallback.
    """
    ir = normalize_ir(ir) if isinstance(ir, dict) and ir.get("kind") not in (None, "") else ir
    best: tuple[int, str, int, int, int, str] | None = None

    def parse_key(obj: Any) -> tuple[int, str, int, int, int, str] | None:
        if not isinstance(obj, dict):
            return None
        raw = obj.get("_displayOrderKey")
        if isinstance(raw, dict):
            file = str(raw.get("file") or "")
            try:
                line = int(raw.get("line") or 0)
            except Exception:
                line = 0
            try:
                column = int(raw.get("column") or 0)
            except Exception:
                column = 0
            try:
                seq = int(raw.get("seq") or 0)
            except Exception:
                seq = 0
            return (0, file, line, column, seq, obs_ir_key(obj))
        return None

    def visit(obj: Any) -> None:
        nonlocal best
        if isinstance(obj, dict):
            k = parse_key(obj)
            if k is not None and (best is None or k < best):
                best = k
            kind = obj.get("kind")
            if kind == "seq":
                visit(obj.get("first"))
                visit(obj.get("second"))
            elif kind == "parallel":
                for arm in obj.get("arms", []) if isinstance(obj.get("arms"), list) else []:
                    visit(arm)
            elif kind == "join":
                for alt in obj.get("alternatives", []) if isinstance(obj.get("alternatives"), list) else []:
                    if isinstance(alt, dict):
                        visit(alt.get("history"))
            elif kind == "callWrap":
                visit(obj.get("inner"))
            elif kind == "fieldRef":
                visit(obj.get("base"))
        elif isinstance(obj, list):
            for item in obj:
                visit(item)

    visit(ir)
    return best if best is not None else (1, "", 0, 0, 0, obs_ir_key(ir))


def sort_irs_for_display(arms: list[Any]) -> list[Any]:
    return sorted(arms, key=display_order_key)


def copy_display_order_metadata(src: Any, dst: Any) -> Any:
    if isinstance(src, dict) and isinstance(dst, dict):
        for k in REPORT_ONLY_IR_FIELDS:
            if k in src and k not in dst:
                dst[k] = src[k]
    return dst


def source_order_key_from_edge(edge: dict[str, Any]) -> dict[str, Any]:
    loc = edge.get("location") if isinstance(edge.get("location"), dict) else {}
    return {
        "file": str(loc.get("file") or edge.get("sourceFile") or edge.get("tuSourceFile") or ""),
        "line": int(loc.get("line") or 0),
        "column": int(loc.get("column") or 0),
        "seq": int(edge.get("_inputOrder") or edge.get("edgeOrdinal") or 0),
    }


def attach_display_order_to_ir(ir: Any, edge: dict[str, Any], *, source: str) -> Any:
    ir = normalize_ir(ir)
    if ir is None or not isinstance(ir, dict):
        return ir
    out = dict(ir)
    out["_displayOrderKey"] = source_order_key_from_edge(edge)
    out["_displayOrderSource"] = source
    return out


def attach_fork_arm_metadata(ir: Any, *, fork_id: str, arm_id: str,
                             origin: str) -> Any:
    """Annotate one report path with a stable parallel-fork witness.

    The tags are intentionally attached only after the semantic path has been
    constructed.  ``obs_ir_key`` strips them, so they cannot affect project
    membership or make repeated SCC replay look new.
    """
    ir = normalize_ir(ir)
    if ir is None or not isinstance(ir, dict) or not fork_id or not arm_id:
        return ir
    out = dict(ir)
    out["_forkId"] = fork_id
    out["_armId"] = arm_id
    out["_forkOrigin"] = origin
    return out


def fork_arm_metadata(ir: Any) -> tuple[str, str, str]:
    """Return the first report-only fork/arm tag found in an IR tree."""
    if not isinstance(ir, dict):
        return "", "", ""
    fork = str(ir.get("_forkId") or "")
    arm = str(ir.get("_armId") or "")
    origin = str(ir.get("_forkOrigin") or "")
    if fork or arm:
        return fork, arm, origin
    kind = ir_kind(ir)
    children: list[Any] = []
    if kind == "seq":
        children = [ir.get("first"), ir.get("second")]
    elif kind == "parallel":
        children = list(ir.get("arms") or [])
    elif kind == "join":
        children = [x.get("history") for x in ir.get("alternatives", [])
                    if isinstance(x, dict)]
    elif kind == "callWrap":
        children = [ir.get("inner")]
    elif kind == "fieldRef":
        children = [ir.get("base")]
    for child in children:
        f, a, o = fork_arm_metadata(child)
        if f or a:
            return f, a, o
    return "", "", ""


def ir_kind(ir: Any) -> str:
    return str(ir.get("kind", "")) if isinstance(ir, dict) else ""


def normalize_ir(ir: Any) -> Any:
    if not obs_ir_is_nonempty(ir):
        return None
    if not isinstance(ir, dict):
        return None
    kind = ir_kind(ir)
    if kind == "seq":
        first = normalize_ir(ir.get("first"))
        second = normalize_ir(ir.get("second"))
        if first is None:
            return second
        if second is None:
            return first
        return copy_display_order_metadata(ir, {"kind": "seq", "first": first, "second": second})
    if kind == "parallel":
        arms = []
        seen: set[str] = set()
        for arm in ir.get("arms", []) if isinstance(ir.get("arms"), list) else []:
            n = normalize_ir(arm)
            if n is None:
                continue
            k = obs_ir_key(n)
            if k in seen:
                continue
            seen.add(k)
            arms.append(n)
        if not arms:
            return None
        if len(arms) == 1:
            return arms[0]
        arms = sort_irs_for_display(arms)
        return copy_display_order_metadata(ir, {"kind": "parallel", "arms": arms})
    if kind == "join":
        alts = []
        for alt in ir.get("alternatives", []) if isinstance(ir.get("alternatives"), list) else []:
            if not isinstance(alt, dict):
                continue
            hist = normalize_ir(alt.get("history"))
            if hist is None:
                continue
            alts.append({"guard": alt.get("guard"), "history": hist})
        if not alts:
            return None
        alts.sort(key=lambda alt: display_order_key(alt.get("history")))
        return copy_display_order_metadata(ir, {"kind": "join", "alternatives": alts})
    if kind == "callWrap":
        inner = normalize_ir(ir.get("inner"))
        if inner is None:
            return None
        out = dict(ir)
        out["inner"] = inner
        return out
    if kind == "fieldRef":
        out = dict(ir)
        out["base"] = normalize_ir(ir.get("base"))
        return out
    return ir


def unique_higher_order_bindings_for_edge(edge: dict[str, Any]) -> dict[int, str]:
    """Return uniquely resolved callback targets recorded for one direct edge.

    A summary transfer edge normally contains only the caller data argument and
    the target callee formal.  For a higher-order callee such as
    ``invoke(compare, key, base)``, that is insufficient: the callee summary
    may contain ``$0.$1``, whose meaning depends on the *other* call actual
    ``compare``.  C6g4c records the resolved function-valued actual alongside
    the transfer edge.  We intentionally return bindings only when exactly one
    target was recorded for that callee function parameter.
    """
    raw = edge.get("resolvedHigherOrderActuals")
    if not isinstance(raw, list):
        return {}

    out: dict[int, str] = {}
    blocked: set[int] = set()
    for item in raw:
        if not isinstance(item, dict):
            continue
        try:
            formal_index = int(item.get("calleeFunctionParamIndex"))
        except Exception:
            continue
        if formal_index in blocked:
            continue
        targets = item.get("targets")
        if (item.get("status") != "unique" or not isinstance(targets, list)
                or len(targets) != 1 or not isinstance(targets[0], dict)):
            out.pop(formal_index, None)
            blocked.add(formal_index)
            continue
        public_key = str(targets[0].get("targetPublicLookupKey") or "")
        if not public_key:
            out.pop(formal_index, None)
            blocked.add(formal_index)
            continue
        if formal_index in out and out[formal_index] != public_key:
            out.pop(formal_index, None)
            blocked.add(formal_index)
            continue
        out[formal_index] = public_key
    return out


def parameter_counts_by_public_lookup_key(
    entries: list[dict[str, Any]],
    details_by_public_key: dict[str, dict[str, Any]],
) -> dict[str, int]:
    """Return declared formal counts, including parameters with identity summaries.

    ``record_map_from_details`` intentionally omits a parameter whose cast
    history is identity.  For higher-order substitution, however, the absence
    of a solved record for a known callback formal means identity rather than
    unresolved.  Keep this knowledge separate from the non-empty summary map.
    """
    counts: dict[str, int] = {}
    for entry in entries:
        key = str(entry.get("publicLookupKey") or public_lookup_key(entry))
        count = 0
        declared = entry.get("paramDeclaredTypes")
        if isinstance(declared, list):
            count = len(declared)

        detail = details_by_public_key.get(key)
        params = detail.get("params") if isinstance(detail, dict) else None
        if isinstance(params, list):
            for param in params:
                if not isinstance(param, dict):
                    continue
                index = param.get("index")
                if isinstance(index, int) and index >= 0:
                    count = max(count, index + 1)
        counts[key] = count
    return counts


def substitute_unique_higher_order_refs_for_edge(
    ir: Any,
    edge: dict[str, Any],
    solved: dict[str, dict[int, dict[str, Any]]],
    known_param_counts: dict[str, int] | None = None,
) -> tuple[Any, bool, bool]:
    """Specialize ``higherOrderParamRef`` nodes using one call-edge snapshot.

    Returns ``(rewritten, saw_higher_order_ref, all_refs_resolved)``.  The
    caller uses the rewritten value only when at least one reference was seen
    and *every* such reference had a uniquely resolved callback target and a
    usable callback parameter meaning.  A known callback formal with no
    non-empty solved record is the identity cast history, not an unresolved
    binding.  This keeps genuinely unresolved and multi-target callback
    behavior on the pre-C6g4c path, including its existing guarded/parallel
    treatment.

    The replacement summary is deliberately not recursively interpreted using
    the same edge.  A nested higher-order reference inside the callback target
    belongs to the callback's own formal environment, not to the outer callee.
    """
    bindings = unique_higher_order_bindings_for_edge(edge)
    saw_higher_order_ref = False
    all_refs_resolved = True

    def replacement_for(node: dict[str, Any]) -> Any:
        nonlocal saw_higher_order_ref, all_refs_resolved
        saw_higher_order_ref = True
        try:
            function_param_index = int(node.get("functionParamIndex"))
            argument_index = int(node.get("argumentIndex"))
        except Exception:
            all_refs_resolved = False
            return dict(node)

        target_key = bindings.get(function_param_index)
        if not target_key:
            all_refs_resolved = False
            return dict(node)

        target_rec = solved.get(target_key, {}).get(argument_index)
        if not isinstance(target_rec, dict):
            # No non-empty record is the normal representation of an identity
            # formal.  The target itself is still known uniquely at this edge,
            # so remove $fn.$arg rather than leaking a formal placeholder into
            # a fully applied caller.  An out-of-range or unknown target count
            # remains unresolved conservatively.
            known_count = (known_param_counts or {}).get(target_key)
            if known_count is not None and 0 <= argument_index < known_count:
                return None
            all_refs_resolved = False
            return dict(node)

        replacement = target_rec.get("solverIr")
        if replacement is None:
            replacement = target_rec.get("semanticCoreIr")
        if replacement is None:
            replacement = target_rec.get("ir")
        replacement = normalize_ir(replacement)
        if replacement is None:
            all_refs_resolved = False
            return dict(node)
        return replacement

    def visit(node: Any) -> Any:
        if not isinstance(node, dict):
            return node
        kind = ir_kind(node)
        if kind == "higherOrderParamRef":
            return replacement_for(node)
        if kind == "seq":
            return copy_display_order_metadata(
                node,
                {"kind": "seq", "first": visit(node.get("first")),
                 "second": visit(node.get("second"))},
            )
        if kind == "parallel":
            raw_arms = node.get("arms", [])
            if not isinstance(raw_arms, list):
                raw_arms = []
            return copy_display_order_metadata(
                node,
                {"kind": "parallel", "arms": [visit(arm) for arm in raw_arms]},
            )
        if kind == "join":
            alts = []
            raw_alts = node.get("alternatives", [])
            if isinstance(raw_alts, list):
                for alt in raw_alts:
                    if isinstance(alt, dict):
                        alts.append({"guard": alt.get("guard"),
                                     "history": visit(alt.get("history"))})
            return copy_display_order_metadata(node, {"kind": "join", "alternatives": alts})
        if kind == "callWrap":
            out = dict(node)
            out["inner"] = visit(node.get("inner"))
            return out
        if kind == "fieldRef":
            out = dict(node)
            out["base"] = visit(node.get("base"))
            return out
        return dict(node)

    return normalize_ir(visit(ir)), saw_higher_order_ref, all_refs_resolved



def compose_ir(prefix: Any, suffix: Any) -> Any:
    pfx = normalize_ir(prefix)
    sfx = normalize_ir(suffix)
    if pfx is None:
        return sfx
    if sfx is None:
        return pfx
    return normalize_ir({"kind": "seq", "first": pfx, "second": sfx})


def flatten_seq(ir: Any) -> list[Any] | None:
    ir = normalize_ir(ir)
    if ir is None:
        return []
    if not isinstance(ir, dict):
        return None
    if ir_kind(ir) == "seq":
        a = flatten_seq(ir.get("first"))
        b = flatten_seq(ir.get("second"))
        if a is None or b is None:
            return None
        return a + b
    if ir_kind(ir) in {"asType", "ptrarith"}:
        return [ir]
    return None


def ir_is_prefix(prefix: Any, whole: Any) -> bool:
    a = flatten_seq(prefix)
    b = flatten_seq(whole)
    if a is None or b is None or len(a) > len(b):
        return False
    return all(obs_ir_key(x) == obs_ir_key(y) for x, y in zip(a, b))


def join_ir(a: Any, b: Any) -> Any:
    a = normalize_ir(a)
    b = normalize_ir(b)
    if a is None:
        return b
    if b is None:
        return a
    if obs_ir_key(a) == obs_ir_key(b):
        return a
    if ir_is_prefix(a, b):
        return b
    if ir_is_prefix(b, a):
        return a

    arms: list[Any] = []
    seen: set[str] = set()
    def add_arm(x: Any) -> None:
        x = normalize_ir(x)
        if x is None:
            return
        if isinstance(x, dict) and x.get("kind") == "parallel" and isinstance(x.get("arms"), list):
            for arm in x["arms"]:
                add_arm(arm)
            return
        k = obs_ir_key(x)
        if k not in seen:
            seen.add(k)
            arms.append(x)
    add_arm(a)
    add_arm(b)
    if not arms:
        return None
    if len(arms) == 1:
        return arms[0]
    arms = sort_irs_for_display(arms)
    return {"kind": "parallel", "arms": arms}




def guard_text_key(guard: Any) -> str:
    if not isinstance(guard, dict):
        return ""
    return str(guard.get("text") or "")


def make_guarded_ir(ir: Any, guard: Any) -> Any:
    """Wrap a transfer candidate under an edge guard in the solver IR domain.

    Guarded field-function-pointer target selection should remain a branch
    alternative in solvedParamSummaries.  This helper intentionally does not
    deduplicate by type: two identical histories under different guards are
    distinct branch arms.
    """
    ir = normalize_ir(ir)
    if ir is None:
        return None
    if not isinstance(guard, dict) or not guard.get("text"):
        return ir
    return normalize_ir({"kind": "join", "alternatives": [
        {"guard": guard, "history": ir}
    ]})


def make_callwrap_ir(callee_name: str, inner: Any) -> Any:
    """Return a provenance-preserving call wrapper IR.

    Project solving uses wrapper-free cores for convergence, but the
    materialized solvedParamSummaries are a report/export domain.  They should
    preserve *why* a type was produced.  A cross-TU function-pointer target
    should therefore materialize as ``g⌜int *⌝g`` rather than as a bare
    ``int *``.
    """
    inner = normalize_ir(inner)
    if inner is None:
        return None
    callee_name = callee_name or "<callee>"
    return normalize_ir({"kind": "callWrap", "callee": callee_name, "inner": inner})


def path_prefix_for_report_ir(path_ir: Any) -> Any:
    """Return the caller-side prefix to keep outside a call wrapper.

    A transfer edge may contain only an identity/void* connector between the
    caller parameter and the callee formal.  Keeping that connector outside the
    wrapper would produce noisy histories such as ``void * => f⌜int *⌝f`` as
    the solved-summary tail.  Meaningful caller-side casts, pointer arithmetic,
    and other non-void evidence are preserved.
    """
    prefix = strip_callwrap_ir(path_ir)
    if ir_is_only_void_connectors(prefix):
        return None
    return normalize_ir(prefix)


def report_domain_transfer_ir(edge: dict[str, Any], callee_rec: dict[str, Any],
                              callee_node: str, path_ir: Any) -> Any:
    """Build the wrapper-preserving report arm for one transfer edge.

    This is used only when the transfer origin should be visible in the final
    solved summary (for example a non-recursive cross-TU import or a C5
    field-function-pointer target).  The solver-domain core remains separate.
    Same-TU ordinary named-call propagation generally should *not* use this
    wrapper arm, because doing so turns downstream chains such as p24 into
    superficial joins of ``char *`` and ``f⌜...⌝f``.
    """
    callee_report_ir = normalize_ir(callee_rec.get("ir"))
    if callee_report_ir is None:
        return None
    callee_name = node_function_name(callee_node) or str(callee_rec.get("function") or "")
    wrapped = make_callwrap_ir(callee_name, callee_report_ir)
    prefix = path_prefix_for_report_ir(path_ir)
    return normalize_ir(compose_project_ir(prefix, wrapped))


def edge_is_field_function_pointer_transfer(edge: dict[str, Any]) -> bool:
    v = edge.get("isFieldFunctionPointerCall")
    if isinstance(v, bool):
        return v
    if isinstance(v, str):
        return v.lower() in {"1", "true", "yes"}
    k = str(edge.get("kind") or edge.get("edgeKind") or "")
    return "field-function-pointer" in k


def unique_public_entry_for_edge_node(edge: dict[str, Any], node: str,
                                      by_public: dict[str, list[dict[str, Any]]]) -> dict[str, Any] | None:
    candidates = [c for c in by_public.get(node, []) if str(c.get("resolution") or "") != "unsafe"]
    if not candidates:
        return None
    if len(candidates) == 1:
        return candidates[0]

    edge_summary = str(edge.get("summaryFile") or "")
    edge_tu = str(edge.get("tuSourceFile") or "")
    same_summary = [c for c in candidates if str(c.get("summaryFile") or "") == edge_summary]
    if len(same_summary) == 1:
        return same_summary[0]
    same_tu = [c for c in candidates if edge_tu and str(c.get("tuSourceFile") or c.get("sourceFile") or "") == edge_tu]
    if len(same_tu) == 1:
        return same_tu[0]
    return None


def endpoint_is_ambiguous_internal(node: str, by_public: dict[str, list[dict[str, Any]]]) -> bool:
    candidates = [c for c in by_public.get(node, []) if str(c.get("resolution") or "") != "unsafe"]
    if len(candidates) <= 1:
        return False
    precise = {str(c.get("lookupKey") or lookup_key(c)) for c in candidates}
    if len(precise) <= 1:
        return False
    return any(normalize_linkage(c.get("linkage")) in INTERNAL_LINKAGES for c in candidates)


def filter_param_transfer_edges_for_public_solver(entries: list[dict[str, Any]],
                                                  transfer_edges: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Drop edges whose public endpoint is an ambiguous source-scoped function.

    C5g4 tried to solve this by switching the whole parameter solver to precise
    lookup keys for internal functions.  That was too broad and regressed normal
    direct-call imports and recursive downstream propagation.  This narrower
    filter keeps the historical public-key solver for ordinary project summaries
    and simply avoids materializing guessed transfer edges such as a.c::fa ->
    b.c::static helper in p04_static_same_name.  Same-TU local visitor
    propagation still handles the real a.c::fa -> a.c::helper edge.
    """
    by_public = entries_by_public_lookup_key(entries)
    kept: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []
    for edge in transfer_edges:
        caller = str(edge.get("callerNode") or "")
        callee = str(edge.get("calleeNode") or "")
        if endpoint_is_ambiguous_internal(caller, by_public) or endpoint_is_ambiguous_internal(callee, by_public):
            skipped.append({
                "reason": "ambiguous source-scoped endpoint; kept local visitor propagation instead of guessed project transfer",
                "callerNode": caller,
                "calleeNode": callee,
                "summaryFile": edge.get("summaryFile", ""),
                "tuSourceFile": edge.get("tuSourceFile", ""),
                "location": edge.get("location", {}),
            })
            continue
        kept.append(edge)
    return kept, {
        "numInputEdges": len(transfer_edges),
        "numKeptEdges": len(kept),
        "numSkippedAmbiguousInternalEdges": len(skipped),
        "skippedAmbiguousInternalEdges": skipped[:25],
        "identity": "public-key solver preserved; ambiguous internal/static endpoints are skipped rather than guessed",
    }


def should_preserve_transfer_wrapper(edge: dict[str, Any], callee_entry: dict[str, Any] | None,
                                     scc_of: dict[str, int], recursive_nodes: set[str]) -> bool:
    """Decide whether solvedParamSummaries should show a call wrapper for edge.

    Preserve wrappers for C5 field-function-pointer targets and for ordinary
    non-recursive cross-TU imports (p01/p08/p37).  Do not preserve wrappers for
    same-TU ordinary named-call downstream propagation, and do not preserve them
    inside recursive SCC solving paths (p18/p24), where the wrapper is already
    available in the display-only provenance section and the function summary
    should keep the full semantic sequence for downstream propagation.
    """
    if edge_is_field_function_pointer_transfer(edge):
        return True
    if same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
        return False
    if not callee_entry:
        return False
    edge_summary = str(edge.get("summaryFile") or "")
    callee_summary = str(callee_entry.get("summaryFile") or "")
    return bool(edge_summary and callee_summary and edge_summary != callee_summary)




def collect_guarded_history_arms(ir: Any) -> list[tuple[str, Any, Any]]:
    """Return (guard-text, guard-object, history) arms for a display/solver IR.

    This helper treats a non-join value as one unguarded arm.  It is used only
    by the report-domain materializer; solver-domain equality still goes
    through ``semanticCoreIr``.
    """
    ir = normalize_ir(ir)
    if ir is None:
        return []
    if isinstance(ir, dict) and ir.get("kind") == "join":
        out: list[tuple[str, Any, Any]] = []
        for alt in ir.get("alternatives", []) if isinstance(ir.get("alternatives"), list) else []:
            if not isinstance(alt, dict):
                continue
            hist = normalize_ir(alt.get("history"))
            if hist is None:
                continue
            guard = alt.get("guard") if isinstance(alt.get("guard"), dict) else None
            out.append((guard_text_key(guard), guard, hist))
        return out
    return [("", None, ir)]


def ir_semantic_core_key(ir: Any) -> str:
    return obs_ir_key(strip_callwrap_ir(ir))


def ir_contains_callwrap(ir: Any) -> bool:
    """Return true if report-domain IR contains call-wrapper provenance."""
    ir = normalize_ir(ir)
    if not isinstance(ir, dict):
        return False
    kind = ir_kind(ir)
    if kind == "callWrap":
        return True
    if kind == "seq":
        return ir_contains_callwrap(ir.get("first")) or ir_contains_callwrap(ir.get("second"))
    if kind == "parallel":
        return any(ir_contains_callwrap(a) for a in ir.get("arms", []) if a is not None)
    if kind == "join":
        return any(
            isinstance(alt, dict) and ir_contains_callwrap(alt.get("history"))
            for alt in ir.get("alternatives", []) if alt is not None
        )
    if kind == "fieldRef":
        return ir_contains_callwrap(ir.get("base"))
    return False


def prune_matching_core_from_history(history: Any, core_history: Any, *,
                                     allow_strict_prefix: bool = False) -> tuple[Any, bool]:
    """Remove the core-only projection of one transfer origin from a history.

    ``history`` is the existing report-domain value.  ``core_history`` is the
    wrapper-free solver-domain arm for the candidate edge.  If ``history`` is
    exactly that semantic core, it is removed.  If it is a parallel containing
    that exact core arm, only that arm is removed.  Other call wrappers or
    different concrete/local arms are preserved.

    ``allow_strict_prefix`` is deliberately opt-in.  It is used only by the
    same-edge field-function-pointer repair below, where the raw local
    projection may be the first concrete prefix of a richer target wrapper,
    e.g. ``int *`` beside ``local_handle⌜int * => void * => char *⌝``.
    """
    history = normalize_ir(history)
    core_history = normalize_ir(core_history)
    if history is None or core_history is None:
        return history, False

    def removable_projection(x: Any) -> bool:
        x = normalize_ir(x)
        if x is None:
            return False
        # Never remove call-wrapper arms; those are the provenance-rich facts
        # this pass is trying to preserve.
        if isinstance(x, dict) and x.get("kind") == "callWrap":
            return False
        if obs_ir_key(x) == obs_ir_key(core_history):
            return True
        return bool(allow_strict_prefix and ir_is_prefix(x, core_history) and
                    obs_ir_key(x) != obs_ir_key(core_history))

    if removable_projection(history):
        return None, True

    if isinstance(history, dict) and history.get("kind") == "parallel" and isinstance(history.get("arms"), list):
        kept: list[Any] = []
        removed = False
        for arm in history.get("arms", []):
            arm_norm = normalize_ir(arm)
            if not removed and removable_projection(arm_norm):
                removed = True
                continue
            if arm_norm is not None:
                kept.append(arm_norm)
        if removed:
            if not kept:
                return None, True
            if len(kept) == 1:
                return kept[0], True
            return normalize_ir({"kind": "parallel", "arms": kept}), True

    return history, False


def prune_core_projection_for_transfer(old_ir: Any, candidate_display_ir: Any,
                                       candidate_solver_ir: Any, *,
                                       allow_strict_prefix: bool = False) -> tuple[Any, bool]:
    """Prefer one provenance-preserving display arm per transfer origin.

    C5g2 made project solved summaries preserve wrappers, but when the same
    edge was also already represented locally as its semantic core, joining the
    two domains produced superficial alternatives such as
      [tag] <| int*, handle_int⌜int*⌝handle_int |> .

    This helper removes only the core-only arm that has the same guard and same
    solver-domain history as the candidate transfer arm.  It does not perform
    global type deduplication: different origins with the same ``int *`` remain
    separate when they are represented as distinct display histories.
    """
    old_ir = normalize_ir(old_ir)
    if old_ir is None:
        return None, False

    solver_arms = collect_guarded_history_arms(candidate_solver_ir)
    if not solver_arms:
        return old_ir, False
    by_guard: dict[str, list[Any]] = defaultdict(list)
    for guard_key, _guard, hist in solver_arms:
        by_guard[guard_key].append(hist)

    # Guarded old summary: prune within the corresponding guarded arm only.
    if isinstance(old_ir, dict) and old_ir.get("kind") == "join" and isinstance(old_ir.get("alternatives"), list):
        new_alts: list[dict[str, Any]] = []
        changed = False
        for alt in old_ir.get("alternatives", []):
            if not isinstance(alt, dict):
                continue
            guard = alt.get("guard") if isinstance(alt.get("guard"), dict) else None
            guard_key = guard_text_key(guard)
            hist = normalize_ir(alt.get("history"))
            if hist is None:
                continue
            for core_hist in by_guard.get(guard_key, []):
                hist, did = prune_matching_core_from_history(
                    hist, core_hist, allow_strict_prefix=allow_strict_prefix)
                changed = changed or did
                if hist is None:
                    break
            if hist is not None:
                new_alts.append({"guard": guard, "history": hist})
        if changed:
            return normalize_join_ir(new_alts), True
        return old_ir, False

    # Unguarded old summary: prune only unguarded candidate projections.
    changed = False
    pruned = old_ir
    for core_hist in by_guard.get("", []):
        pruned, did = prune_matching_core_from_history(
            pruned, core_hist, allow_strict_prefix=allow_strict_prefix)
        changed = changed or did
        if pruned is None:
            break
    return pruned, changed


def field_fnptr_same_edge_prefix_suppression_enabled(edge: dict[str, Any] | None,
                                                       candidate_display_ir: Any) -> bool:
    """Enable strict-prefix pruning only for a single field-FP transfer edge.

    This is the p48/C6c1 safety valve: the solver may already have a raw
    guarded projection such as ``[tag] int *`` from the same local field-FP
    edge, then later materialize the provenance-preserving target wrapper
    ``[tag] local_handle⌜int * => ...⌝local_handle`` for that exact edge.

    The caller passes exactly one transfer edge at a time, so the edge itself
    supplies the narrow key: call-site location, guard, field entity/path,
    target function, caller parameter index, and callee formal index.  We do
    not enable this for generic joins or non-field-function-pointer calls.
    """
    if not isinstance(edge, dict):
        return False
    if not edge_is_field_function_pointer_transfer(edge):
        return False
    if not ir_contains_callwrap(candidate_display_ir):
        return False
    required = [
        "callerNode", "calleeNode", "callerParamIndex", "calleeParamIndex",
        "calleeExpr", "fieldEntity", "location",
    ]
    return all(edge.get(k) not in (None, "") for k in required)


def origin_aware_join_report_ir(old_ir: Any, candidate_display_ir: Any,
                                candidate_solver_ir: Any, algebra: "ProjectSummaryAlgebra",
                                edge: dict[str, Any] | None = None) -> Any:
    """Join report-domain summaries using candidate solver arms as replacement keys."""
    allow_prefix = field_fnptr_same_edge_prefix_suppression_enabled(edge, candidate_display_ir)
    pruned_old_ir, _ = prune_core_projection_for_transfer(
        old_ir, candidate_display_ir, candidate_solver_ir,
        allow_strict_prefix=allow_prefix)
    return algebra.limit_parallel(algebra.join(pruned_old_ir, candidate_display_ir))


def split_seq_common_prefix(histories: list[Any]) -> tuple[Any, list[Any]]:
    """Return (common_prefix, suffixes) for linear histories when possible."""
    if not histories:
        return None, []
    seqs: list[list[Any]] = []
    for h in histories:
        items = flatten_seq(h)
        if items is None:
            return None, histories
        seqs.append(items)
    if not seqs:
        return None, histories
    min_len = min(len(xs) for xs in seqs)
    common_len = 0
    while common_len < min_len:
        k = obs_ir_key(seqs[0][common_len])
        if all(obs_ir_key(xs[common_len]) == k for xs in seqs[1:]):
            common_len += 1
        else:
            break
    if common_len == 0:
        return None, histories
    prefix = rebuild_seq(seqs[0][:common_len])
    suffixes = [rebuild_seq(xs[common_len:]) for xs in seqs]
    return normalize_ir(prefix), [normalize_ir(s) for s in suffixes]


def normalize_join_ir(alternatives: list[dict[str, Any]]) -> Any:
    """Build a branch/join IR while preserving guard-origin distinctions.

    The old project solver joined multiple guarded field-function-pointer target
    summaries as an unguarded Parallel.  For p36-style code, that produced a
    stale project-solved summary such as <| char*, int* |> which was then
    overlaid with the local guarded summary during import, yielding four arms.

    This normalizer keeps guarded alternatives as a Join and factors a shared
    linear prefix, so alternatives like
      [tag]     void*=>int*
      [!(tag)]  void*=>char*
    become
      void* => <[tag] int*, [!(tag)] char*>
    instead of a parallel join.
    """
    cleaned: list[dict[str, Any]] = []
    seen: set[str] = set()
    for alt in alternatives:
        if not isinstance(alt, dict):
            continue
        hist = normalize_ir(alt.get("history"))
        if hist is None:
            continue
        guard = alt.get("guard") if isinstance(alt.get("guard"), dict) else None
        # Exact duplicate only: same guard and same history. Do not merge two
        # int* arms under different guards.
        key = json.dumps({"guard": guard, "history": hist}, sort_keys=True, separators=(",", ":"))
        if key in seen:
            continue
        seen.add(key)
        cleaned.append({"guard": guard, "history": hist})
    cleaned.sort(key=lambda alt: display_order_key(alt.get("history")))
    if not cleaned:
        return None
    if len(cleaned) == 1:
        only = cleaned[0]
        if only.get("guard"):
            return {"kind": "join", "alternatives": cleaned}
        return normalize_ir(only.get("history"))

    # Factor a shared prefix across guarded histories for readability and for
    # consistency with the visitor's report-domain summaries.
    if all(alt.get("guard") for alt in cleaned):
        prefix, suffixes = split_seq_common_prefix([alt["history"] for alt in cleaned])
        if prefix is not None:
            factored: list[dict[str, Any]] = []
            for alt, suffix in zip(cleaned, suffixes):
                if suffix is None:
                    suffix = alt["history"]
                factored.append({"guard": alt.get("guard"), "history": suffix})
            joined = normalize_ir({"kind": "join", "alternatives": factored})
            return compose_ir(prefix, joined)

    return normalize_ir({"kind": "join", "alternatives": cleaned})


def join_guard_aware_ir(a: Any, b: Any) -> Any:
    """Join solver IR, preserving branch alternatives when guards are present."""
    a = normalize_ir(a)
    b = normalize_ir(b)
    if a is None:
        return b
    if b is None:
        return a
    if obs_ir_key(a) == obs_ir_key(b):
        return a

    def collect_join_alts(x: Any) -> list[dict[str, Any]] | None:
        x = normalize_ir(x)
        if not isinstance(x, dict) or x.get("kind") != "join":
            return None
        alts = []
        for alt in x.get("alternatives", []) if isinstance(x.get("alternatives"), list) else []:
            if isinstance(alt, dict):
                alts.append({"guard": alt.get("guard"), "history": alt.get("history")})
        return alts

    a_alts = collect_join_alts(a)
    b_alts = collect_join_alts(b)
    if a_alts is not None or b_alts is not None:
        alts: list[dict[str, Any]] = []
        if a_alts is not None:
            alts.extend(a_alts)
        else:
            alts.append({"guard": None, "history": a})
        if b_alts is not None:
            alts.extend(b_alts)
        else:
            alts.append({"guard": None, "history": b})
        # If any arm is guarded, keep the whole structure as a guard-aware join;
        # otherwise fall back to the legacy parallel join.
        if any(isinstance(alt.get("guard"), dict) and alt.get("guard", {}).get("text") for alt in alts):
            return normalize_join_ir(alts)

    return join_ir(a, b)

def strip_callwrap_ir(ir: Any) -> Any:
    """Return the semantic core used by the project-level solver.

    Function-name call wrappers are useful in final reports, but they are
    provenance decoration for project-level SCC solving.  Keeping the wrapper
    itself in the fixpoint domain makes otherwise-identical paths look
    different and can prevent convergence.  Unlike the older visitor-side
    experiment, this helper is used only by the index-level solver and does
    not change the raw report-domain summaries emitted by cast-history-tool.
    """
    ir = normalize_ir(ir)
    if ir is None or not isinstance(ir, dict):
        return None
    kind = ir_kind(ir)
    if kind == "callWrap":
        return strip_callwrap_ir(ir.get("inner"))
    if kind == "seq":
        return compose_ir(strip_callwrap_ir(ir.get("first")),
                          strip_callwrap_ir(ir.get("second")))
    if kind == "parallel":
        return normalize_ir({"kind": "parallel",
                             "arms": [strip_callwrap_ir(a) for a in ir.get("arms", [])]})
    if kind == "join":
        alts = []
        for alt in ir.get("alternatives", []) if isinstance(ir.get("alternatives"), list) else []:
            if not isinstance(alt, dict):
                continue
            hist = strip_callwrap_ir(alt.get("history"))
            if hist is not None:
                alts.append({"guard": alt.get("guard"), "history": hist})
        return normalize_ir({"kind": "join", "alternatives": alts})
    if kind == "fieldRef":
        out = dict(ir)
        out["base"] = strip_callwrap_ir(ir.get("base"))
        return normalize_ir(out)
    return ir



def is_void_pointer_type_atom(type_obj: Any) -> bool:
    if not isinstance(type_obj, dict):
        return False
    if bool(type_obj.get("isVoidPointer")):
        return True
    kind = str(type_obj.get("kind") or "")
    text = str(type_obj.get("canonical") or type_obj.get("text") or "")
    return kind == "void-pointer" or text == "void *"


def nonvoid_pointer_repeat_key(atom: Any) -> str | None:
    if not isinstance(atom, dict) or atom.get("kind") != "asType":
        return None
    type_obj = atom.get("type") if isinstance(atom.get("type"), dict) else {}
    if is_void_pointer_type_atom(type_obj):
        return None
    is_ptr = bool(type_obj.get("isPointer")) or str(type_obj.get("kind") or "").endswith("pointer")
    if not is_ptr:
        return None
    return str(type_obj.get("canonical") or type_obj.get("text") or obs_ir_key(type_obj))


def rebuild_seq(items: list[Any]) -> Any:
    out = None
    for item in items:
        out = compose_ir(out, item)
    return out


def truncate_seq_atoms_ir(ir: Any, *, max_atoms: int = 16) -> Any:
    """Bound purely by sequence length, not by repeated concrete types.

    C4L deliberately allows legitimate repeated concrete pointer types, e.g.
      void* => int* => void* => int* => void* => char*
    because the two int* observations may come from different wrappers, call
    edges, guards, or storage contexts.  SCC cycle control is handled by
    provenance-sensitive transfer-edge traces, not by type-repeat deletion.
    """
    ir = normalize_ir(ir)
    if ir is None or not isinstance(ir, dict):
        return None
    kind = ir_kind(ir)
    if kind == "parallel":
        return normalize_ir({"kind": "parallel",
                             "arms": [truncate_seq_atoms_ir(a, max_atoms=max_atoms)
                                      for a in ir.get("arms", [])]})
    if kind == "join":
        alts = []
        for alt in ir.get("alternatives", []) if isinstance(ir.get("alternatives"), list) else []:
            if not isinstance(alt, dict):
                continue
            hist = truncate_seq_atoms_ir(alt.get("history"), max_atoms=max_atoms)
            if hist is not None:
                alts.append({"guard": alt.get("guard"), "history": hist})
        return normalize_ir({"kind": "join", "alternatives": alts})
    items = flatten_seq(ir)
    if items is None:
        return ir
    if max_atoms and len(items) > max_atoms:
        items = items[:max_atoms]
    return normalize_ir(rebuild_seq(items))


def widen_same_scc_ir(ir: Any, *, max_atoms: int = 16) -> Any:
    """Return the project-solver semantic core in a bounded representation.

    Unlike C4I/C4J, this function no longer truncates on repeated concrete
    pointer types.  Wrapper stripping is still solver-local, but repeated-segment
    prevention is handled by edge/provenance traces in the SCC transfer solver.
    """
    return truncate_seq_atoms_ir(strip_callwrap_ir(ir), max_atoms=max_atoms)


