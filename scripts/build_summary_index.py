def prefix_segments_before_return_to_root(rec: dict[str, Any], root_key: str) -> list[dict[str, Any]]:
    """Return the non-repeating prefix of a solved SCC trace for root_key.

    The unit of cycle detection is a transfer segment, not a pointer type.  If a
    callee summary already contains a segment that calls back to the root
    function currently being solved, the prefix stops before that segment.  If
    the immediately preceding segment is only a void* connector into the next
    call, drop that connector too; it is the start of the next SCC lap rather
    than a new concrete interpretation.
    """
    raw = rec.get("projectSegments")
    if not isinstance(raw, list):
        return []
    out: list[dict[str, Any]] = []
    seen_edges: set[str] = set()
    for seg in raw:
        if not isinstance(seg, dict):
            continue
        if str(seg.get("calleeNode") or "") == root_key:
            # Avoid leaving a trailing erasure-only call connector as the last
            # visible part of this SCC expansion.
            while out and ir_is_only_void_connectors(out[-1].get("contributionIr")):
                out.pop()
            break
        ek = segment_edge_key(seg)
        if ek and ek in seen_edges:
            break
        if ek:
            seen_edges.add(ek)
        out.append(seg)
    return out


def limit_parallel_arms_ir(ir: Any, *, max_arms: int = 8) -> Any:
    ir = normalize_ir(ir)
    if ir is None or not isinstance(ir, dict):
        return ir
    kind = ir_kind(ir)
    if kind == "parallel":
        arms = []
        seen: set[str] = set()
        for arm in ir.get("arms", []) if isinstance(ir.get("arms"), list) else []:
            arm = limit_parallel_arms_ir(arm, max_arms=max_arms)
            if arm is None:
                continue
            k = obs_ir_key(arm)
            if k in seen:
                continue
            seen.add(k)
            arms.append(arm)
        arms.sort(key=lambda a: (len(nonvoid_pointer_keys_in_ir(a)), seq_len_or_large(a), obs_ir_key(a)), reverse=True)
        arms = arms[:max_arms]
        arms = sort_irs_for_display(arms)
        return normalize_ir({"kind": "parallel", "arms": arms})
    if kind == "join":
        alts = []
        for alt in ir.get("alternatives", []) if isinstance(ir.get("alternatives"), list) else []:
            if not isinstance(alt, dict):
                continue
            hist = limit_parallel_arms_ir(alt.get("history"), max_arms=max_arms)
            if hist is not None:
                alts.append({"guard": alt.get("guard"), "history": hist})
        return normalize_ir({"kind": "join", "alternatives": alts})
    if kind == "seq":
        return compose_ir(limit_parallel_arms_ir(ir.get("first"), max_arms=max_arms),
                          limit_parallel_arms_ir(ir.get("second"), max_arms=max_arms))
    if kind == "callWrap":
        out = dict(ir)
        out["inner"] = limit_parallel_arms_ir(ir.get("inner"), max_arms=max_arms)
        return normalize_ir(out)
    return ir


def join_same_scc_ir(old_ir: Any, candidate_ir: Any, *, max_atoms: int = 16) -> Any:
    """Join in the bounded intra-SCC domain.

    C4L keeps the old/candidate representative decision simple and stable; the
    actual cycle bound is enforced by provenance-sensitive projectSegments.
    """
    old_ir = widen_same_scc_ir(old_ir, max_atoms=max_atoms)
    candidate_ir = widen_same_scc_ir(candidate_ir, max_atoms=max_atoms)
    if old_ir is None:
        return candidate_ir
    if candidate_ir is None:
        return old_ir
    if obs_ir_key(old_ir) == obs_ir_key(candidate_ir):
        return old_ir
    if ir_is_prefix(old_ir, candidate_ir):
        return candidate_ir
    if ir_is_prefix(candidate_ir, old_ir):
        return old_ir

    old_items = flatten_seq(old_ir)
    cand_items = flatten_seq(candidate_ir)
    if old_items is not None and cand_items is not None:
        old_nonvoid = len(nonvoid_pointer_keys_in_ir(old_ir))
        cand_nonvoid = len(nonvoid_pointer_keys_in_ir(candidate_ir))
        if cand_nonvoid > old_nonvoid:
            return candidate_ir
        if cand_nonvoid < old_nonvoid:
            return old_ir
        if len(cand_items) > len(old_items):
            return candidate_ir
        return old_ir

    return limit_parallel_arms_ir(widen_same_scc_ir(join_ir(old_ir, candidate_ir),
                                                    max_atoms=max_atoms),
                                  max_arms=env_int("CAST_HISTORY_SOLVED_PARAM_MAX_PARALLEL_ARMS", 8))


def compose_project_ir(prefix: Any, suffix: Any) -> Any:
    """Compose solver-domain histories while preserving void* connectors.

    This is intentionally weaker than any semantic simplification: it only
    removes an exact duplicate atom at the boundary between two already-linear
    histories.  It does not remove repeated concrete pointer types elsewhere,
    so paths such as void*=>int*=>void*=>int* remain representable when they
    arise from distinct transfer contexts.
    """
    pfx = normalize_ir(prefix)
    sfx = normalize_ir(suffix)
    if pfx is None:
        return sfx
    if sfx is None:
        return pfx
    a = flatten_seq(pfx)
    b = flatten_seq(sfx)
    if a is not None and b is not None:
        items = list(a)
        if items and b and obs_ir_key(items[-1]) == obs_ir_key(b[0]):
            items.extend(b[1:])
        else:
            items.extend(b)
        return normalize_ir(rebuild_seq(items))
    return compose_ir(pfx, sfx)


def has_local_contribution(ir: Any) -> bool:
    ir = normalize_ir(ir)
    return ir is not None and not ir_is_only_void_connectors(ir)


def param_indices_for_node(node: str, local_map: dict[str, dict[int, dict[str, Any]]],
                           transfer_edges: list[dict[str, Any]]) -> set[int]:
    out: set[int] = set()
    for idx in local_map.get(node, {}):
        out.add(int(idx))
    for e in transfer_edges:
        try:
            if str(e.get("callerNode") or "") == node:
                out.add(int(e.get("callerParamIndex")))
            if str(e.get("calleeNode") or "") == node:
                out.add(int(e.get("calleeParamIndex")))
        except Exception:
            pass
    return out


def better_path_ir(old_ir: Any, new_ir: Any) -> Any:
    """Choose one representative path, rather than unrolling into parallel arms.

    For a single SCC parameter, the project-level summary should be a bounded
    representative of the simple SCC expansion.  Prefer the path that has more
    concrete/non-void observations; break ties by longer sequential evidence.
    This prevents repeated substitution of whole solved summaries while avoiding
    type-based truncation.
    """
    old_ir = normalize_ir(old_ir)
    new_ir = normalize_ir(new_ir)
    if old_ir is None:
        return new_ir
    if new_ir is None:
        return old_ir
    if obs_ir_key(old_ir) == obs_ir_key(new_ir):
        return old_ir
    if ir_is_prefix(old_ir, new_ir):
        return new_ir
    if ir_is_prefix(new_ir, old_ir):
        return old_ir
    old_nonvoid = len(nonvoid_pointer_keys_in_ir(old_ir))
    new_nonvoid = len(nonvoid_pointer_keys_in_ir(new_ir))
    if new_nonvoid > old_nonvoid:
        return new_ir
    if new_nonvoid < old_nonvoid:
        return old_ir
    if seq_len_or_large(new_ir) > seq_len_or_large(old_ir):
        return new_ir
    return old_ir


def same_recursive_scc_for_edge(edge: dict[str, Any], scc_of: dict[str, int],
                                recursive_nodes: set[str]) -> bool:
    caller = str(edge.get("callerNode") or "")
    callee = str(edge.get("calleeNode") or "")
    callee_display = str(edge.get("calleePublicNode") or callee)
    if not caller or not callee:
        return False
    caller_scc = scc_of.get(caller)
    callee_scc = scc_of.get(callee)
    return (caller_scc is not None and caller_scc == callee_scc and
            caller in recursive_nodes and callee in recursive_nodes)


def canonical_guarded_ptrarith_transformer(ir: Any) -> Any:
    """Extract one canonical p127-style guarded local transformer.

    C1's rich report history may already contain a recursive Seq/Parallel
    expansion around the underlying local branch transformer.  C2 needs the
    local relation itself, not that accidental expansion.  Search the tree for
    a guarded Join whose arms are direct PtrArith steps, and return the
    deterministic smallest semantic candidate.  This is materialization-only
    and never affects SCC membership or transfer propagation.
    """
    candidates: list[Any] = []

    def visit(node: Any) -> None:
        node = normalize_ir(node)
        if not isinstance(node, dict):
            return
        if ir_kind(node) == "join":
            alts = node.get("alternatives")
            if isinstance(alts, list) and len(alts) >= 2:
                good = True
                for alt in alts:
                    if not isinstance(alt, dict):
                        good = False
                        break
                    guard = alt.get("guard")
                    hist = normalize_ir(alt.get("history"))
                    if (not isinstance(guard, dict) or
                            not str(guard.get("text") or "") or
                            not isinstance(hist, dict) or
                            ir_kind(hist) != "ptrarith"):
                        good = False
                        break
                if good:
                    candidates.append(node)
                    return
            for alt in alts if isinstance(alts, list) else []:
                if isinstance(alt, dict):
                    visit(alt.get("history"))
            return
        kind = ir_kind(node)
        if kind == "seq":
            visit(node.get("first")); visit(node.get("second"))
        elif kind == "parallel":
            for arm in node.get("arms", []) if isinstance(node.get("arms"), list) else []:
                visit(arm)
        elif kind == "callWrap":
            visit(node.get("inner"))
        elif kind == "fieldRef":
            visit(node.get("base"))

    visit(ir)
    if not candidates:
        return None
    candidates.sort(key=lambda x: obs_ir_key(normalize_ir(x)))
    return normalize_ir(candidates[0])


def is_guarded_local_ptrarith_transformer(ir: Any) -> bool:
    return canonical_guarded_ptrarith_transformer(ir) is not None


def _record_fork_arm_path(paths: dict[tuple[str, str], dict[str, Any]], *,
                          fork_id: str, arm_id: str, origin: str,
                          ir: Any, trace: list[dict[str, Any]]) -> None:
    """Retain one bounded representative for each root fork arm."""
    if not fork_id or not arm_id:
        return
    ir = normalize_ir(ir)
    if ir is None:
        return
    key = (fork_id, arm_id)
    old = paths.get(key)
    if old is not None:
        old_ir = old.get("ir")
        # Same arm can be observed at an intermediate relay and at the final
        # root-return boundary.  Prefer the extension, never a second arm.
        if ir_is_prefix(ir, old_ir):
            return
        if not ir_is_prefix(old_ir, ir):
            selected = better_path_ir(old_ir, ir)
            if obs_ir_key(normalize_ir(selected)) != obs_ir_key(ir):
                return
    paths[key] = {
        "forkId": fork_id,
        "armId": arm_id,
        "origin": origin,
        "rendered": render_ir(ir),
        "ir": ir,
        "trace": trace_clone(trace),
    }


def solve_recursive_scc_by_simple_paths_for_import(
    solved: dict[str, dict[int, dict[str, Any]]],
    transfer_edges: list[dict[str, Any]],
    recursive_nodes: set[str],
    scc_of: dict[str, int],
    *,
    algebra: ProjectSummaryAlgebra,
    known_param_counts: dict[str, int] | None = None,
    excluded_roots: set[str] | None = None,
) -> tuple[int, int, int]:
    """Build import-authoritative SCC summaries using the established C6g5s path rule.

    This deliberately does not compose whole solved summaries recursively.
    Instead, for each root parameter it walks simple transfer paths inside its
    SCC and appends each callee's local/base contribution at most once per path.
    A path stops before taking an edge that returns to the root; this prevents
    the next SCC lap from replaying the root's own local contribution.

    It preserves the complete solved continuation used by ordinary summary
    import. C6g5v deliberately keeps this path distinct from the separate
    fork-aware canonical reporting overlay below.
    """
    outgoing: dict[tuple[str, int], list[dict[str, Any]]] = defaultdict(list)
    same_edges: list[dict[str, Any]] = []
    for edge in transfer_edges:
        if not same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
            continue
        try:
            caller_idx = int(edge.get("callerParamIndex"))
            int(edge.get("calleeParamIndex"))
        except Exception:
            continue
        same_edges.append(edge)
        outgoing[(str(edge.get("callerNode") or ""), caller_idx)].append(edge)

    # Local/base contribution snapshot.  Do not read newly solved SCC summaries
    # while expanding paths; otherwise we fall back into recursive substitution.
    local_base: dict[str, dict[int, Any]] = {}
    local_trace: dict[str, dict[int, list[dict[str, Any]]]] = {}
    for node, by_idx in solved.items():
        for idx, rec in by_idx.items():
            ir = rec.get("projectBaseIr")
            if ir is None:
                ir = strip_callwrap_ir(rec.get("ir"))
            ir = algebra.bound_same_scc(ir)
            local_base.setdefault(node, {})[int(idx)] = ir
            trace = trace_clone(rec.get("projectTrace"))
            if not trace and ir is not None:
                trace = [trace_step_local(node, int(idx), ir, role="local-base")]
            local_trace.setdefault(node, {})[int(idx)] = trace

    changed = 0
    path_count = 0
    max_depth = max(1, len({(str(e.get("callerNode") or ""), str(e.get("calleeNode") or "")) for e in same_edges}) + 1)
    nodes = sorted(recursive_nodes)
    excluded_roots = excluded_roots or set()

    for root in nodes:
        if root not in recursive_nodes or root in excluded_roots:
            continue
        for root_idx in sorted(param_indices_for_node(root, solved, same_edges)):
            root_base = local_base.get(root, {}).get(root_idx)
            best = root_base
            best_trace = trace_clone(local_trace.get(root, {}).get(root_idx, []))

            stack: list[tuple[str, int, Any, list[dict[str, Any]], frozenset[str], frozenset[tuple[str, int]], int]] = [
                (root, root_idx, root_base, best_trace, frozenset(), frozenset({(root, root_idx)}), 0)
            ]
            while stack:
                node, idx, acc, trace, used_edges, visited_params, depth = stack.pop()
                if depth >= max_depth:
                    continue
                for edge in outgoing.get((node, idx), []):
                    edge_key = transfer_edge_key(edge)
                    if edge_key in used_edges:
                        continue
                    callee = str(edge.get("calleeNode") or "")
                    try:
                        callee_idx = int(edge.get("calleeParamIndex"))
                    except Exception:
                        continue

                    path_obj = edge.get("actualPathFromCallerParam") if isinstance(edge.get("actualPathFromCallerParam"), dict) else {}
                    path_ir = strip_callwrap_ir(path_obj.get("ir") if isinstance(path_obj, dict) else None)
                    next_acc = algebra.compose(acc, path_ir)
                    transfer_step = trace_step_transfer(edge, path_ir)
                    next_trace = trace_extend(trace, transfer_step)

                    # Returning to the root would start the next SCC lap.  Keep
                    # the call-boundary erasure such as int* => void*, then stop
                    # before appending the root's local contribution again.
                    if callee == root and callee_idx == root_idx:
                        stop_step = trace_step_stop(
                            "would return to root parameter and replay its local/base contribution; kept the call-boundary path and stopped before the next SCC lap",
                            node=root, index=root_idx)
                        stopped_trace = trace_extend(next_trace, stop_step)
                        stopped_acc = make_guarded_ir(next_acc, edge.get("guard"))
                        if has_local_contribution(stopped_acc):
                            best, best_trace = choose_better_path_with_trace(best, best_trace, stopped_acc, stopped_trace)
                            path_count += 1
                        continue

                    callee_base = local_base.get(callee, {}).get(callee_idx)
                    if callee_base is not None:
                        specialized_callee_base, saw_hof_ref, all_hof_refs_resolved = (
                            substitute_unique_higher_order_refs_for_edge(
                                callee_base, edge, solved, known_param_counts))
                        if saw_hof_ref and all_hof_refs_resolved:
                            callee_base = specialized_callee_base
                        next_acc = algebra.compose(next_acc, callee_base)
                        callee_trace = local_trace.get(callee, {}).get(callee_idx)
                        if callee_trace:
                            # The local trace normally has one local/base step.
                            next_trace = trace_extend(next_trace, *trace_clone(callee_trace))
                        else:
                            next_trace = trace_extend(next_trace, trace_step_local(callee, callee_idx, callee_base, role="callee-local-base"))
                        candidate_acc = make_guarded_ir(next_acc, edge.get("guard"))
                        if has_local_contribution(candidate_acc):
                            best, best_trace = choose_better_path_with_trace(best, best_trace, candidate_acc, next_trace)
                            path_count += 1

                    # Continue through connector-only functions such as relay,
                    # but do not revisit the same parameter in one expansion.
                    next_param = (callee, callee_idx)
                    if next_param in visited_params:
                        continue
                    next_used = frozenset(set(used_edges) | {edge_key})
                    next_visited = frozenset(set(visited_params) | {next_param})
                    stack.append((callee, callee_idx, algebra.bound_same_scc(next_acc),
                                  trace_clone(next_trace), next_used, next_visited, depth + 1))

            best = algebra.bound_same_scc(best)
            if best is None:
                continue
            old_rec = solved.setdefault(root, {}).get(root_idx)
            old_ir = old_rec.get("ir") if old_rec else None
            if old_rec and obs_ir_key(normalize_ir(old_ir)) == obs_ir_key(best):
                # Preserve an explanation if the old record did not already have one.
                if best_trace and not old_rec.get("projectTrace"):
                    old_rec["projectTrace"] = best_trace
                continue
            solved[root][root_idx] = {
                "index": root_idx,
                "rendered": render_ir(best),
                "ir": best,
                "projectBaseIr": root_base,
                "source": "project-intra-scc-simple-path-fixpoint",
                "bounded": True,
                "projectTraceKind": "simple-scc-path",
                "projectTrace": best_trace,
                "projectExplanationStopReasons": trace_stop_reasons(best_trace),
            }
            changed += 1

    return len(same_edges), changed, path_count


def solve_recursive_scc_by_simple_paths(
    solved: dict[str, dict[int, dict[str, Any]]],
    transfer_edges: list[dict[str, Any]],
    recursive_nodes: set[str],
    scc_of: dict[str, int],
    *,
    algebra: ProjectSummaryAlgebra,
    known_param_counts: dict[str, int] | None = None,
) -> tuple[int, int, int]:
    """Solve recursive parameter summaries with bounded, root-correlated paths.

    The C6g5s version selected a single "best" path after starting each walk
    with the entire root local summary.  That loses correlation for a local
    fork such as p126's ``as_int`` / ``as_char`` calls: both candidates inherit
    the same aggregate root Parallel and later joins can make both appear to
    begin at ``int *``.

    C6g5v uses this only for display-only canonical histories.  It starts a
    walk at the actual-path snapshot of each outgoing
    edge.  The first edge is a stable *fork* and its edge key is a stable *arm*.
    The walk then appends callee-local bases at most once per parameter node and
    stops before replaying the root.  Multiple root arms are joined as distinct
    report alternatives; fork/arm tags are report-only metadata and are
    ignored by semantic equality.
    """
    outgoing: dict[tuple[str, int], list[dict[str, Any]]] = defaultdict(list)
    same_edges: list[dict[str, Any]] = []
    for edge in transfer_edges:
        if not same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
            continue
        try:
            caller_idx = int(edge.get("callerParamIndex"))
            int(edge.get("calleeParamIndex"))
        except Exception:
            continue
        same_edges.append(edge)
        outgoing[(str(edge.get("callerNode") or ""), caller_idx)].append(edge)

    for edges in outgoing.values():
        edges.sort(key=transfer_edge_key)

    # Freeze local/base contributions.  A recursive materialization must never
    # read the newly joined SCC result as a next-step callee contribution.
    local_base: dict[str, dict[int, Any]] = {}
    local_trace: dict[str, dict[int, list[dict[str, Any]]]] = {}
    for node, by_idx in solved.items():
        for idx, rec in by_idx.items():
            # projectBaseIr is the immutable direct-local AST contribution.
            # It is not the import-authoritative rich summary stored in ir.
            ir = rec.get("projectBaseIr")
            if ir is None and not rec.get("directLocalBasePresent", False):
                # Legacy/pre-C6g5v fallback only.
                ir = strip_callwrap_ir(rec.get("rawReportIr") or rec.get("ir"))
            ir = algebra.bound_same_scc(ir)
            local_base.setdefault(node, {})[int(idx)] = ir
            trace = trace_clone(rec.get("projectTrace"))
            if not trace and ir is not None:
                trace = [trace_step_local(node, int(idx), ir, role="local-base")]
            local_trace.setdefault(node, {})[int(idx)] = trace

    changed = 0
    path_count = 0
    max_depth = max(1, len({(str(e.get("callerNode") or ""), str(e.get("calleeNode") or ""))
                            for e in same_edges}) + 1)
    nodes = sorted(recursive_nodes)

    for root in nodes:
        for root_idx in sorted(param_indices_for_node(root, solved, same_edges)):
            root_base = local_base.get(root, {}).get(root_idx)
            root_edges = outgoing.get((root, root_idx), [])

            # p127: the local guarded transformer is already a finite, complete
            # canonical report contribution.  Do not synthetically unroll it
            # through the same SCC just to rediscover tag / !tag ptrarith arms.
            root_transformer = canonical_guarded_ptrarith_transformer(root_base)
            if root_transformer is not None:
                # Keep the local guarded relation once.  The rich C1 summary may
                # contain repeated recursive wrappers around it, but those are
                # report artifacts rather than new local transformer facts.
                best = root_transformer
                best_trace = trace_clone(local_trace.get(root, {}).get(root_idx, []))
                fork_paths: dict[tuple[str, str], dict[str, Any]] = {}
                path_count += 1
            else:
                best: Any = None
                best_trace: list[dict[str, Any]] = []
                fork_paths: dict[tuple[str, str], dict[str, Any]] = {}

                # The root has one local parallel fork when multiple distinct
                # actual-path snapshots leave the same formal.  Keep only this
                # first fork identity; later relay edges are continuation, not
                # independent root alternatives.
                distinct_root_paths = {
                    obs_ir_key(strip_callwrap_ir(
                        (edge.get("actualPathFromCallerParam") or {}).get("ir")
                        if isinstance(edge.get("actualPathFromCallerParam"), dict)
                        else None))
                    for edge in root_edges
                }
                has_root_fork = len(distinct_root_paths) > 1
                root_fork_id = (f"{root}.${root_idx}:call-actual-fork"
                                if has_root_fork else "")

                def absorb(candidate: Any, trace: list[dict[str, Any]], *,
                           fork_id: str = "", arm_id: str = "",
                           origin: str = "") -> None:
                    nonlocal best, best_trace, path_count
                    candidate = algebra.limit_parallel(candidate)
                    if candidate is None or not has_local_contribution(candidate):
                        return
                    if fork_id and arm_id:
                        candidate = attach_fork_arm_metadata(
                            candidate, fork_id=fork_id, arm_id=arm_id,
                            origin=origin)
                        _record_fork_arm_path(
                            fork_paths, fork_id=fork_id, arm_id=arm_id,
                            origin=origin, ir=candidate, trace=trace)
                    joined = candidate if best is None else algebra.limit_parallel(
                        algebra.join(best, candidate))
                    if best is None or obs_ir_key(normalize_ir(best)) != obs_ir_key(normalize_ir(joined)):
                        best = joined
                        # A single linear trace is still useful for debugging;
                        # the complete arm provenance is retained separately.
                        best_trace = trace_clone(trace)
                    path_count += 1

                stack: list[tuple[str, int, Any, list[dict[str, Any]],
                                  frozenset[str], frozenset[tuple[str, int]],
                                  int, str, str, str]] = [
                    (root, root_idx, None, [], frozenset(),
                     frozenset({(root, root_idx)}), 0, "", "", "")
                ]
                while stack:
                    (node, idx, acc, trace, used_edges, visited_params, depth,
                     inherited_fork_id, inherited_arm_id, inherited_origin) = stack.pop()
                    if depth >= max_depth:
                        continue
                    for edge in outgoing.get((node, idx), []):
                        edge_key = transfer_edge_key(edge)
                        if edge_key in used_edges:
                            continue
                        callee = str(edge.get("calleeNode") or "")
                        try:
                            callee_idx = int(edge.get("calleeParamIndex"))
                        except Exception:
                            continue

                        path_obj = (edge.get("actualPathFromCallerParam")
                                    if isinstance(edge.get("actualPathFromCallerParam"), dict)
                                    else {})
                        path_ir = strip_callwrap_ir(path_obj.get("ir")
                                                     if isinstance(path_obj, dict)
                                                     else None)
                        if acc is None and path_ir is None:
                            # Identity direct-parameter call: its local base is
                            # the only source contribution available.
                            next_acc = root_base
                        else:
                            next_acc = algebra.compose(acc, path_ir)

                        fork_id = inherited_fork_id
                        arm_id = inherited_arm_id
                        origin = inherited_origin
                        if depth == 0 and root_fork_id:
                            fork_id = root_fork_id
                            arm_id = edge_key
                            origin = "root-actual-path"

                        transfer_step = trace_step_transfer(edge, path_ir)
                        if fork_id and arm_id:
                            transfer_step["forkId"] = fork_id
                            transfer_step["armId"] = arm_id
                            transfer_step["forkOrigin"] = origin
                        next_trace = trace_extend(trace, transfer_step)

                        # A repeated parameter closes a simple path.  Keep the
                        # actual call-boundary conversion, but stop *before*
                        # appending the repeated callee's local base.  This is
                        # the rule that prevents p126 from re-inserting
                        # relay_a's int*/char* fork after returning from
                        # relay_b.  Edge guards remain provenance/trace data;
                        # they are not synthetic cast-history nodes.
                        next_param = (callee, callee_idx)
                        if next_param in visited_params:
                            stopped_trace = trace_extend(
                                next_trace,
                                trace_step_stop(
                                    "would revisit a parameter and replay its direct-local base; kept the call-boundary path and stopped",
                                    node=callee, index=callee_idx))
                            absorb(next_acc, stopped_trace, fork_id=fork_id,
                                   arm_id=arm_id, origin=origin)
                            continue

                        callee_base = local_base.get(callee, {}).get(callee_idx)
                        # An actual-path snapshot already contains the caller's
                        # local cast that prepares this call.  Append the
                        # callee's direct-local base only on an identity edge,
                        # where that next local fact would otherwise be absent
                        # (for example relay -> g in p23).  This avoids both
                        # re-inserting p126's fork base and creating spurious
                        # guard-only refinement segments in p100/p101.
                        base_to_append = callee_base if path_ir is None else None
                        if base_to_append is not None:
                            specialized_base, saw_hof_ref, all_hof_refs_resolved = (
                                substitute_unique_higher_order_refs_for_edge(
                                    base_to_append, edge, solved,
                                    known_param_counts))
                            if saw_hof_ref and all_hof_refs_resolved:
                                base_to_append = specialized_base
                            next_acc = algebra.compose(next_acc, base_to_append)
                            callee_trace = local_trace.get(callee, {}).get(callee_idx)
                            if callee_trace:
                                next_trace = trace_extend(
                                    next_trace, *trace_clone(callee_trace))
                            else:
                                next_trace = trace_extend(
                                    next_trace,
                                    trace_step_local(callee, callee_idx,
                                                     base_to_append,
                                                     role="identity-edge-direct-local-base"))

                        next_used = frozenset(set(used_edges) | {edge_key})
                        next_visited = frozenset(set(visited_params) | {next_param})
                        stack.append((callee, callee_idx,
                                      algebra.bound_same_scc(next_acc),
                                      trace_clone(next_trace), next_used,
                                      next_visited, depth + 1, fork_id, arm_id,
                                      origin))

                if best is None:
                    best = root_base
                    best_trace = trace_clone(local_trace.get(root, {}).get(root_idx, []))

            best = algebra.bound_same_scc(best)
            if best is None:
                continue
            old_rec = solved.setdefault(root, {}).get(root_idx)
            old_ir = old_rec.get("ir") if old_rec else None
            old_fork_paths = (old_rec.get("forkArmProvenance")
                              if isinstance(old_rec, dict) else None)
            normalized_fork_paths = [
                {k: v for k, v in rec.items() if k != "ir"}
                for _key, rec in sorted(fork_paths.items())
            ]
            if old_rec and obs_ir_key(normalize_ir(old_ir)) == obs_ir_key(best):
                if best_trace and not old_rec.get("projectTrace"):
                    old_rec["projectTrace"] = best_trace
                if normalized_fork_paths and not old_fork_paths:
                    old_rec["forkArmProvenance"] = normalized_fork_paths
                continue

            rec: dict[str, Any] = {
                "index": root_idx,
                "rendered": render_ir(best),
                "ir": best,
                "projectBaseIr": root_base,
                "source": "project-intra-scc-fork-aware-simple-path-fixpoint",
                "bounded": True,
                "projectTraceKind": "fork-aware-simple-scc-path",
                "projectTrace": best_trace,
                "projectExplanationStopReasons": trace_stop_reasons(best_trace),
            }
            if normalized_fork_paths:
                rec["forkArmProvenance"] = normalized_fork_paths
            solved[root][root_idx] = rec
            changed += 1

    return len(same_edges), changed, path_count

def render_type_atom(obj: Any) -> str:
    if not isinstance(obj, dict):
        return "?"
    return str(obj.get("text") or obj.get("canonical") or "?")


def render_ir(ir: Any) -> str:
    ir = normalize_ir(ir)
    if ir is None:
        return ""
    if not isinstance(ir, dict):
        return "?"
    kind = ir.get("kind")
    if kind == "asType":
        return render_type_atom(ir.get("type"))
    if kind == "ptrarith":
        return f"ptrarith({render_type_atom(ir.get('type'))})"
    if kind == "seq":
        lhs = render_ir(ir.get("first"))
        rhs = render_ir(ir.get("second"))
        if not lhs:
            return rhs
        if not rhs:
            return lhs
        return f"{lhs} => {rhs}"
    if kind == "parallel":
        return "⟨| " + ", ".join(render_ir(a) for a in ir.get("arms", [])) + " |⟩"
    if kind == "join":
        parts = []
        for alt in ir.get("alternatives", []):
            if isinstance(alt, dict):
                g = alt.get("guard") if isinstance(alt.get("guard"), dict) else {}
                parts.append(f"[{g.get('text', 'guard')}] {render_ir(alt.get('history'))}")
        return "⟨" + ", ".join(parts) + "⟩"
    if kind == "callWrap":
        callee = ir.get("callee") or "call"
        return f"{callee}⌜{render_ir(ir.get('inner'))}⌝{callee}"
    if kind == "paramRef":
        return f"${ir.get('index', 0)}"
    if kind == "returnRef":
        return "$ret"
    if kind == "higherOrderParamRef":
        return f"${ir.get('functionParamIndex', 0)}.${ir.get('argumentIndex', 0)}"
    if kind == "fieldRef":
        base = render_ir(ir.get("base"))
        fields = ".".join(str(f) for f in ir.get("fieldPath", []))
        return f"{base}.{fields}" if base else fields
    if kind == "unknown":
        return f"unknown({ir.get('note', '')})"
    return str(kind or "?")


def param_summary_records_from_detail(detail: dict[str, Any]) -> list[dict[str, Any]]:
    params = detail.get("params")
    if not isinstance(params, list):
        return []
    out: list[dict[str, Any]] = []
    for p in params:
        if not isinstance(p, dict):
            continue
        idx = p.get("index")
        if not isinstance(idx, int) or idx < 0:
            continue
        summary = p.get("summary") if isinstance(p.get("summary"), dict) else {}
        ir = normalize_ir(summary.get("ir"))
        if not obs_ir_is_nonempty(ir):
            continue
        out.append({
            "index": idx,
            "rendered": summary.get("rendered", "") if isinstance(summary.get("rendered"), str) else render_ir(ir),
            "ir": ir,
            "source": "materialized-from-function-summary-detail",
        })
    out.sort(key=lambda x: x.get("index", 0))
    return out



def _history_ir_from_param_field(param: dict[str, Any], field: str) -> Any:
    raw = param.get(field)
    if not isinstance(raw, dict):
        return None
    return normalize_ir(raw.get("ir"))


def canonical_param_summary_records_from_detail(detail: dict[str, Any]) -> list[dict[str, Any]]:
    """Read companion direct-local metadata for display-only C2 histories.

    The ordinary `summary` remains import-authoritative and is handled by
    param_summary_records_from_detail().  An explicit directLocalSummary with a
    null IR denotes an identity forwarder; keep that record so downstream
    propagation can install the canonical callee fact.
    """
    params = detail.get("params")
    if not isinstance(params, list):
        return []
    out: list[dict[str, Any]] = []
    for p in params:
        if not isinstance(p, dict):
            continue
        idx = p.get("index")
        if not isinstance(idx, int) or idx < 0:
            continue
        raw_summary = p.get("summary") if isinstance(p.get("summary"), dict) else {}
        raw_ir = normalize_ir(raw_summary.get("ir"))
        direct_present = isinstance(p.get("directLocalSummary"), dict)
        direct_ir = _history_ir_from_param_field(p, "directLocalSummary")
        if not direct_present:
            # Older link summaries lack the companion field.  Fall back
            # conservatively to the legacy local report core.
            direct_ir = strip_callwrap_ir(raw_ir)
        if not obs_ir_is_nonempty(raw_ir) and not direct_present:
            continue
        out.append({
            "index": idx,
            "rendered": render_ir(direct_ir),
            "ir": direct_ir,
            "rawReportIr": raw_ir,
            "projectBaseIr": direct_ir,
            "directLocalBasePresent": direct_present,
            "source": "canonical-direct-local-base",
            "projectTraceKind": "canonical-direct-local-base",
            "projectTrace": ([trace_step_local(str(detail.get("function") or ""), idx, direct_ir,
                                                role="direct-local-base")]
                             if direct_ir is not None else []),
        })
    out.sort(key=lambda x: int(x.get("index", 0)))
    return out


def canonical_record_map_from_details(entries: list[dict[str, Any]],
                                       details_by_public_key: dict[str, dict[str, Any]]) -> dict[str, dict[int, dict[str, Any]]]:
    solved: dict[str, dict[int, dict[str, Any]]] = {}
    for entry in entries:
        key = str(entry.get("publicLookupKey") or public_lookup_key(entry))
        detail = details_by_public_key.get(key)
        if not detail:
            continue
        for rec in canonical_param_summary_records_from_detail(detail):
            idx = int(rec["index"])
            rec["solverIr"] = rec.get("projectBaseIr")
            solved.setdefault(key, {})[idx] = rec
    return solved


def propagate_canonical_project_histories(
    solved: dict[str, dict[int, dict[str, Any]]],
    transfer_edges: list[dict[str, Any]],
    recursive_nodes: set[str], scc_of: dict[str, int], *,
    algebra: ProjectSummaryAlgebra, max_iterations: int,
) -> tuple[int, int, int]:
    """Propagate canonical display facts only along the condensation DAG.

    It intentionally ignores call-edge guards for history construction: guards
    remain transfer provenance.  Direct guarded casts/PtrArith are already part
    of directLocalSummary and therefore remain visible (p127).
    """
    considered = changed_count = 0
    iterations = 0
    for iteration in range(max_iterations):
        changed = False
        for edge in transfer_edges:
            if same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
                continue
            caller = str(edge.get("callerNode") or "")
            callee = str(edge.get("calleeNode") or "")
            try:
                caller_idx = int(edge.get("callerParamIndex"))
                callee_idx = int(edge.get("calleeParamIndex"))
            except Exception:
                continue
            callee_rec = solved.get(callee, {}).get(callee_idx)
            if not callee_rec:
                continue
            callee_ir = normalize_ir(callee_rec.get("ir"))
            if callee_ir is None:
                continue
            path_obj = edge.get("actualPathFromCallerParam")
            path_ir = strip_callwrap_ir(path_obj.get("ir") if isinstance(path_obj, dict) else None)
            candidate = algebra.limit_parallel(algebra.compose(path_ir, callee_ir))
            if candidate is None:
                continue
            considered += 1
            old = solved.setdefault(caller, {}).get(caller_idx)
            old_ir = normalize_ir(old.get("ir")) if old else None
            # For an identity forwarder with an explicitly empty local base,
            # this is exactly the callee fact rather than a join with stale raw
            # report content.
            joined = candidate if old_ir is None else algebra.limit_parallel(algebra.join(old_ir, candidate))
            if old and obs_ir_key(old_ir) == obs_ir_key(joined):
                continue
            solved[caller][caller_idx] = {
                "index": caller_idx,
                "rendered": render_ir(joined),
                "ir": joined,
                "solverIr": algebra.semantic_core(joined),
                "projectBaseIr": old.get("projectBaseIr") if old else None,
                "directLocalBasePresent": old.get("directLocalBasePresent", False) if old else False,
                "rawReportIr": old.get("rawReportIr") if old else None,
                "source": "canonical-project-param-transfer",
                "bounded": False,
                "projectTraceKind": "canonical-downstream-transfer",
                "projectTrace": trace_extend(
                    trace_clone(old.get("projectTrace") if old else []),
                    trace_step_transfer(edge, path_ir),
                    *trace_clone(callee_rec.get("projectTrace"))),
            }
            changed = True
            changed_count += 1
        iterations = iteration + 1
        if not changed:
            break
    return considered, changed_count, iterations


def canonical_records_for_index(solved: dict[str, dict[int, dict[str, Any]]],
                                key: str, recursive_nodes: set[str]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for idx in sorted(solved.get(key, {})):
        rec = dict(solved[key][idx])
        ir = normalize_ir(rec.get("ir"))
        if ir is None:
            continue
        rec["ir"] = ir
        rec["rendered"] = render_ir(ir)
        rec.pop("solverIr", None)
        rec.pop("projectBaseIr", None)
        rec.pop("rawReportIr", None)
        rec.pop("directLocalBasePresent", None)
        rec.pop("projectTrace", None)
        rec.pop("projectTraceKind", None)
        if key in recursive_nodes:
            rec.setdefault("bounded", True)
        out.append(rec)
    return out




def _json_clone(x: Any) -> Any:
    return json.loads(json.dumps(x))


def provenance_has_recursive_named_call_evidence(prov: Any) -> bool:
    if not isinstance(prov, dict):
        return False
    if str(prov.get("source") or "") in {
        "same-tu-recursive-fixpoint",
        "same-tu-field-fnptr-recursive-fixpoint",
    }:
        return True
    raw = prov.get("recursiveNamedCallEvidence", False)
    if isinstance(raw, bool):
        return raw
    if isinstance(raw, str):
        return raw.strip().lower() in {"1", "true", "yes"}
    return bool(raw)


def normalized_pointer_use_provenance(use: dict[str, Any]) -> dict[str, Any]:
    prov = use.get("provenance") if isinstance(use.get("provenance"), dict) else {}
    # Keep the identity/provenance fields that explain why two otherwise equal
    # operations should remain distinct.  Drop volatile project-internal fields
    # from the key to avoid non-convergence.
    return {
        "originKind": prov.get("originKind", ""),
        "targetFunction": prov.get("targetFunction", ""),
        "targetQualifiedName": prov.get("targetQualifiedName", ""),
        "targetLookupKey": prov.get("targetLookupKey", ""),
        "fieldEntity": prov.get("fieldEntity", ""),
        "fieldPath": prov.get("fieldPath", ""),
        "calleeExpr": prov.get("calleeExpr", ""),
        "signatureKey": prov.get("signatureKey", ""),
        "edgeKind": prov.get("edgeKind", ""),
    }


def merge_pointer_use_provenance(base: dict[str, Any], overlay: dict[str, Any]) -> dict[str, Any]:
    out = dict(base) if isinstance(base, dict) else {}
    # Capture legacy/source-only evidence before later source overlays replace
    # the spelling with project-pointer-use-transfer-fixpoint.
    recursive_named_call_evidence = (
        provenance_has_recursive_named_call_evidence(base) or
        provenance_has_recursive_named_call_evidence(overlay)
    )
    for k, v in overlay.items():
        if v is None:
            continue
        if not isinstance(v, (str, int, float, bool)):
            continue
        if k == "recursiveNamedCallEvidence":
            # Applied after the pre-loop capture; retained here for clarity
            # when callers explicitly pass the structured bit.
            out[k] = recursive_named_call_evidence or bool(v)
            continue
        sv = str(v)
        if sv == "":
            continue
        if k == "originKind":
            cur = str(out.get(k, ""))
            if cur in {"", "local", "transferred"}:
                out[k] = sv
            continue
        if k in {"source", "transferKind", "edgeKind"}:
            out[k] = sv
            continue
        if str(out.get(k, "")) == "":
            out[k] = sv
    out["recursiveNamedCallEvidence"] = recursive_named_call_evidence
    return out


def _usable_source_span(value: Any) -> bool:
    if not isinstance(value, dict):
        return False
    try:
        return (bool(str(value.get("file") or "")) or
                int(value.get("line") or 0) != 0 or
                int(value.get("column") or 0) != 0)
    except (TypeError, ValueError):
        return False


def normalize_pointer_use_source_leaf_metadata(use: dict[str, Any], *, transfer: bool) -> None:
    """Preserve C6g4s source-leaf diagnostics through project-index processing.

    The immutable operation site and local-guard origin deliberately remain
    outside the project solver key.  Older summaries missing either structured
    field keep their original behavior but are explicitly marked
    ``legacy-fallback`` and use their mutable span/location as a diagnostic
    fallback site.
    """
    has_site = _usable_source_span(use.get("operationSiteSpan"))
    has_local_guard = "operationLocalGuard" in use
    if not has_site or not has_local_guard:
        fallback = (use.get("span") if isinstance(use.get("span"), dict)
                    else use.get("location"))
        if isinstance(fallback, dict):
            use["operationSiteSpan"] = _json_clone(fallback)
        use["operationLocalGuardOrigin"] = "legacy-fallback"
        return

    origin = use.get("operationLocalGuardOrigin")
    if not isinstance(origin, str) or not origin:
        origin = "imported-summary"
    use["operationLocalGuardOrigin"] = (
        "preserved-transfer" if transfer else origin
    )


def pointer_use_key(use: dict[str, Any]) -> str:
    """Stable semantic key for pointer-use records in the project solver.

    We intentionally ignore diagnostic detail strings, mutable locations, and
    C6g4s source-leaf diagnostics so a use does not fail to converge merely
    because it has traveled through another SCC edge.  The attachment IR,
    operation kind, pointer/access types, and guard are the semantic payload.
    """
    attach = use.get("attachPath") if isinstance(use.get("attachPath"), dict) else {}
    guard = use.get("guard") if isinstance(use.get("guard"), (dict, str)) else None
    payload = {
        "kind": use.get("kind"),
        "pointerType": use.get("pointerType"),
        "accessType": use.get("accessType"),
        "attachIr": normalize_ir(attach.get("ir") if isinstance(attach, dict) else None),
        "guard": guard,
        "provenance": normalized_pointer_use_provenance(use),
    }
    return json.dumps(payload, sort_keys=True, separators=(",", ":"))



def detail_public_lookup_key(detail: dict[str, Any]) -> str:
    ident = detail.get("identity") if isinstance(detail.get("identity"), dict) else {}
    qn = ident.get("qualifiedName") or detail.get("function") or ident.get("name") or ""
    sig = ident.get("signatureKey") or ""
    return f"{qn}::{sig}"

def pointer_use_records_from_detail(detail: dict[str, Any]) -> dict[int, list[dict[str, Any]]]:
    params = detail.get("params")
    out: dict[int, list[dict[str, Any]]] = {}
    if not isinstance(params, list):
        return out
    for p in params:
        if not isinstance(p, dict):
            continue
        idx = p.get("index")
        if not isinstance(idx, int) or idx < 0:
            continue
        uses = p.get("pointerUses")
        if not isinstance(uses, list):
            continue
        seen: set[str] = set()
        for use in uses:
            if not isinstance(use, dict):
                continue
            if not isinstance(use.get("pointerType"), str) or not use.get("pointerType"):
                continue
            rec = _json_clone(use)
            rec.setdefault("source", "materialized-from-function-summary-detail")
            rec["_projectVisitedParams"] = [f"{detail_public_lookup_key(detail)}#${idx}"]
            key = pointer_use_key(rec)
            if key in seen:
                continue
            seen.add(key)
            out.setdefault(idx, []).append(rec)
    return out


def pointer_solver_node_key(entry: dict[str, Any]) -> str:
    """Identity used only by the project pointer-use solver.

    Public lookup keys intentionally erase source identity so external functions
    can be imported by name/signature.  That is unsafe for SCC pointer-use
    materialization because source-scoped/static functions with the same public
    name would share one solved-use bucket.  Use the precise lookupKey here:
    external functions keep the external name/signature key; internal/static
    functions include source-file identity.
    """
    return str(entry.get("lookupKey") or lookup_key(entry))


def pointer_detail_solver_node_key(detail: dict[str, Any], fallback_entry: dict[str, Any]) -> str:
    ident = detail.get("identity") if isinstance(detail.get("identity"), dict) else {}
    linkage = normalize_linkage(ident.get("linkage") or fallback_entry.get("linkage"))
    qn = ident.get("qualifiedName") or detail.get("function") or ident.get("name") or fallback_entry.get("qualifiedName") or fallback_entry.get("function") or ""
    sig = ident.get("signatureKey") or fallback_entry.get("signatureKey") or ""
    source = ident.get("sourceFile") or fallback_entry.get("sourceFile") or fallback_entry.get("tuSourceFile") or ""
    if linkage in INTERNAL_LINKAGES:
        return f"internal::{source}::{qn}::{sig}"
    return f"external::{qn}::{sig}"


def pointer_use_map_from_entry_details(entries: list[dict[str, Any]],
                                       details_by_lookup_key: dict[str, dict[str, Any]]) -> dict[str, dict[int, list[dict[str, Any]]]]:
    solved: dict[str, dict[int, list[dict[str, Any]]]] = {}
    for entry in entries:
        key = pointer_solver_node_key(entry)
        detail = details_by_lookup_key.get(key)
        if not detail:
            continue
        by_idx = pointer_use_records_from_detail(detail)
        if not by_idx:
            continue
        # Rewrite the visited seed from public identity to solver identity so
        # same-name static functions in different TUs cannot block or merge each
        # other accidentally during bounded SCC closure.
        for idx, uses in by_idx.items():
            for rec in uses:
                rec["_projectVisitedParams"] = [f"{key}#${idx}"]
        solved[key] = by_idx
    return solved


def entries_by_public_lookup_key(entries: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for e in entries:
        out[str(e.get("publicLookupKey") or public_lookup_key(e))].append(e)
    return out


def is_pointer_solver_entry_unsafe(entry: dict[str, Any]) -> bool:
    # Do not materialize solved pointer-use summaries for genuinely unsafe
    # project identities.  Duplicate external definitions are link errors and
    # should not get a guessed callee.  Source-scoped entries can still be used
    # when an edge is resolved by summary/TU context.
    return str(entry.get("resolution") or "") == "unsafe"


def resolve_pointer_solver_endpoint(edge: dict[str, Any], public_node: str,
                                    by_public: dict[str, list[dict[str, Any]]]) -> tuple[str | None, str | None]:
    candidates = by_public.get(public_node, [])
    if not candidates:
        return None, f"unresolved endpoint {public_node}"

    # Hard unsafe groups, especially duplicate external definitions, should not
    # participate in solved pointer-use materialization.  The index already
    # reports them as problems; C4Q2c avoids turning the problem into a guessed
    # behavior classification.
    safeish = [c for c in candidates if not is_pointer_solver_entry_unsafe(c)]
    if not safeish:
        return None, f"unsafe endpoint {public_node}"

    if len(safeish) == 1:
        return pointer_solver_node_key(safeish[0]), None

    edge_summary = str(edge.get("summaryFile") or "")
    edge_tu = str(edge.get("tuSourceFile") or "")

    # For source-scoped/static functions, the per-TU edge was emitted from the
    # caller's summary.  Resolve same public name/signature by the same summary
    # file first, then by TU source.  This distinguishes a.c::static helper from
    # b.c::static helper in p04_static_same_name.
    same_summary = [c for c in safeish if str(c.get("summaryFile") or "") == edge_summary]
    if len(same_summary) == 1:
        return pointer_solver_node_key(same_summary[0]), None
    same_tu = [c for c in safeish if edge_tu and str(c.get("tuSourceFile") or c.get("sourceFile") or "") == edge_tu]
    if len(same_tu) == 1:
        return pointer_solver_node_key(same_tu[0]), None

    # If all remaining candidates are repeated summaries of the same definition,
    # they will share the same precise lookup key and can be treated as one node.
    precise_keys = sorted({pointer_solver_node_key(c) for c in safeish})
    if len(precise_keys) == 1:
        return precise_keys[0], None

    return None, f"ambiguous endpoint {public_node}; candidates={len(safeish)}"


def resolve_pointer_solver_transfer_edges(entries: list[dict[str, Any]],
                                          transfer_edges: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    by_public = entries_by_public_lookup_key(entries)
    resolved: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []
    seen: set[str] = set()
    for edge in transfer_edges:
        caller_public = str(edge.get("callerNode") or "")
        callee_public = str(edge.get("calleeNode") or "")
        if not caller_public or not callee_public:
            skipped.append({"reason": "missing endpoint", "edge": edge})
            continue
        caller_key, caller_reason = resolve_pointer_solver_endpoint(edge, caller_public, by_public)
        callee_key, callee_reason = resolve_pointer_solver_endpoint(edge, callee_public, by_public)
        if not caller_key or not callee_key:
            skipped.append({
                "reason": caller_reason or callee_reason or "unresolved endpoint",
                "callerNode": caller_public,
                "calleeNode": callee_public,
                "summaryFile": edge.get("summaryFile", ""),
                "tuSourceFile": edge.get("tuSourceFile", ""),
            })
            continue
        out = dict(edge)
        out["callerPublicNode"] = caller_public
        out["calleePublicNode"] = callee_public
        out["callerNode"] = caller_key
        out["calleeNode"] = callee_key
        key = "::".join([
            str(out.get("callerNode") or ""),
            str(out.get("calleeNode") or ""),
            str(out.get("callerParamIndex", "")),
            str(out.get("calleeParamIndex", "")),
            str(out.get("summaryFile") or ""),
            str(out.get("location") or ""),
        ])
        if key in seen:
            continue
        seen.add(key)
        resolved.append(out)
    stats = {
        "numInputEdges": len(transfer_edges),
        "numResolvedEdges": len(resolved),
        "numSkippedEdges": len(skipped),
        "skippedEdges": skipped[:25],
        "identity": "precise lookupKey for pointer-use solver; source-scoped endpoints require same summary/TU resolution",
    }
    return resolved, stats


def history_summary_from_ir(ir: Any) -> dict[str, Any]:
    ir = normalize_ir(ir)
    return {"rendered": render_ir(ir) if ir is not None else "<id>", "ir": ir}


def strip_project_pointer_use_detail_prefixes(detail: str) -> str:
    prefixes = ("project-scc via ", "project-solved; ")
    changed = True
    while changed and detail:
        changed = False
        for prefix in prefixes:
            if detail.startswith(prefix):
                semi = detail.find("; ")
                if semi < 0:
                    return ""
                detail = detail[semi + 2:]
                changed = True
                break
    return detail


def transfer_pointer_use_record(edge: dict[str, Any], callee_idx: int,
                                callee_use: dict[str, Any]) -> dict[str, Any] | None:
    caller = str(edge.get("callerNode") or "")
    callee = str(edge.get("calleeNode") or "")
    callee_display = str(edge.get("calleePublicNode") or callee)
    if not caller or not callee:
        return None
    try:
        caller_idx = int(edge.get("callerParamIndex"))
    except Exception:
        return None

    visited_raw = callee_use.get("_projectVisitedParams")
    visited = list(visited_raw) if isinstance(visited_raw, list) else []
    caller_param_key = f"{caller}#${caller_idx}"
    if caller_param_key in visited:
        # This would start the next SCC lap.  C4Q2b keeps pointer-use closure to
        # simple parameter paths, mirroring the bounded SCC discipline of the
        # cast-history solver while preserving pointer uses as a separate domain.
        return None

    use = _json_clone(callee_use)
    # Preserve source-leaf metadata before the transfer rewrites attachment,
    # reporting detail, and provenance at the project-SCC boundary.
    normalize_pointer_use_source_leaf_metadata(use, transfer=True)
    path_obj = edge.get("actualPathFromCallerParam") if isinstance(edge.get("actualPathFromCallerParam"), dict) else {}
    path_ir = strip_callwrap_ir(path_obj.get("ir") if isinstance(path_obj, dict) else None)
    attach_obj = use.get("attachPath") if isinstance(use.get("attachPath"), dict) else {}
    attach_ir = strip_callwrap_ir(attach_obj.get("ir") if isinstance(attach_obj, dict) else None)
    composed = compose_ir(path_ir, attach_ir)
    use["attachPath"] = history_summary_from_ir(composed)

    base_detail = strip_project_pointer_use_detail_prefixes(str(use.get("detail") or ""))
    use["detail"] = (f"project-scc via {callee_display}.${callee_idx}" +
                     (f"; {base_detail}" if base_detail else ""))
    use["source"] = "project-pointer-use-transfer-fixpoint"

    edge_is_field_fp = bool(edge.get("isFieldFunctionPointerCall"))
    overlay = {
        "originKind": "field-fnptr" if edge_is_field_fp else "project-scc",
        "targetFunction": str(edge.get("callee", "")),
        "targetQualifiedName": str(edge.get("calleeQualifiedName", "")),
        "targetLookupKey": str(edge.get("calleeNode", "")),
        "fieldEntity": str(edge.get("fieldEntity", "")),
        "fieldPath": str(edge.get("fieldPath", "")),
        "calleeExpr": str(edge.get("calleeExpr", "")),
        "signatureKey": str(edge.get("fieldSignatureKey", "") or edge.get("calleeSignatureKey", "")),
        "source": "project-pointer-use-transfer-fixpoint",
        "transferKind": "summary-param-transfer",
        "edgeKind": "field-function-pointer-call" if edge_is_field_fp else "summary-param-transfer",
        # Monotone evidence bit.  It is deliberately absent from pointer_use_key
        # so recursive and nonrecursive routes share one semantic solver fact.
        "recursiveNamedCallEvidence": bool(edge.get("recursiveNamedCallEvidence")) or
                                      provenance_has_recursive_named_call_evidence(
                                          use.get("provenance")),
    }
    use["provenance"] = merge_pointer_use_provenance(
        use.get("provenance") if isinstance(use.get("provenance"), dict) else {},
        overlay)

    use["_projectVisitedParams"] = visited + [caller_param_key]
    return use


def add_pointer_use_record(vec: list[dict[str, Any]], rec: dict[str, Any]) -> bool:
    key = pointer_use_key(rec)
    for existing in vec:
        if pointer_use_key(existing) != key:
            continue
        incoming = rec.get("provenance") if isinstance(rec.get("provenance"), dict) else {}
        existing_prov = existing.get("provenance") if isinstance(existing.get("provenance"), dict) else {}
        if (provenance_has_recursive_named_call_evidence(incoming) and
                not provenance_has_recursive_named_call_evidence(existing_prov)):
            merged = dict(existing_prov)
            merged["recursiveNamedCallEvidence"] = True
            existing["provenance"] = merged
            # Treat the monotone evidence upgrade as a solver change so it can
            # propagate through later project-SCC edges in this closure.
            return True
        return False
    vec.append(rec)
    return True


def clean_project_pointer_use_record(use: dict[str, Any]) -> dict[str, Any]:
    out = _json_clone(use)
    normalize_pointer_use_source_leaf_metadata(out, transfer=False)
    for k in list(out.keys()):
        if isinstance(k, str) and k.startswith("_project"):
            out.pop(k, None)
    out.setdefault("source", "project-pointer-use-transfer-fixpoint")
    prov = out.get("provenance") if isinstance(out.get("provenance"), dict) else {}
    prov = dict(prov)
    prov.setdefault("source", out.get("source", "project-pointer-use-transfer-fixpoint"))
    out["provenance"] = prov
    return out


def materialize_project_solved_pointer_use_summaries(
    entries: list[dict[str, Any]],
    details_by_lookup_key: dict[str, dict[str, Any]],
    dep_sccs: dict[str, Any],
    transfer_edges: list[dict[str, Any]],
    *,
    max_iterations: int = 32,
) -> dict[str, Any]:
    """Attach project-level solvedPointerUseSummaries to function entries.

    This is C4Q2b's separate pointer-use domain.  Cast histories remain solved by
    solvedParamSummaries.  Here we start from parameter-local pointerUses already
    emitted by each TU, then propagate callee-parameter operations back to caller
    parameters along summaryParamTransferEdges until a bounded simple-path
    closure is reached.
    """
    max_iterations = env_int("CAST_HISTORY_SOLVED_POINTER_USE_MAX_ITERATIONS", max_iterations)
    max_seconds = env_float("CAST_HISTORY_SOLVED_POINTER_USE_MAX_SECONDS", 30.0)
    start_time = time.monotonic()
    recursive_nodes = recursive_concrete_scc_nodes(dep_sccs)
    concrete_scc_by_node = concrete_scc_node_map(dep_sccs)
    solved = pointer_use_map_from_entry_details(entries, details_by_lookup_key)
    transfer_edges, edge_resolution_stats = resolve_pointer_solver_transfer_edges(entries, transfer_edges)
    # A transfer is recursive only when both endpoints are members of the same
    # recursive concrete function SCC.  Preserve that distinction separately
    # from the project's source/edge labels.
    annotated_edges: list[dict[str, Any]] = []
    for raw_edge in transfer_edges:
        edge = dict(raw_edge)
        caller = str(edge.get("callerNode") or "")
        callee = str(edge.get("calleeNode") or "")
        edge["recursiveNamedCallEvidence"] = (
            caller in recursive_nodes and callee in recursive_nodes and
            concrete_scc_by_node.get(caller) == concrete_scc_by_node.get(callee)
        )
        annotated_edges.append(edge)
    transfer_edges = annotated_edges

    considered = 0
    changed_edges = 0
    iterations = 0
    converged = True
    stopped_by_time_limit = False

    for iteration in range(max_iterations):
        if max_seconds and (time.monotonic() - start_time) > max_seconds:
            stopped_by_time_limit = True
            iterations = iteration
            converged = False
            break
        changed = False
        for edge in transfer_edges:
            caller_key = str(edge.get("callerNode") or "")
            callee_key = str(edge.get("calleeNode") or "")
            if not caller_key or not callee_key:
                continue
            try:
                caller_idx = int(edge.get("callerParamIndex"))
                callee_idx = int(edge.get("calleeParamIndex"))
            except Exception:
                continue
            callee_uses = solved.get(callee_key, {}).get(callee_idx, [])
            if not callee_uses:
                continue
            for callee_use in list(callee_uses):
                candidate = transfer_pointer_use_record(edge, callee_idx, callee_use)
                if candidate is None:
                    continue
                considered += 1
                dest = solved.setdefault(caller_key, {}).setdefault(caller_idx, [])
                if add_pointer_use_record(dest, candidate):
                    changed = True
                    changed_edges += 1
        iterations = iteration + 1
        if not changed:
            converged = True
            break
    else:
        iterations = max_iterations
        converged = False

    num_functions = 0
    num_records = 0
    recursive_functions = 0
    for entry in entries:
        key = pointer_solver_node_key(entry)
        by_idx = solved.get(key, {})
        records: list[dict[str, Any]] = []
        for idx in sorted(by_idx):
            for use in by_idx[idx]:
                cleaned = clean_project_pointer_use_record(use)
                records.append({
                    "index": idx,
                    "source": cleaned.get("source", "project-pointer-use-transfer-fixpoint"),
                    "use": cleaned,
                })
        if records:
            entry["solvedPointerUseSummaries"] = records
            num_functions += 1
            num_records += len(records)
            if key in recursive_nodes:
                recursive_functions += 1

    return {
        "algorithm": "bounded-simple-parameter-path-pointer-use-transfer",
        "solverDomain": "parameter-pointer-uses separate from parameter-cast-histories",
        "numFunctions": num_functions,
        "numRecords": num_records,
        "recursiveSCCFunctions": recursive_functions,
        "iterations": iterations,
        "maxIterations": max_iterations,
        "converged": converged,
        "consideredTransferUses": considered,
        "changedTransferUses": changed_edges,
        "edgeResolution": edge_resolution_stats,
        "maxSeconds": max_seconds,
        "stoppedByTimeLimit": stopped_by_time_limit,
        "recursiveSCCNodes": len(recursive_nodes),
        "widening": "simple-parameter-path-visited-set; caller actual inherits callee formal uses",
        "note": (
            "C4Q2c materializes project-level pointer-use summaries with "
            "source-scoped endpoint resolution in "
            "project-summary-index.json.  It does not modify solvedParamSummaries "
            "or encode operations as cast-history observations."
        ),
    }


def param_summary_ir_from_detail(detail: dict[str, Any], index: int) -> Any:
    params = detail.get("params")
    if not isinstance(params, list):
        return None
    for p in params:
        if not isinstance(p, dict):
            continue
        if p.get("index") != index:
            continue
        summary = p.get("summary") if isinstance(p.get("summary"), dict) else {}
        return normalize_ir(summary.get("ir"))
    return None


def return_summary_ir_has_param_ref(ir: Any, index: int | None = None) -> bool:
    ir = normalize_ir(ir)
    if not isinstance(ir, dict):
        return False
    kind = ir_kind(ir)
    if kind == "paramRef":
        return index is None or ir.get("index") == index
    if kind == "seq":
        return return_summary_ir_has_param_ref(ir.get("first"), index) or return_summary_ir_has_param_ref(ir.get("second"), index)
    if kind == "callWrap":
        return return_summary_ir_has_param_ref(ir.get("inner"), index)
    if kind == "fieldRef":
        return return_summary_ir_has_param_ref(ir.get("base"), index)
    if kind == "parallel":
        return any(return_summary_ir_has_param_ref(a, index) for a in ir.get("arms", []) if isinstance(a, dict))
    if kind == "join":
        return any(return_summary_ir_has_param_ref(a.get("history"), index)
                   for a in ir.get("alternatives", []) if isinstance(a, dict))
    return False


def is_trivial_declared_return_ir(ir: Any) -> bool:
    ir = normalize_ir(ir)
    if ir is None:
        return True
    text = render_ir(ir)
    if text in {"", "<id>", "<none>", "void", "void *"}:
        return True
    return isinstance(ir, dict) and ir_kind(ir) == "asType"


def derive_alias_return_ir_from_param_summary(detail: dict[str, Any], aliased_idx: int,
                                              declared_type: str) -> Any:
    """Build $i => param-summary($i) => declared-return for alias returns.

    This is the project-level analogue of the single-TU return-alias mechanism:
    if a function returns an alias of parameter $i, its solved return fact should
    be a path from $i, not merely the declared return type.  This also repairs
    forwarding-return cases where an imported raw report summary was rich but
    the materialized project solvedReturnSummary would otherwise collapse to
    just "void *".
    """
    base: Any = {"kind": "paramRef", "index": aliased_idx}
    param_ir = strip_callwrap_ir(param_summary_ir_from_detail(detail, aliased_idx))
    out = compose_ir(base, param_ir)
    if declared_type:
        declared_ir = as_type_ir_from_text(declared_type)
        # Avoid appending the same declared return type if the path already ends
        # at that type.
        if declared_ir and not ir_is_prefix(declared_ir, out):
            items = flatten_seq(out)
            last = items[-1] if items else out
            if obs_ir_key(last) != obs_ir_key(declared_ir):
                out = compose_ir(out, declared_ir)
    return normalize_ir(out)


def return_summary_record_from_detail(detail: dict[str, Any]) -> dict[str, Any] | None:
    """Extract a project-level solved return fact from one function detail.

    C4P3 keeps return solving in the *return-slice* domain.  A function's full
    parameter summary can contain non-return side effects such as writes through
    an ``int *`` view; those observations must not be synthesized into the
    return value path.

    Therefore, when the raw/local/imported ReturnSummaryDetail already contains
    a nontrivial path from the aliased parameter to the returned value, that
    return-specific path is authoritative for solvedReturnSummary.  Deriving a
    path from the full parameter summary is only a conservative fallback for the
    weaker case where the return summary is merely a declared-return type or
    lacks a usable reference to the aliased parameter.
    """
    ret = detail.get("return")
    if not isinstance(ret, dict):
        return None
    summary = ret.get("summary") if isinstance(ret.get("summary"), dict) else {}
    raw_ir = normalize_ir(summary.get("ir"))
    if not obs_ir_is_nonempty(raw_ir):
        return None
    may_alias = bool(ret.get("mayAliasParam"))
    raw_idx = ret.get("aliasedParamIndex")
    aliased_idx = raw_idx if isinstance(raw_idx, int) and raw_idx >= 0 else None
    declared_type = ret.get("declaredType", "") if isinstance(ret.get("declaredType"), str) else ""

    raw_core = strip_callwrap_ir(raw_ir)
    solved_core = raw_core
    derived_from_alias = False
    derived_fallback_only = False

    if may_alias and aliased_idx is not None:
        raw_has_return_slice = (
            obs_ir_is_nonempty(raw_core)
            and not is_trivial_declared_return_ir(raw_core)
            and return_summary_ir_has_param_ref(raw_core, aliased_idx)
        )

        if not raw_has_return_slice:
            derived = derive_alias_return_ir_from_param_summary(detail, aliased_idx, declared_type)
            if obs_ir_is_nonempty(derived):
                # Fallback only: the full parameter summary is an approximation
                # of the return slice, so it is used only when no return-specific
                # path is available.  Do not join it with an existing return
                # slice; doing so leaks side-effect casts into the return value.
                solved_core = derived
                derived_from_alias = True
                derived_fallback_only = True

    if not obs_ir_is_nonempty(solved_core):
        return None

    rec = {
        "rendered": render_ir(solved_core),
        "ir": solved_core,
        "source": "materialized-return-slice-fact",
        "mayAliasParam": may_alias,
        "aliasedParamIndex": aliased_idx,
        "declaredType": declared_type,
        "rawRendered": summary.get("rendered", "") if isinstance(summary.get("rendered"), str) else render_ir(raw_ir),
        "rawIr": raw_ir,
    }
    if obs_ir_key(raw_ir) != obs_ir_key(solved_core):
        rec["provenanceRendered"] = render_ir(raw_ir)
        rec["provenanceIr"] = raw_ir
    if derived_from_alias:
        rec["derivedFromAliasedParamSummary"] = True
        rec["derivedFallbackOnly"] = derived_fallback_only
        rec["derivation"] = (
            f"return aliases ${aliased_idx}; no nontrivial return-slice path was available, "
            f"so the solved return path was conservatively derived from parameter "
            f"${aliased_idx} summary plus declared return type"
        )
    else:
        rec["usedReturnSlicePath"] = True
        rec["derivation"] = (
            "used existing return-specific summary path; full parameter summary was "
            "not folded into the return value"
        )
    return rec


def materialize_project_solved_return_summaries(
    entries: list[dict[str, Any]],
    details_by_public_key: dict[str, dict[str, Any]],
) -> dict[str, Any]:
    """Attach solvedReturnSummary to entries and return debug statistics.

    This is the return-domain analogue of solvedParamSummaries.  In C4P3, the
    materialized fact is the wrapper-free semantic core of the callee's own
    return-specific summary, plus explicit return-alias metadata.  Cross-TU
    callers then compose this imported solved return fact through the existing
    return-alias origin machinery.  Full parameter summaries are not folded into
    solvedReturnSummary unless no return-slice path is available.
    """
    functions: list[dict[str, Any]] = []
    alias_count = 0
    for entry in entries:
        key = str(entry.get("publicLookupKey") or public_lookup_key(entry))
        detail = details_by_public_key.get(key)
        if not detail:
            continue
        rec = return_summary_record_from_detail(detail)
        if not rec:
            continue
        entry["solvedReturnSummary"] = rec
        if rec.get("mayAliasParam"):
            alias_count += 1
        functions.append({
            "function": entry.get("function", ""),
            "qualifiedName": entry.get("qualifiedName", ""),
            "signatureKey": entry.get("signatureKey", ""),
            "publicLookupKey": key,
            "rendered": rec.get("rendered", ""),
            "mayAliasParam": bool(rec.get("mayAliasParam")),
            "aliasedParamIndex": rec.get("aliasedParamIndex"),
            "source": rec.get("source", ""),
        })
    return {
        "algorithm": "return-summary-fact-join-and-alias-path-materialization",
        "solverDomain": "wrapper-free return facts joined with explicit return-alias metadata; provenance IR kept separately when available",
        "numFunctions": len(functions),
        "numAliasReturningFunctions": alias_count,
        "functions": functions,
        "note": (
            "C4P2 materializes return-domain facts in project-summary-index.json. "
            "Alias-return facts are represented as paths from the aliased parameter, "
            "for example $0 => int * => void *.  The final cast-history-tool "
            "import path instantiates these facts at call sites through the same "
            "return-alias mechanism used for single-TU callees; wrappers remain "
            "display-only and are not fed back into SCC solving."
        ),
    }


def recursive_concrete_scc_nodes(dep_sccs: dict[str, Any]) -> set[str]:
    concrete = dep_sccs.get("concreteFunctionGraph") if isinstance(dep_sccs, dict) else None
    if not isinstance(concrete, dict):
        return set()
    nodes: set[str] = set()
    comps = concrete.get("components")
    if not isinstance(comps, list):
        comps = concrete.get("nontrivialComponents")
    if not isinstance(comps, list):
        return nodes
    for comp in comps:
        if not isinstance(comp, dict) or not comp.get("recursive"):
            continue
        members = comp.get("members")
        if not isinstance(members, list):
            continue
        for m in members:
            if isinstance(m, str) and m:
                nodes.add(m)
    return nodes


def concrete_scc_node_map(dep_sccs: dict[str, Any]) -> dict[str, int]:
    concrete = dep_sccs.get("concreteFunctionGraph") if isinstance(dep_sccs, dict) else None
    if not isinstance(concrete, dict):
        return {}
    raw = concrete.get("nodeToScc")
    if not isinstance(raw, dict):
        return {}
    out: dict[str, int] = {}
    for k, v in raw.items():
        if isinstance(k, str) and isinstance(v, int):
            out[k] = v
    return out


def record_map_from_details(entries: list[dict[str, Any]],
                            details_by_public_key: dict[str, dict[str, Any]]) -> dict[str, dict[int, dict[str, Any]]]:
    solved: dict[str, dict[int, dict[str, Any]]] = {}
    for entry in entries:
        key = str(entry.get("publicLookupKey") or public_lookup_key(entry))
        detail = details_by_public_key.get(key)
        if not detail:
            continue
        for rec in param_summary_records_from_detail(detail):
            ir = normalize_ir(rec.get("ir"))
            idx = int(rec["index"])
            base_ir = strip_callwrap_ir(ir)
            rec["solverIr"] = base_ir
            rec["projectBaseIr"] = base_ir
            rec["projectSegments"] = []
            rec["projectTraceKind"] = "local-base"
            rec["projectTrace"] = [trace_step_local(key, idx, base_ir, role="local-base")] if base_ir is not None else []
            solved.setdefault(key, {})[idx] = rec
    return solved



def recursive_closure_metadata_for_edge(edge: dict[str, Any]) -> tuple[str, str, str]:
    """Return (closure-key, family-id, family-kind) for one tagged transfer.

    C6g5w1d deliberately consumes only source-defined metadata already emitted
    on ordinary summaryParamTransferEdges.  Missing/legacy metadata therefore
    remains on the pre-existing C6g5s import-authoritative solver path.
    """
    family = edge.get("branchFamily")
    if not isinstance(family, dict):
        return "", "", ""
    family_id = str(family.get("id") or "")
    family_kind = str(family.get("kind") or "")
    closure_key = str(family.get("recursiveClosureKey") or family_id)
    if not family_id or not closure_key:
        return "", "", ""
    # The only behaviors enabled in this first consumer patch are the two
    # shapes whose metadata has been exercised by p126/p127/p130.  Unknown
    # branchFamily kinds stay untagged and use the legacy solver unchanged.
    if family_kind not in {"parallel-call-actuals", "guarded-local-ptrarith"}:
        return "", "", ""
    return closure_key, family_id, family_kind


def recursive_closure_tagged_nodes_and_families(
    transfer_edges: list[dict[str, Any]],
    recursive_nodes: set[str],
    scc_of: dict[str, int],
) -> tuple[set[str], set[str], set[str]]:
    """Return participating recursive endpoints, family IDs, and closure keys.

    A family is eligible only when its annotated ordinary transfer edge is
    inside one concrete recursive SCC.  Both endpoints are excluded from the
    generic recursive materializer so the tagged result cannot be joined with
    a second, legacy whole-summary expansion for the same SCC member.
    """
    nodes: set[str] = set()
    family_ids: set[str] = set()
    closure_keys: set[str] = set()
    for edge in transfer_edges:
        if not same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
            continue
        closure_key, family_id, _kind = recursive_closure_metadata_for_edge(edge)
        if not closure_key:
            continue
        caller = str(edge.get("callerNode") or "")
        callee = str(edge.get("calleeNode") or "")
        if not caller or not callee:
            continue
        nodes.update({caller, callee})
        family_ids.add(family_id)
        closure_keys.add(closure_key)
    return nodes, family_ids, closure_keys


def _annotate_tagged_recursive_closure_consumption(
    transfer_edges: list[dict[str, Any]], consumed_family_ids: set[str]
) -> None:
    """Mark index-owned records after C2 has actually consumed their key.

    This mutates only the in-memory C2 index representation, never the input
    TU summary.  The marker is report/provenance data; it is not another
    history atom and does not participate in equality.
    """
    if not consumed_family_ids:
        return
    for edge in transfer_edges:
        family = edge.get("branchFamily")
        if isinstance(family, dict) and str(family.get("id") or "") in consumed_family_ids:
            family["consumedByTaggedRecursiveSolver"] = True


def solve_tagged_recursive_scc_by_closure_key_paths_for_import(
    solved: dict[str, dict[int, dict[str, Any]]],
    transfer_edges: list[dict[str, Any]],
    recursive_nodes: set[str],
    scc_of: dict[str, int],
    *,
    algebra: ProjectSummaryAlgebra,
    known_param_counts: dict[str, int] | None = None,
) -> dict[str, Any]:
    """Materialize authoritative C2 summaries for narrow tagged SCC paths.

    This is not C6g5t's display-only overlay.  Its results replace only the
    normal ``solvedParamSummaries`` records for SCC members reached by the
    proved C6g5w1c metadata shapes:

      * p126/p130 ``parallel-call-actuals``; and
      * p127 ``guarded-local-ptrarith``.

    State is arm/path-local: each work item carries the set of closure keys it
    has already consumed.  Repeating a key stops *before* the second edge is
    composed.  The existing simple parameter-visit rule is retained as the
    independent root/SCC-lap boundary; it is necessary for p126's relay_b
    root, whose first visit of relay_a's family returns to an already visited
    relay_b formal.
    """
    outgoing: dict[tuple[str, int], list[dict[str, Any]]] = defaultdict(list)
    same_edges: list[dict[str, Any]] = []
    for edge in transfer_edges:
        if not same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
            continue
        try:
            caller_idx = int(edge.get("callerParamIndex"))
            int(edge.get("calleeParamIndex"))
        except Exception:
            continue
        same_edges.append(edge)
        outgoing[(str(edge.get("callerNode") or ""), caller_idx)].append(edge)
    for edges in outgoing.values():
        edges.sort(key=transfer_edge_key)

    tagged_nodes, consumed_family_ids, consumed_closure_keys = (
        recursive_closure_tagged_nodes_and_families(
            same_edges, recursive_nodes, scc_of))
    if not tagged_nodes:
        return {
            "taggedNodes": set(), "consumedFamilyIds": set(),
            "consumedClosureKeys": set(), "consideredEdges": 0,
            "changed": 0, "paths": 0, "closureKeyStops": 0,
            "seededGuardedTransformerClosures": 0,
        }

    # Use immutable direct-local bases, not rich C1 summaries that may already
    # encode a recursive report expansion.  This is the key difference from
    # the generic import path and is enabled only for the tagged roots above.
    local_base: dict[str, dict[int, Any]] = {}
    local_trace: dict[str, dict[int, list[dict[str, Any]]]] = {}
    for node, by_idx in solved.items():
        for idx, rec in by_idx.items():
            ir = rec.get("projectBaseIr")
            if ir is None and not rec.get("directLocalBasePresent", False):
                # This function is called with canonical/direct records.  Keep
                # a legacy fallback only for compatibility with synthetic tests.
                ir = strip_callwrap_ir(rec.get("rawReportIr") or rec.get("ir"))
            ir = algebra.bound_same_scc(ir)
            local_base.setdefault(node, {})[int(idx)] = ir
            trace = trace_clone(rec.get("projectTrace"))
            if not trace and ir is not None:
                trace = [trace_step_local(node, int(idx), ir,
                                          role="direct-local-base")]
            local_trace.setdefault(node, {})[int(idx)] = trace

    changed = paths = closure_key_stops = seeded_transformer_closures = 0
    max_depth = max(1, len({(str(e.get("callerNode") or ""),
                             str(e.get("calleeNode") or ""))
                            for e in same_edges}) + 1)

    for root in sorted(tagged_nodes):
        for root_idx in sorted(param_indices_for_node(root, solved, same_edges)):
            root_base = local_base.get(root, {}).get(root_idx)
            root_edges = outgoing.get((root, root_idx), [])
            root_transformer = canonical_guarded_ptrarith_transformer(root_base)
            root_closure_keys = {
                key for edge in root_edges
                for key, _family, kind in [recursive_closure_metadata_for_edge(edge)]
                if key and kind == "guarded-local-ptrarith"
            }

            # p127: f and g each directly define the same complete guarded
            # transformer.  Seed its key at the root so the outgoing matching
            # edge is recognized as a second application, not as another
            # unrolling.  This retains the local Join exactly once.
            if root_transformer is not None and len(root_closure_keys) == 1:
                closure_key = next(iter(root_closure_keys))
                best = root_transformer
                best_trace = trace_extend(
                    local_trace.get(root, {}).get(root_idx, []),
                    trace_step_stop(
                        "seeded guarded local transformer closure key; retained "
                        "the direct guarded relation and stopped before a second "
                        "recursive application",
                        node=root, index=root_idx))
                paths += 1
                seeded_transformer_closures += 1
            else:
                best: Any = None
                best_trace: list[dict[str, Any]] = []

                def absorb_candidate(candidate: Any,
                                     candidate_trace: list[dict[str, Any]]) -> None:
                    """Join distinct tagged root-arm candidates instead of ranking them.

                    C6g5w1d's closure traversal is arm-local.  In particular,
                    p126/p130's ``int *`` and ``char *`` source arms are two
                    sibling facts, not competing candidate paths.  The generic
                    importer may choose a representative path for untagged SCCs;
                    this tagged path must retain the bounded parallel join.
                    """
                    nonlocal best, best_trace, paths
                    candidate = algebra.bound_same_scc(candidate)
                    if not has_local_contribution(candidate):
                        return
                    joined = (candidate if best is None else
                              algebra.bound_same_scc(algebra.join(best, candidate)))
                    if (best is None or
                            obs_ir_key(normalize_ir(best)) !=
                            obs_ir_key(normalize_ir(joined))):
                        best = joined
                        # Preserve one representative explanatory trace.  The
                        # IR is authoritative for the arm join; trace remains
                        # diagnostic-only and must not suppress a sibling arm.
                        best_trace = trace_clone(candidate_trace)
                    paths += 1

                stack: list[tuple[str, int, Any, list[dict[str, Any]],
                                  frozenset[str], frozenset[tuple[str, int]],
                                  frozenset[str], int]] = [
                    (root, root_idx, None, [], frozenset(),
                     frozenset({(root, root_idx)}), frozenset(), 0)
                ]
                while stack:
                    (node, idx, acc, trace, used_edges, visited_params,
                     active_closure_keys, depth) = stack.pop()
                    if depth >= max_depth:
                        continue
                    for edge in outgoing.get((node, idx), []):
                        edge_key = transfer_edge_key(edge)
                        if edge_key in used_edges:
                            continue
                        callee = str(edge.get("calleeNode") or "")
                        try:
                            callee_idx = int(edge.get("calleeParamIndex"))
                        except Exception:
                            continue

                        closure_key, _family_id, _family_kind = (
                            recursive_closure_metadata_for_edge(edge))
                        if closure_key and closure_key in active_closure_keys:
                            closure_key_stops += 1
                            if acc is not None:
                                stopped_trace = trace_extend(
                                    trace,
                                    trace_step_stop(
                                        "recursive closure key already active on this arm-local path; "
                                        "stopped before re-importing/re-expanding the same tagged transfer",
                                        node=callee, index=callee_idx))
                                candidate = algebra.bound_same_scc(acc)
                                absorb_candidate(candidate, stopped_trace)
                            continue

                        path_obj = (edge.get("actualPathFromCallerParam")
                                    if isinstance(edge.get("actualPathFromCallerParam"), dict)
                                    else {})
                        path_ir = strip_callwrap_ir(path_obj.get("ir")
                                                     if isinstance(path_obj, dict)
                                                     else None)
                        if acc is None and path_ir is None:
                            next_acc = root_base
                        else:
                            next_acc = algebra.compose(acc, path_ir)
                        transfer_step = trace_step_transfer(edge, path_ir)
                        if closure_key:
                            transfer_step["recursiveClosureKey"] = closure_key
                        next_trace = trace_extend(trace, transfer_step)
                        next_active = (frozenset(set(active_closure_keys) | {closure_key})
                                       if closure_key else active_closure_keys)

                        next_param = (callee, callee_idx)
                        if next_param in visited_params:
                            stopped_trace = trace_extend(
                                next_trace,
                                trace_step_stop(
                                    "would revisit a parameter and replay its "
                                    "direct-local base; kept the call-boundary "
                                    "path and stopped",
                                    node=callee, index=callee_idx))
                            candidate = algebra.bound_same_scc(next_acc)
                            absorb_candidate(candidate, stopped_trace)
                            continue

                        # Path snapshots already contain the caller-side direct
                        # cast that prepares a non-identity actual.  Borrow a
                        # callee direct base only for identity edges, preserving
                        # p23/p129's existing connector behavior while avoiding
                        # p126 family/root reinsertion.
                        callee_base = local_base.get(callee, {}).get(callee_idx)
                        base_to_append = callee_base if path_ir is None else None
                        if base_to_append is not None:
                            specialized_base, saw_hof_ref, all_hof_refs_resolved = (
                                substitute_unique_higher_order_refs_for_edge(
                                    base_to_append, edge, solved,
                                    known_param_counts))
                            if saw_hof_ref and all_hof_refs_resolved:
                                base_to_append = specialized_base
                            next_acc = algebra.compose(next_acc, base_to_append)
                            callee_trace = local_trace.get(callee, {}).get(callee_idx)
                            if callee_trace:
                                next_trace = trace_extend(
                                    next_trace, *trace_clone(callee_trace))
                            else:
                                next_trace = trace_extend(
                                    next_trace,
                                    trace_step_local(callee, callee_idx,
                                                     base_to_append,
                                                     role="identity-edge-direct-local-base"))

                        next_used = frozenset(set(used_edges) | {edge_key})
                        next_visited = frozenset(set(visited_params) | {next_param})
                        stack.append((callee, callee_idx,
                                      algebra.bound_same_scc(next_acc),
                                      trace_clone(next_trace), next_used,
                                      next_visited, next_active, depth + 1))

                if best is None:
                    best = root_base
                    best_trace = trace_clone(local_trace.get(root, {}).get(root_idx, []))

            best = algebra.bound_same_scc(best)
            if best is None:
                continue
            old_rec = solved.setdefault(root, {}).get(root_idx)
            old_ir = old_rec.get("ir") if old_rec else None
            if old_rec and obs_ir_key(normalize_ir(old_ir)) == obs_ir_key(best):
                if best_trace and not old_rec.get("projectTrace"):
                    old_rec["projectTrace"] = best_trace
                continue
            solved[root][root_idx] = {
                "index": root_idx,
                "rendered": render_ir(best),
                "ir": best,
                "solverIr": best,
                "projectBaseIr": root_base,
                "directLocalBasePresent": True,
                "source": "tagged-recursive-closure-key-simple-scc-path",
                "bounded": True,
                "projectTraceKind": "tagged-recursive-closure-key-simple-path",
                "projectTrace": best_trace,
                "projectExplanationStopReasons": trace_stop_reasons(best_trace),
            }
            changed += 1

    return {
        "taggedNodes": tagged_nodes,
        "consumedFamilyIds": consumed_family_ids,
        "consumedClosureKeys": consumed_closure_keys,
        "consideredEdges": sum(
            1 for edge in same_edges
            if str(edge.get("callerNode") or "") in tagged_nodes or
               str(edge.get("calleeNode") or "") in tagged_nodes),
        "changed": changed,
        "paths": paths,
        "closureKeyStops": closure_key_stops,
        "seededGuardedTransformerClosures": seeded_transformer_closures,
    }

def materialize_project_solved_param_summaries(
    entries: list[dict[str, Any]],
    details_by_public_key: dict[str, dict[str, Any]],
    dep_sccs: dict[str, Any],
    transfer_edges: list[dict[str, Any]],
    *,
    max_iterations: int = 32,
) -> dict[str, Any]:
    """Attach project-level solvedParamSummaries to function entries.

    C4M replaces recursive whole-summary substitution with a two-stage project
    solver:

      1. For each recursive concrete SCC, enumerate bounded simple parameter
         paths using local/base contributions and transfer edges.  The same
         transfer edge and same function-parameter node are not repeated in one
         expansion, so the solver cannot unroll another SCC lap.
      2. Propagate the resulting solved summaries to callers outside the SCC
         using the full project transfer graph.

    Final text output and classifications remain in cast-history-tool; this
    script only materializes solved summary facts.
    """
    max_iterations = env_int("CAST_HISTORY_SOLVED_PARAM_MAX_ITERATIONS", max_iterations)
    algebra = ProjectSummaryAlgebra.from_env(max_same_scc_atoms=16, max_parallel_arms=8)
    max_same_scc_atoms = algebra.max_same_scc_atoms
    max_seconds = env_float("CAST_HISTORY_SOLVED_PARAM_MAX_SECONDS", 30.0)
    start_time = time.monotonic()
    stopped_by_time_limit = False

    recursive_nodes = recursive_concrete_scc_nodes(dep_sccs)
    scc_of = concrete_scc_node_map(dep_sccs)
    transfer_edges, transfer_edge_filter_stats = filter_param_transfer_edges_for_public_solver(entries, transfer_edges)
    for _edge_order, _edge in enumerate(transfer_edges):
        if isinstance(_edge, dict) and "_inputOrder" not in _edge:
            _edge["_inputOrder"] = _edge_order
    entries_by_public_for_transfer = entries_by_public_lookup_key(entries)
    known_param_counts = parameter_counts_by_public_lookup_key(
        entries, details_by_public_key)
    solved = record_map_from_details(entries, details_by_public_key)

    # C6g5w1d: only recursive SCC members reached by the proved closure-key
    # metadata shapes bypass generic whole-summary materialization.  Every
    # untagged SCC member remains on the established C6g5s import solver.
    tagged_direct_solved = canonical_record_map_from_details(
        entries, details_by_public_key)
    tagged_nodes, _tagged_family_ids, _tagged_closure_keys = (
        recursive_closure_tagged_nodes_and_families(
            transfer_edges, recursive_nodes, scc_of))

    # A non-recursive caller such as p126's ``run`` may have a stale C1
    # report-expanded summary even though its direct-local base is empty.  When
    # it receives a C6g5w1d-tagged solved callee, seed downstream propagation
    # from that immutable direct-local base once, rather than joining the tagged
    # result with the stale report tree.  This reverse reachability is confined
    # to callers of tagged SCC members; untagged components keep the established
    # C6g5s record-map behavior byte-for-byte.
    tagged_downstream_nodes: set[str] = set(tagged_nodes)
    changed_downstream = True
    while changed_downstream:
        changed_downstream = False
        for _edge in transfer_edges:
            if same_recursive_scc_for_edge(_edge, scc_of, recursive_nodes):
                continue
            _caller = str(_edge.get("callerNode") or "")
            _callee = str(_edge.get("calleeNode") or "")
            if _caller and _callee in tagged_downstream_nodes and _caller not in tagged_downstream_nodes:
                tagged_downstream_nodes.add(_caller)
                changed_downstream = True

    # Import-authoritative project summaries retain the established C6g5s
    # full path materialization for all untagged SCC roots.  The tagged path
    # solver below writes the normal solvedParamSummaries channel, not the
    # C6g5v display-only canonical overlay.
    intra_considered, intra_changed, simple_paths = solve_recursive_scc_by_simple_paths_for_import(
        solved, transfer_edges, recursive_nodes, scc_of, algebra=algebra,
        known_param_counts=known_param_counts, excluded_roots=tagged_nodes)

    tagged_stats = solve_tagged_recursive_scc_by_closure_key_paths_for_import(
        tagged_direct_solved, transfer_edges, recursive_nodes, scc_of,
        algebra=algebra, known_param_counts=known_param_counts)
    for _node in tagged_stats["taggedNodes"]:
        for _idx, _rec in tagged_direct_solved.get(_node, {}).items():
            solved.setdefault(_node, {})[int(_idx)] = dict(_rec)
    _annotate_tagged_recursive_closure_consumption(
        transfer_edges, tagged_stats["consumedFamilyIds"])

    considered = intra_considered + int(tagged_stats["consideredEdges"])
    changed_edges = intra_changed + int(tagged_stats["changed"])
    simple_paths += int(tagged_stats["paths"])
    cross_considered = 0
    cross_changed = 0
    iterations = 0
    converged = True
    rebased_tagged_downstream_slots: set[tuple[str, int]] = set()

    # Cross-SCC/downstream propagation.  Use the already-solved SCC summaries
    # as facts, then push them to callers such as h and k.  Same-SCC edges were
    # handled by the simple-path solver above and are not recursively substituted.
    for iteration in range(max_iterations):
        if max_seconds and (time.monotonic() - start_time) > max_seconds:
            stopped_by_time_limit = True
            iterations = iteration
            converged = False
            break
        changed = False
        for edge in transfer_edges:
            caller_key = str(edge.get("callerNode") or "")
            callee_key = str(edge.get("calleeNode") or "")
            if not caller_key or not callee_key:
                continue
            if same_recursive_scc_for_edge(edge, scc_of, recursive_nodes):
                continue
            try:
                caller_idx = int(edge.get("callerParamIndex"))
                callee_idx = int(edge.get("calleeParamIndex"))
            except Exception:
                continue

            callee_rec = solved.get(callee_key, {}).get(callee_idx)
            if not callee_rec:
                continue
            path_obj = edge.get("actualPathFromCallerParam") if isinstance(edge.get("actualPathFromCallerParam"), dict) else {}
            path_ir = path_obj.get("ir") if isinstance(path_obj, dict) else None
            stripped_path_ir = strip_callwrap_ir(path_ir)
            callee_solver_ir = callee_rec.get("solverIr")
            if callee_solver_ir is None:
                callee_solver_ir = algebra.semantic_core(callee_rec.get("ir"))

            # C6g4o2: restore C6g4c project-index specialization of symbolic
            # higher-order references such as $0.$1.  The C++ summary exporter
            # records the uniquely resolved function-valued actual in
            # ``resolvedHigherOrderActuals`` on this edge; substitute the
            # callback target's already-solved parameter summary before
            # composing this data-argument transfer.  This is a replacement,
            # not another candidate arm, and unresolved/multi-target callbacks
            # retain the pre-specialization path.
            specialized_callee_solver_ir, saw_hof_ref, all_hof_refs_resolved = (
                substitute_unique_higher_order_refs_for_edge(
                    callee_solver_ir, edge, solved, known_param_counts))
            higher_order_specialized = saw_hof_ref and all_hof_refs_resolved
            if higher_order_specialized:
                callee_solver_ir = specialized_callee_solver_ir

            candidate_solver_ir = algebra.compose(stripped_path_ir, callee_solver_ir)
            candidate_solver_ir = make_guarded_ir(candidate_solver_ir, edge.get("guard"))
            candidate_solver_ir = algebra.limit_parallel(candidate_solver_ir)

            callee_entry = unique_public_entry_for_edge_node(edge, callee_key, entries_by_public_for_transfer)
            if should_preserve_transfer_wrapper(edge, callee_entry, scc_of, recursive_nodes):
                candidate_ir = report_domain_transfer_ir(edge, callee_rec, callee_key, path_ir)
                if higher_order_specialized:
                    specialized_report_ir, report_saw_hof_ref, report_all_hof_refs_resolved = (
                        substitute_unique_higher_order_refs_for_edge(
                            candidate_ir, edge, solved, known_param_counts))
                    if report_saw_hof_ref and report_all_hof_refs_resolved:
                        candidate_ir = specialized_report_ir
                if edge_is_field_function_pointer_transfer(edge):
                    # C6a1: field-function-pointer display arms should follow
                    # caller source order (ops.parse(x) before ops.emit(x)).
                    # The metadata is report-only and ignored by obs_ir_key().
                    candidate_ir = attach_display_order_to_ir(
                        candidate_ir, edge, source="field-function-pointer-callsite")
                candidate_ir = make_guarded_ir(candidate_ir, edge.get("guard"))
                candidate_ir = algebra.limit_parallel(candidate_ir)
            else:
                candidate_ir = candidate_solver_ir
            if candidate_ir is None or candidate_solver_ir is None:
                continue

            higher_order_trace: list[dict[str, Any]] = []
            if higher_order_specialized:
                higher_order_trace.append({
                    "kind": "resolved-higher-order-callback-specialization",
                    "calleeFunction": callee_key,
                    "calleeParamIndex": callee_idx,
                    "bindings": unique_higher_order_bindings_for_edge(edge),
                    "note": "substituted uniquely resolved higher-order callback target before project parameter transfer",
                })

            callee_trace = trace_clone(callee_rec.get("projectTrace"))
            if callee_trace:
                candidate_trace = trace_extend(
                    higher_order_trace, trace_step_transfer(edge, stripped_path_ir), *callee_trace)
            else:
                candidate_trace = trace_extend(
                    higher_order_trace, trace_step_transfer(edge, stripped_path_ir),
                    trace_step_imported_callee(callee_rec, callee_key, callee_idx))

            # C6g5w1d's tagged SCC result is authoritative for an identity
            # forwarding caller with no direct-local contribution.  Rebase that
            # one downstream slot exactly once; subsequent fixed-point rounds
            # still join all of its ordinary C2 candidates normally.
            downstream_slot = (caller_key, caller_idx)
            if (caller_key in tagged_downstream_nodes and
                    downstream_slot not in rebased_tagged_downstream_slots):
                direct_rec = tagged_direct_solved.get(caller_key, {}).get(caller_idx)
                direct_base = (direct_rec.get("projectBaseIr") if direct_rec
                               else None)
                if direct_rec and not has_local_contribution(direct_base):
                    solved.setdefault(caller_key, {})[caller_idx] = dict(direct_rec)
                rebased_tagged_downstream_slots.add(downstream_slot)

            old_rec = solved.setdefault(caller_key, {}).get(caller_idx)
            old_ir = old_rec.get("ir") if old_rec else None
            old_solver_ir = old_rec.get("solverIr") if old_rec else None
            if old_solver_ir is None and old_ir is not None:
                old_solver_ir = algebra.semantic_core(old_ir)

            joined_solver_ir = algebra.limit_parallel(algebra.join(old_solver_ir, candidate_solver_ir))
            joined_ir = origin_aware_join_report_ir(old_ir, candidate_ir, candidate_solver_ir, algebra, edge)
            if joined_ir is None or joined_solver_ir is None:
                continue
            cross_considered += 1
            considered += 1
            if old_rec and obs_ir_key(normalize_ir(old_rec.get("ir"))) == obs_ir_key(joined_ir):
                if candidate_trace and not old_rec.get("projectTrace"):
                    old_rec["projectTrace"] = candidate_trace
                old_rec.setdefault("solverIr", joined_solver_ir)
                continue

            if old_rec and old_ir is not None and obs_ir_key(normalize_ir(joined_ir)) != obs_ir_key(normalize_ir(candidate_ir)):
                project_trace = [{
                    "kind": "join",
                    "oldSummary": render_ir(old_ir),
                    "newCandidate": render_ir(candidate_ir),
                    "joinedSummary": render_ir(joined_ir),
                    "oldSolverSummary": render_ir(old_solver_ir),
                    "newSolverCandidate": render_ir(candidate_solver_ir),
                    "joinedSolverSummary": render_ir(joined_solver_ir),
                    "note": "multiple downstream transfer candidates were joined; report-domain arms preserve call wrappers/origins while solver-domain summaries remain wrapper-free",
                }]
            else:
                project_trace = candidate_trace

            solved[caller_key][caller_idx] = {
                "index": caller_idx,
                "rendered": render_ir(joined_ir),
                "ir": joined_ir,
                "solverIr": joined_solver_ir,
                "projectBaseIr": old_rec.get("projectBaseIr") if old_rec else strip_callwrap_ir(old_ir),
                "source": "project-param-transfer-fixpoint",
                "bounded": False,
                "projectTraceKind": "downstream-transfer",
                "projectTrace": project_trace,
                "projectExplanationStopReasons": trace_stop_reasons(project_trace),
            }
            changed = True
            changed_edges += 1
            cross_changed += 1
        if not changed:
            iterations = iteration + 1
            converged = True
            break
    else:
        iterations = max_iterations
        converged = False

    # C6g5v display-only canonical overlay.  This map starts from the explicit
    # directLocalSummary companion field, never alters `solved`, and is stored
    # under canonicalProjectParamHistories rather than solvedParamSummaries.
    canonical_solved = canonical_record_map_from_details(entries, details_by_public_key)
    canon_intra_considered, canon_intra_changed, canon_simple_paths = (
        solve_recursive_scc_by_simple_paths(
            canonical_solved, transfer_edges, recursive_nodes, scc_of,
            algebra=algebra, known_param_counts=known_param_counts))
    canon_cross_considered, canon_cross_changed, canon_iterations = (
        propagate_canonical_project_histories(
            canonical_solved, transfer_edges, recursive_nodes, scc_of,
            algebra=algebra, max_iterations=max_iterations))

    count = 0
    for entry in entries:
        key = str(entry.get("publicLookupKey") or public_lookup_key(entry))
        records = solved.get(key, {})
        canonical_records = canonical_records_for_index(
            canonical_solved, key, recursive_nodes)
        if not records and not canonical_records:
            continue
        out = []
        for i in sorted(records):
            rec = dict(records[i])
            trace = trace_clone(rec.get("projectTrace"))
            if trace:
                rec["explanation"] = trace
                rec["explanationStopReasons"] = trace_stop_reasons(trace)
            trace_kind = rec.get("projectTraceKind")
            if trace_kind:
                rec["explanationKind"] = trace_kind
            solver_ir = rec.pop("solverIr", None)
            if solver_ir is not None:
                rec["semanticCoreIr"] = solver_ir
                rec["semanticCoreRendered"] = render_ir(solver_ir)
            rec.pop("projectBaseIr", None)
            rec.pop("projectSegments", None)
            rec.pop("projectTrace", None)
            rec.pop("projectTraceKind", None)
            rec.pop("projectExplanationStopReasons", None)
            if key in recursive_nodes:
                rec.setdefault("source", "recursive-scc-materialized")
                rec.setdefault("bounded", True)
            out.append(rec)
        entry["solvedParamSummaries"] = out
        # Display-only C6g5v canonical records.  SummaryIndex import readers
        # deliberately do not consume this field.
        entry["canonicalProjectParamHistories"] = canonical_records
        count += 1

    return {
        "numFunctions": count,
        "iterations": iterations,
        "converged": converged,
        "consideredTransferEdges": considered,
        "changedTransferEdges": changed_edges,
        "intraSCCTransferEdgesConsidered": intra_considered,
        "intraSCCTransferEdgesChanged": intra_changed,
        "crossSCCTransferEdgesConsidered": cross_considered,
        "crossSCCTransferEdgesChanged": cross_changed,
        "transferEdgeFilter": transfer_edge_filter_stats,
        "recursiveSCCFunctions": len(recursive_nodes),
        "maxIterations": max_iterations,
        "maxSameSCCSeqAtoms": max_same_scc_atoms,
        "maxSeconds": max_seconds,
        "stoppedByTimeLimit": stopped_by_time_limit,
        "intraSCCTransfersSkipped": False,
        "simpleSCCPathsEnumerated": simple_paths,
        "recursiveClosureKey": {
            "enabled": bool(tagged_stats["taggedNodes"]),
            "taggedRecursiveNodes": sorted(tagged_stats["taggedNodes"]),
            "consumedFamilyIds": sorted(tagged_stats["consumedFamilyIds"]),
            "consumedClosureKeys": sorted(tagged_stats["consumedClosureKeys"]),
            "consideredEdges": int(tagged_stats["consideredEdges"]),
            "changedRoots": int(tagged_stats["changed"]),
            "paths": int(tagged_stats["paths"]),
            "closureKeyStops": int(tagged_stats["closureKeyStops"]),
            "seededGuardedTransformerClosures": int(
                tagged_stats["seededGuardedTransformerClosures"]),
            "scope": (
                "Only parallel-call-actuals and guarded-local-ptrarith branch "
                "families inside recursive SCCs consume recursiveClosureKey; "
                "untagged SCC roots remain on the established C6g5s solver."
            ),
        },
        "widening": "tagged-recursive-closure-key-simple-paths-plus-untagged-c6g5s-simple-paths-plus-cross-scc-transfer-fixpoint",
        "algebraVersion": algebra.version,
        "summaryAlgebra": algebra.metadata(),
        "canonicalDisplay": {
            "intraSCCTransferEdgesConsidered": canon_intra_considered,
            "intraSCCTransferEdgesChanged": canon_intra_changed,
            "crossSCCTransferEdgesConsidered": canon_cross_considered,
            "crossSCCTransferEdgesChanged": canon_cross_changed,
            "iterations": canon_iterations,
            "simpleSCCPathsEnumerated": canon_simple_paths,
            "note": "display-only; excluded from solvedParamSummaries import channel",
        },
    }



def build_solved_param_summary_debug(entries: list[dict[str, Any]],
                                     solved_stats: dict[str, Any]) -> dict[str, Any]:
    """Return human-oriented debug metadata for materialized solved summaries.

    This is intentionally explanatory.  The authoritative machine-readable
    solved facts remain the per-function ``solvedParamSummaries`` arrays.
    The debug section records why those facts exist and how to interpret the
    trailing ``void *`` that appears at recursive SCC call boundaries.
    """
    functions: list[dict[str, Any]] = []
    num_param_records = 0
    num_recursive_scc_functions = 0
    num_downstream_functions = 0
    num_explained_param_records = 0

    for entry in entries:
        solved = entry.get("solvedParamSummaries")
        if not isinstance(solved, list) or not solved:
            continue
        records = []
        recursive = False
        downstream = False
        for rec in solved:
            if not isinstance(rec, dict):
                continue
            num_param_records += 1
            source = str(rec.get("source") or "")
            if source in {"recursive-scc-materialized", "project-intra-scc-simple-path-fixpoint"} or rec.get("bounded"):
                recursive = True
            if source == "project-param-transfer-fixpoint":
                downstream = True
            explanation = rec.get("explanation") if isinstance(rec.get("explanation"), list) else []
            if explanation:
                num_explained_param_records += 1
            records.append({
                "index": rec.get("index"),
                "rendered": rec.get("rendered") or "<none>",
                "source": source or "unknown",
                "bounded": bool(rec.get("bounded", False)),
                "explanationKind": rec.get("explanationKind") or "unknown",
                "explanationStepCount": len(explanation),
                "stopReasons": rec.get("explanationStopReasons") if isinstance(rec.get("explanationStopReasons"), list) else [],
                "explanation": explanation,
            })
        if recursive:
            num_recursive_scc_functions += 1
        if downstream:
            num_downstream_functions += 1
        functions.append({
            "function": entry.get("function") or "",
            "qualifiedName": entry.get("qualifiedName") or entry.get("function") or "",
            "signatureKey": entry.get("signatureKey") or "",
            "publicLookupKey": entry.get("publicLookupKey") or public_lookup_key(entry),
            "sourceFile": entry.get("sourceFile") or "",
            "solvedParams": records,
        })

    algebra_meta = solved_stats.get("summaryAlgebra") if isinstance(solved_stats.get("summaryAlgebra"), dict) else {}
    return {
        "purpose": "Explain materialized solvedParamSummaries with per-parameter derivation traces, without replacing final cast-history-tool reporting.",
        "authoritativeFacts": "functions[*].solvedParamSummaries",
        "algorithm": solved_stats.get("widening") or "project-level parameter-summary solver",
        "algebraVersion": solved_stats.get("algebraVersion") or algebra_meta.get("version") or "unknown",
        "summaryAlgebra": algebra_meta,
        "interpretation": {
            "recursiveSCC": (
                "For recursive SCC members, solvedParamSummaries summarize one bounded simple SCC path. "
                "The path stops before replaying the root function parameter's local contribution."
            ),
            "downstream": (
                "For acyclic/downstream callers, solvedParamSummaries are propagated from already-solved callees "
                "through exported summaryParamTransferEdges."
            ),
            "terminalVoidPointer": (
                "A trailing '=> void *' can be intentional: it records the SCC call-boundary erasure when a value "
                "is passed back into a void* formal and the solver stops before starting the next SCC lap."
            ),
            "perParameterExplanation": (
                "Each solved parameter record may include an explanation array. Steps describe local/base contributions, "
                "summaryParamTransferEdges, imported solved callee summaries, joins, and stop reasons."
            ),
            "structuredAlgebra": (
                "C4O names the project-level algebra operations explicitly. The solver still stores ordinary IR under "
                "solvedParamSummaries[*].ir for compatibility, while solvedParamSummaryDebug.summaryAlgebra documents "
                "the normalize/semantic-core/compose/join/bound operations used to produce it."
            ),
            "finalReporting": (
                "The project index computes solved summary facts only. Final text output, entity/storage histories, "
                "pointer metrics, and behavior classifications are still produced by cast-history-tool in the final import pass."
            ),
        },
        "counts": {
            "functionsWithSolvedParams": len(functions),
            "solvedParamRecords": num_param_records,
            "explainedParamRecords": num_explained_param_records,
            "recursiveSCCFunctions": num_recursive_scc_functions,
            "downstreamFunctions": num_downstream_functions,
            "simpleSCCPathsEnumerated": solved_stats.get("simpleSCCPathsEnumerated", 0),
        },
        "functions": functions,
    }


