def nonvoid_pointer_keys_in_ir(ir: Any) -> list[str]:
    items = flatten_seq(ir)
    if items is None:
        return []
    out: list[str] = []
    for item in items:
        k = nonvoid_pointer_repeat_key(item)
        if k is not None:
            out.append(k)
    return out


def seq_len_or_large(ir: Any) -> int:
    items = flatten_seq(ir)
    if items is None:
        return 1000000
    return len(items)


def ir_has_nonvoid_pointer(ir: Any) -> bool:
    return bool(nonvoid_pointer_keys_in_ir(ir))


def ir_is_only_void_connectors(ir: Any) -> bool:
    ir = normalize_ir(ir)
    if ir is None:
        return True
    items = flatten_seq(ir)
    if items is None:
        return False
    if not items:
        return True
    return not any(nonvoid_pointer_repeat_key(item) is not None for item in items)


@dataclass(frozen=True)
class ProjectSummaryAlgebra:
    """Named algebra operations for project-level summary solving.

    The index builder uses a smaller project-solving domain than the final
    cast-history report domain.  This class makes that domain explicit without
    changing the existing C4M/C4d-3 semantics:

      * call wrappers are provenance in the report domain, but are stripped in
        the project solver's semantic core;
      * sequential composition preserves void* call-boundary connectors;
      * repeated concrete pointer types are allowed;
      * recursive SCC expansion is bounded by simple transfer paths, not by
        string suffix trimming or type-repeat deletion;
      * parallel arms are limited only as a safety bound.

    The methods intentionally delegate to the existing IR helpers so this patch
    is a structural refactor and a debugging aid rather than a semantic rewrite.
    """

    version: str = "C4O-structured-project-summary-algebra"
    domain: str = "project-solver-semantic-core"
    max_same_scc_atoms: int = 16
    max_parallel_arms: int = 8

    @classmethod
    def from_env(cls, *, max_same_scc_atoms: int = 16, max_parallel_arms: int = 8) -> "ProjectSummaryAlgebra":
        return cls(
            max_same_scc_atoms=env_int("CAST_HISTORY_SOLVED_PARAM_MAX_SEQ_ATOMS", max_same_scc_atoms),
            max_parallel_arms=env_int("CAST_HISTORY_SOLVED_PARAM_MAX_PARALLEL_ARMS", max_parallel_arms),
        )

    def normalize(self, ir: Any) -> Any:
        return normalize_ir(ir)

    def semantic_core(self, ir: Any) -> Any:
        return strip_callwrap_ir(ir)

    def bound_same_scc(self, ir: Any) -> Any:
        return widen_same_scc_ir(ir, max_atoms=self.max_same_scc_atoms)

    def compose(self, prefix: Any, suffix: Any) -> Any:
        return compose_project_ir(prefix, suffix)

    def join(self, a: Any, b: Any) -> Any:
        return join_guard_aware_ir(a, b)

    def limit_parallel(self, ir: Any) -> Any:
        return limit_parallel_arms_ir(normalize_ir(ir), max_arms=self.max_parallel_arms)

    def representative(self, old_ir: Any, new_ir: Any) -> Any:
        return better_path_ir(old_ir, new_ir)

    def render(self, ir: Any) -> str:
        return render_ir(ir)

    def metadata(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "domain": self.domain,
            "reportDomain": "materialized solvedParamSummaries.ir preserves call wrappers/guards/provenance for final reporting",
            "solverDomain": "wrapper-stripped semantic core tracked separately as semanticCoreIr for convergence",
            "maxSameSCCSeqAtoms": self.max_same_scc_atoms,
            "maxParallelArms": self.max_parallel_arms,
            "operations": {
                "normalize": "normalize seq/parallel/join forms and remove empty summaries",
                "semanticCore": "strip callWrap nodes for project solving only",
                "compose": "sequentially compose path summaries while preserving void* call-boundary connectors",
                "join": "join downstream alternatives and prefer prefix-extending evidence when possible",
                "boundSameSCC": "bound sequence length for safety; do not remove repeated concrete pointer types",
                "representative": "choose the bounded simple SCC path with richer non-void/sequential evidence",
            },
            "cycleControl": {
                "sameSCC": "bounded simple paths over summaryParamTransferEdges",
                "repetitionUnit": "function-parameter nodes and transfer-edge provenance, not concrete pointer type text",
                "rootStop": "when an edge returns to the root parameter, keep the call-boundary path and stop before replaying the root local contribution",
            },
            "terminalVoidPointer": (
                "A trailing '=> void *' may be intentional: it records an SCC call-boundary erasure "
                "when the path returns to a void* formal and the solver stops before the next SCC lap."
            ),
        }


def suffix_after_prefix_ir(whole: Any, prefix: Any) -> Any:
    whole_items = flatten_seq(whole)
    prefix_items = flatten_seq(prefix)
    if whole_items is None:
        return normalize_ir(whole)
    if prefix_items is None or not prefix_items:
        return normalize_ir(whole)
    if len(prefix_items) <= len(whole_items) and all(
        obs_ir_key(a) == obs_ir_key(b) for a, b in zip(prefix_items, whole_items)
    ):
        return normalize_ir(rebuild_seq(whole_items[len(prefix_items):]))
    return normalize_ir(whole)


