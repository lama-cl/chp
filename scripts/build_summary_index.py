@dataclass
class Issue:
    severity: str
    file: str
    message: str


def load_json(path: Path) -> tuple[dict[str, Any] | None, str | None]:
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="replace"))
    except Exception as exc:
        return None, f"failed to parse JSON: {exc}"
    if not isinstance(data, dict):
        return None, f"top-level JSON must be object, got {type(data).__name__}"
    return data, None


def validate_tu_summary_schema(data: dict[str, Any], path: Path) -> str | None:
    schema_name = data.get("schemaName")
    if schema_name not in SUPPORTED_TU_SUMMARY_SCHEMAS:
        return (f"unsupported TU summary schemaName {schema_name!r}; "
                "expected cast-history-tu-link-summary or legacy "
                "cast-history-tu-summary")
    return None


def canonical_history_key(summary: Any) -> str:
    """Stable return-alias key component for link summaries without rendered text."""
    if not isinstance(summary, dict):
        return ""
    rendered = summary.get("rendered")
    if isinstance(rendered, str) and rendered:
        return rendered
    ir = summary.get("ir")
    if ir is None:
        return ""
    try:
        return json.dumps(ir, sort_keys=True, separators=(",", ":"))
    except Exception:
        return ""


def stable_relpath(path: Path, base: Path) -> str:
    try:
        return path.resolve().relative_to(base.resolve()).as_posix()
    except Exception:
        return path.as_posix()


def summary_input_fingerprint(files: list[Path]) -> str:
    """Return a stable content fingerprint for one index build input.

    The fingerprint intentionally uses summary-file bytes rather than rendered
    report text generated by this script.  It is a conservative reuse gate:
    a match proves the builder would receive identical input; a mismatch only
    causes a normal rebuild.  This keeps reuse safe even while rich histories
    and project algebra evolve.
    """
    digest = hashlib.sha256()
    for path in sorted(files, key=lambda x: x.resolve().as_posix()):
        resolved = path.resolve().as_posix().encode("utf-8", errors="surrogateescape")
        digest.update(len(resolved).to_bytes(8, "big"))
        digest.update(resolved)
        try:
            payload = path.read_bytes()
        except OSError as exc:
            payload = f"<unreadable:{exc}>".encode("utf-8", errors="replace")
        digest.update(len(payload).to_bytes(8, "big"))
        digest.update(payload)
    return digest.hexdigest()


def summary_input_bytes(files: list[Path]) -> int:
    total = 0
    for path in files:
        try:
            total += path.stat().st_size
        except OSError:
            pass
    return total


def reusable_index_matches(path: Path, fingerprint: str) -> bool:
    data, err = load_json(path)
    if err or not isinstance(data, dict):
        return False
    meta = data.get("buildMetadata")
    if not isinstance(meta, dict):
        return False
    return str(meta.get("inputSummaryFingerprint") or "") == fingerprint


def find_summary_files(paths: list[Path]) -> list[Path]:
    files: list[Path] = []
    for path in paths:
        if path.is_file():
            if path.name != "project-summary-index.json":
                files.append(path)
        elif path.is_dir():
            for p in sorted(path.rglob("*.cast-summary.json")):
                if p.name != "project-summary-index.json":
                    files.append(p)
        else:
            print(f"warning: path does not exist: {path}", file=sys.stderr)
    seen: set[Path] = set()
    out: list[Path] = []
    for f in files:
        r = f.resolve()
        if r not in seen:
            seen.add(r)
            out.append(f)
    return out


def default_output_path(paths: list[Path]) -> Path:
    if len(paths) == 1 and paths[0].is_dir():
        return paths[0] / "project-summary-index.json"
    return Path("project-summary-index.json")


def normalize_linkage(x: Any) -> str:
    return x if isinstance(x, str) and x else "unknown"


def location_key(loc: Any) -> str:
    if not isinstance(loc, dict):
        return ""
    return f"{loc.get('file','')}:{loc.get('line','')}:{loc.get('column','')}"


def lookup_key(entry: dict[str, Any]) -> str:
    qn = entry.get("qualifiedName") or entry.get("function") or ""
    sig = entry.get("signatureKey") or ""
    linkage = entry.get("linkage") or "unknown"
    if linkage in INTERNAL_LINKAGES:
        return f"internal::{entry.get('sourceFile','')}::{qn}::{sig}"
    return f"external::{qn}::{sig}"


def public_lookup_key(entry: dict[str, Any]) -> str:
    return f"{entry.get('qualifiedName') or entry.get('function') or ''}::{entry.get('signatureKey') or ''}"


def extract_function_details(summary: dict[str, Any]) -> list[dict[str, Any]]:
    details = summary.get("functionSummaryDetails")
    if isinstance(details, list):
        return [x for x in details if isinstance(x, dict)]
    compact = summary.get("functionSummaries")
    if isinstance(compact, list):
        return [x for x in compact if isinstance(x, dict)]
    return []


def extract_entry(detail: dict[str, Any], summary_file: Path, summary_root: Path,
                  tu_source: str, tu_config: str, tu_hash: str,
                  issues: list[Issue]) -> dict[str, Any] | None:
    ident = detail.get("identity") if isinstance(detail.get("identity"), dict) else {}
    function = detail.get("function") if isinstance(detail.get("function"), str) else ""
    if not function and isinstance(ident.get("name"), str):
        function = ident["name"]
    if not function:
        issues.append(Issue("warning", str(summary_file), "skipping function summary with missing function name"))
        return None

    name = ident.get("name") if isinstance(ident.get("name"), str) and ident.get("name") else function
    qualified = ident.get("qualifiedName") if isinstance(ident.get("qualifiedName"), str) and ident.get("qualifiedName") else function
    signature = ident.get("signatureKey") if isinstance(ident.get("signatureKey"), str) else ""
    linkage = normalize_linkage(ident.get("linkage"))
    source_file = ident.get("sourceFile") if isinstance(ident.get("sourceFile"), str) and ident.get("sourceFile") else tu_source
    loc = ident.get("location") if isinstance(ident.get("location"), dict) else {}
    if not loc and isinstance(detail.get("location"), dict):
        loc = detail["location"]

    if not signature:
        issues.append(Issue("warning", str(summary_file), f"function {function!r} has missing signatureKey"))
    if linkage == "unknown":
        issues.append(Issue("warning", str(summary_file), f"function {function!r} has unknown linkage"))

    param_declared_types: list[str] = []
    raw_params = detail.get("params")
    if isinstance(raw_params, list):
        for raw_param in raw_params:
            if not isinstance(raw_param, dict):
                continue
            idx = raw_param.get("index")
            if not isinstance(idx, int) or idx < 0:
                continue
            while len(param_declared_types) <= idx:
                param_declared_types.append("")
            declared = raw_param.get("declaredType")
            if isinstance(declared, str):
                param_declared_types[idx] = declared

    entry = {
        "function": function,
        "name": name,
        "qualifiedName": qualified,
        "signatureKey": signature,
        "linkage": linkage,
        "sourceFile": source_file,
        "location": loc,
        "summaryFile": stable_relpath(summary_file, summary_root),
        "tuSourceFile": tu_source,
        "tuConfigurationId": tu_config,
        "tuCompileCommandHash": tu_hash,
        "functionBehavior": detail.get("functionBehavior", ""),
        "paramDeclaredTypes": param_declared_types,
    }
    entry["lookupKey"] = lookup_key(entry)
    entry["publicLookupKey"] = public_lookup_key(entry)
    entry["locationKey"] = location_key(loc)
    entry["status"] = "unambiguous"
    entry["resolution"] = RESOLUTION_FOR_STATUS["unambiguous"]
    return entry


def status_counts(entries: list[dict[str, Any]], field: str) -> dict[str, int]:
    counts: dict[str, int] = {}
    for e in entries:
        v = str(e.get(field, "unknown"))
        counts[v] = counts.get(v, 0) + 1
    return dict(sorted(counts.items()))




def normalize_summary_dependency_edge(edge: dict[str, Any], summary_file: Path,
                                      summary_root: Path, tu_source: str,
                                      tu_config: str, tu_hash: str) -> dict[str, Any]:
    """Return a project-index edge enriched with TU provenance.

    C4a deliberately keeps these as dependency facts, not SCC results.  Later
    C4b/C4c patches can build a graph/SCC solver from this merged array.
    """
    out = dict(edge)
    out["summaryFile"] = stable_relpath(summary_file, summary_root)
    out["tuSourceFile"] = tu_source
    out["tuConfigurationId"] = tu_config
    out["tuCompileCommandHash"] = tu_hash

    caller = out.get("callerQualifiedName") or out.get("caller") or ""
    callee = out.get("calleeQualifiedName") or out.get("callee") or ""
    caller_sig = out.get("callerSignatureKey") or ""
    callee_sig = out.get("calleeSignatureKey") or ""
    kind = out.get("kind") or "unknown"
    loc = out.get("location") if isinstance(out.get("location"), dict) else {}
    loc_key = location_key(loc)

    out["callerNode"] = f"{caller}::{caller_sig}" if caller_sig else str(caller)
    if callee_sig:
        out["calleeNode"] = f"{callee}::{callee_sig}"
    else:
        out["calleeNode"] = str(callee)
    out["edgeKey"] = "::".join([
        str(kind), out["callerNode"], out["calleeNode"], str(out.get("via") or ""), loc_key
    ])
    return out


def extract_summary_dependency_edges(summary: dict[str, Any], summary_file: Path,
                                     summary_root: Path, tu_source: str,
                                     tu_config: str, tu_hash: str,
                                     issues: list[Issue]) -> list[dict[str, Any]]:
    raw = summary.get("summaryDependencyEdges")
    if raw is None:
        return []
    if not isinstance(raw, list):
        issues.append(Issue("warning", str(summary_file), "summaryDependencyEdges is not an array"))
        return []
    out: list[dict[str, Any]] = []
    for i, edge in enumerate(raw):
        if not isinstance(edge, dict):
            issues.append(Issue("warning", str(summary_file), f"summaryDependencyEdges[{i}] is not an object"))
            continue
        out.append(normalize_summary_dependency_edge(edge, summary_file, summary_root,
                                                     tu_source, tu_config, tu_hash))
    return out


def normalize_summary_param_transfer_edge(edge: dict[str, Any], summary_file: Path,
                                          summary_root: Path, tu_source: str,
                                          tu_config: str, tu_hash: str) -> dict[str, Any]:
    """Normalize a C4H caller-param -> callee-param transfer fact."""
    out = dict(edge)
    out["summaryFile"] = stable_relpath(summary_file, summary_root)
    out["tuSourceFile"] = tu_source
    out["tuConfigurationId"] = tu_config
    out["tuCompileCommandHash"] = tu_hash

    caller = out.get("callerQualifiedName") or out.get("caller") or ""
    callee = out.get("calleeQualifiedName") or out.get("callee") or ""
    caller_sig = out.get("callerSignatureKey") or ""
    callee_sig = out.get("calleeSignatureKey") or ""
    out["callerNode"] = out.get("callerNode") or (f"{caller}::{caller_sig}" if caller_sig else str(caller))
    out["calleeNode"] = out.get("calleeNode") or (f"{callee}::{callee_sig}" if callee_sig else str(callee))

    loc = out.get("location") if isinstance(out.get("location"), dict) else {}
    loc_key = location_key(loc)
    out["edgeKey"] = "::".join([
        "param-transfer", str(out.get("callerNode") or ""),
        str(out.get("calleeNode") or ""),
        str(out.get("callerParamIndex", "")),
        str(out.get("calleeParamIndex", "")), loc_key,
    ])
    return out


