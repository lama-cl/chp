    callee_nodes = sorted({str(e.get("calleeNode", "")) for e in edges if e.get("calleeNode")})
    full_nodes, full_unique_edges = dependency_graph_nodes_and_edges(edges, concrete_only=False)
    concrete_nodes, concrete_unique_edges = dependency_graph_nodes_and_edges(edges, concrete_only=True)
    concrete_raw_edges = [e for e in edges if is_concrete_dependency_edge(e)]
    symbolic_raw_edges = [e for e in edges if not is_concrete_dependency_edge(e)]
    return {
        "numEdges": len(edges),
        "numRawEdges": len(edges),
        "numUniqueEdges": len(full_unique_edges),
        "numConcreteEdges": len(concrete_raw_edges),
        "numSymbolicEdges": len(symbolic_raw_edges),
        "numConcreteUniqueEdges": len(concrete_unique_edges),
        "numSymbolicUniqueEdges": len(full_unique_edges - concrete_unique_edges),
        "numCallerNodes": len(caller_nodes),
        "numCalleeNodes": len(callee_nodes),
        "numFullGraphNodes": len(full_nodes),
        "numConcreteGraphNodes": len(concrete_nodes),
        "kindCounts": dependency_edge_kind_counts(edges),
        "uniqueEdges": aggregate_unique_dependency_edges(edges, concrete_only=False),
        "uniqueConcreteEdges": aggregate_unique_dependency_edges(edges, concrete_only=True),
    }



