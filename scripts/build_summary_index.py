def is_symbolic_summary_node(node: Any) -> bool:
    """Return true for symbolic callback/formal nodes such as $0.

    C4a records both concrete function nodes (name::signature) and symbolic
    higher-order nodes ($0).  SCC solving later needs both views, but the
    concrete function graph should exclude symbolic callback placeholders.
    """
    text = str(node or "")
    return (not text) or text.startswith("$") or text.startswith("<")


def is_concrete_dependency_edge(edge: dict[str, Any]) -> bool:
    caller = edge.get("callerNode") or edge.get("caller") or ""
    callee = edge.get("calleeNode") or edge.get("callee") or ""
    return (not is_symbolic_summary_node(caller)
            and not is_symbolic_summary_node(callee)
            and bool(edge.get("callerSignatureKey"))
            and bool(edge.get("calleeSignatureKey")))


def graph_edge_key(edge: dict[str, Any]) -> tuple[str, str]:
    return (str(edge.get("callerNode") or edge.get("caller") or ""),
            str(edge.get("calleeNode") or edge.get("callee") or ""))


def dependency_graph_nodes_and_edges(edges: list[dict[str, Any]], *, concrete_only: bool) -> tuple[set[str], set[tuple[str, str]]]:
    nodes: set[str] = set()
    graph_edges: set[tuple[str, str]] = set()
    for edge in edges:
        if concrete_only and not is_concrete_dependency_edge(edge):
            continue
        src, dst = graph_edge_key(edge)
        if not src or not dst:
            continue
        if concrete_only and (is_symbolic_summary_node(src) or is_symbolic_summary_node(dst)):
            continue
        nodes.add(src)
        nodes.add(dst)
        graph_edges.add((src, dst))
    return nodes, graph_edges


def aggregate_unique_dependency_edges(edges: list[dict[str, Any]], *, concrete_only: bool) -> list[dict[str, Any]]:
    grouped: dict[tuple[str, str], dict[str, Any]] = {}
    for edge in edges:
        if concrete_only and not is_concrete_dependency_edge(edge):
            continue
        src, dst = graph_edge_key(edge)
        if not src or not dst:
            continue
        if concrete_only and (is_symbolic_summary_node(src) or is_symbolic_summary_node(dst)):
            continue
        key = (src, dst)
        g = grouped.setdefault(key, {
            "callerNode": src,
            "calleeNode": dst,
            "count": 0,
            "kinds": {},
            "sites": [],
            "summaryFiles": set(),
            "tuSourceFiles": set(),
            "concrete": is_concrete_dependency_edge(edge),
            "symbolic": is_symbolic_summary_node(src) or is_symbolic_summary_node(dst),
        })
        g["count"] += 1
        kind = str(edge.get("kind", "unknown"))
        g["kinds"][kind] = g["kinds"].get(kind, 0) + 1
        if edge.get("summaryFile"):
            g["summaryFiles"].add(str(edge.get("summaryFile")))
        if edge.get("tuSourceFile"):
            g["tuSourceFiles"].add(str(edge.get("tuSourceFile")))
        loc = edge.get("location") if isinstance(edge.get("location"), dict) else {}
        loc_key = location_key(loc)
        if loc_key:
            g["sites"].append({
                "kind": kind,
                "location": loc,
                "via": edge.get("via", ""),
                "calleeExpr": edge.get("calleeExpr", ""),
            })
    out: list[dict[str, Any]] = []
    for g in grouped.values():
        item = dict(g)
        item["kinds"] = dict(sorted(item["kinds"].items()))
        item["summaryFiles"] = sorted(item["summaryFiles"])
        item["tuSourceFiles"] = sorted(item["tuSourceFiles"])
        item["sites"] = sorted(item["sites"], key=lambda s: (str(s.get("kind", "")),
                                                              location_key(s.get("location", {})),
                                                              str(s.get("via", ""))))
        out.append(item)
    out.sort(key=lambda e: (e.get("callerNode", ""), e.get("calleeNode", "")))
    return out


def tarjan_scc(nodes: set[str], edges: set[tuple[str, str]]) -> list[list[str]]:
    adjacency: dict[str, list[str]] = {n: [] for n in nodes}
    for src, dst in edges:
        adjacency.setdefault(src, []).append(dst)
        adjacency.setdefault(dst, [])
    for n in adjacency:
        adjacency[n].sort()

    index = 0
    stack: list[str] = []
    on_stack: set[str] = set()
    indices: dict[str, int] = {}
    lowlink: dict[str, int] = {}
    components: list[list[str]] = []

    def strongconnect(v: str) -> None:
        nonlocal index
        indices[v] = index
        lowlink[v] = index
        index += 1
        stack.append(v)
        on_stack.add(v)

        for w in adjacency.get(v, []):
            if w not in indices:
                strongconnect(w)
                lowlink[v] = min(lowlink[v], lowlink[w])
            elif w in on_stack:
                lowlink[v] = min(lowlink[v], indices[w])

        if lowlink[v] == indices[v]:
            comp: list[str] = []
            while True:
                w = stack.pop()
                on_stack.remove(w)
                comp.append(w)
                if w == v:
                    break
            components.append(sorted(comp))

    for n in sorted(adjacency):
        if n not in indices:
            strongconnect(n)

    # Deterministic order: nontrivial SCCs first, then singleton components.
    components.sort(key=lambda c: (0 if len(c) > 1 else 1, c[0] if c else ""))
    return components


def build_scc_report(edges: list[dict[str, Any]], *, concrete_only: bool) -> dict[str, Any]:
    """Build SCC metadata plus C6g5s edge-topology facts.

    The C++ import solver must distinguish a local-only recursive component
    (already closed by the C1 same-TU two-phase solver) from a real project
    component containing at least one imported direct-call edge.  This remains
    index metadata only: Python does not execute the C++ SCC solver.
    """
    nodes, unique_edges = dependency_graph_nodes_and_edges(edges, concrete_only=concrete_only)
    components = tarjan_scc(nodes, unique_edges)
    edge_set = set(unique_edges)
    component_items: list[dict[str, Any]] = []
    node_to_component: dict[str, int] = {}
    for idx, comp in enumerate(components):
        has_self_loop = any((n, n) in edge_set for n in comp)
        recursive = len(comp) > 1 or has_self_loop
        item = {
            "sccId": idx,
            "members": comp,
            "size": len(comp),
            "recursive": recursive,
            "selfLoop": has_self_loop,
            # Filled below from raw concrete edges.  These fields are useful
            # even for a nonrecursive component and make the schema uniform.
            "concreteEdgeCount": 0,
            "localEdgeCount": 0,
            "importedEdgeCount": 0,
            "translationUnits": [],
        }
        component_items.append(item)
        for n in comp:
            node_to_component[n] = idx

    # Preserve raw-edge multiplicity because a component can contain several
    # call sites for one graph edge.  `crossTUCandidate` is produced by the
    # visitor at the call site: it is true precisely when the direct callee has
    # no definition in the current translation unit and is eligible for import.
    component_tus: dict[int, set[str]] = {i: set() for i in range(len(component_items))}
    for edge in edges:
        if concrete_only and not is_concrete_dependency_edge(edge):
            continue
        src, dst = graph_edge_key(edge)
        if not src or not dst:
            continue
        src_scc = node_to_component.get(src)
        dst_scc = node_to_component.get(dst)
        if src_scc is None or src_scc != dst_scc:
            continue
        item = component_items[src_scc]
        item["concreteEdgeCount"] += 1
        if bool(edge.get("crossTUCandidate", False)):
            item["importedEdgeCount"] += 1
        else:
            item["localEdgeCount"] += 1
        tu = str(edge.get("tuSourceFile") or "")
        if tu:
            component_tus[src_scc].add(tu)

    for idx, item in enumerate(component_items):
        item["translationUnits"] = sorted(component_tus[idx])

    nontrivial = [c for c in component_items if c.get("recursive")]
    return {
        "graphKind": "concrete-function" if concrete_only else "full-summary",
        "numNodes": len(nodes),
        "numUniqueEdges": len(unique_edges),
        "numSCCs": len(component_items),
        "numNontrivialSCCs": len(nontrivial),
        "components": component_items,
        "nontrivialComponents": nontrivial,
        "nodeToScc": dict(sorted(node_to_component.items())),
        "edgeTopologyVersion": 1,
    }


def dependency_scc_summary(edges: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "fullGraph": build_scc_report(edges, concrete_only=False),
        "concreteFunctionGraph": build_scc_report(edges, concrete_only=True),
    }


