"""
Build a project-level function-summary index from compact per-TU cast-history
link summaries.

C6g5e consumes only `cast-history-tu-link-summary` interchange artifacts.
Legacy monolithic `cast-history-tu-summary` files remain accepted during
migration; verbose `cast-history-tu-report` sidecars are deliberately rejected.

Typical use for a real linked project:
  python3 scripts/build_summary_index.py summaries

For a directory of independent standalone examples:
  python3 scripts/build_summary_index.py json-summaries --project-kind example-suite
"""
